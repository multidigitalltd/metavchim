-- חתימת שם לאיתור כרטיסים כפולים.
--
-- ה-phone_hash מונע כפילות על *אותו* מספר, אבל אדם עם שני מספרים
-- (נייד וטלפון בית) מקבל שני כרטיסים — ומאותו רגע חצי מההיסטוריה
-- שלו יושבת בכרטיס אחד וחצי בשני.
--
-- למה חתימה ולא השוואת שמות: השמות מוצפנים במסד, ואי אפשר להשוות
-- אותם בשאילתה. HMAC של השם המנורמל מאפשר למצוא התאמה מדויקת על
-- מאגר שלם בשאילתה אחת, בלי לפענח דבר ובלי לחשוף PII.
--
-- NULL מותר: השדה מתמלא בכתיבה הבאה ובסריקת השלמה שרצה בעובד.
-- מיגרציה אינה יכולה למלא אותו — ההצפנה יושבת בשכבת האפליקציה.
ALTER TABLE contacts ADD COLUMN name_hash CHAR(64);

-- אינדקס חלקי: השאילתה מחפשת קבוצות בעלות אותה חתימה, ושורות בלי
-- חתימה אינן מועמדות ואין טעם שיתפסו מקום באינדקס.
CREATE INDEX contacts_name_hash_idx ON contacts (tenant_id, name_hash)
  WHERE name_hash IS NOT NULL;
