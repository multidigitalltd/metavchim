-- שלמות ההסכם החתום — שני תיקונים מביקורת Codex על שער ההחתמה.

-- 1) הגיבוב שהוצג ללקוח *לפני* החתימה.
--
-- מספר הזהות של החותם נכנס לגוף המסמך ברגע החתימה (התקנות דורשות
-- שההזמנה בכתב תכלול את מספרי הזיהוי של הצדדים), ולכן הנוסח משתנה
-- בדיוק אז. body_hash מעיד מעכשיו על מה שנחתם, והעמודה הזו שומרת את
-- מה שהוצג — כך אפשר להוכיח את שניהם ולא רק אחד מהם.
ALTER TABLE agreements ADD COLUMN presented_hash CHAR(64);

-- 2) הסכם פעיל אחד לכל (לקוח, סוג, נכס).
--
-- הקוד ניסה למחזר הסכם ממתין קיים, אבל הבדיקה והיצירה לא היו
-- אטומיות: שתי בקשות במקביל ראו "אין שורה" ויצרו שני מסמכים עם שני
-- טוקנים שונים. כיוון שנעילת החתימה מותנית בשורה, שני המסמכים היו
-- ניתנים לחתימה בנפרד — כלומר שתי חתימות על אותה הזמנה.
--
-- COALESCE ולא property_id ישירות: ב-Postgres שני NULL אינם שווים,
-- ואינדקס ייחודי רגיל לא היה מונע כפילות בהסכם ללא נכס.
CREATE UNIQUE INDEX agreements_active_unique
  ON agreements (tenant_id, contact_id, kind, COALESCE(property_id, ''))
  WHERE status IN ('pending', 'viewed');
