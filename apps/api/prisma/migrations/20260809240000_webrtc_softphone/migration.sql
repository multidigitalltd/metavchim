-- קו ה-SIP האישי של הסוכן — לסופטפון בדפדפן.
--
-- הקו הוא **של האדם ולא של המשרד**: שיחה נכנסת צריכה לצלצל אצל מי
-- שהיא מיועדת לו, ושיחה יוצאת צריכה לצאת ממנו. קו משרדי אחד לכולם
-- היה מחזיר אותנו בדיוק לבעיה שחיוג בלחיצה בא לפתור — מי שבמקרה
-- הרים מדבר עם הלקוח של מישהו אחר.
ALTER TABLE users ADD COLUMN sip_username VARCHAR(80);

-- הסיסמה מוצפנת כמו כל סוד אחר במערכת. היא כן מגיעה לדפדפן בזמן
-- הרישום — אין דרך אחרת ב-SIP over WebSocket — אבל היא לא יושבת
-- בבסיס הנתונים בטקסט גלוי, ולא נשלחת לאף משתמש אחר.
ALTER TABLE users ADD COLUMN sip_password_encrypted TEXT;
