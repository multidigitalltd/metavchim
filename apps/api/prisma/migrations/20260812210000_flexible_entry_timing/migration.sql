-- מועד כניסה/מסירה גמיש.
--
-- עד כה השדה היה תאריך בלבד, ולכן "מיידי", "גמיש" ו"בתיאום עם
-- השוכר" — הרוב המוחלט של הנכסים בשוק — נאלצו להתחפש ליום מסוים
-- בלוח. הסוכן המציא תאריך, ומנוע ההתאמות התייחס אליו כאילו הוא
-- אמיתי. המצב הוא השדה; התאריך נלווה אליו רק כשיש כזה.
ALTER TABLE properties ADD COLUMN entry_type VARCHAR(20);
ALTER TABLE properties ADD COLUMN entry_note VARCHAR(160);

-- נכסים קיימים עם תאריך: התאריך פירושו "מסירה בתאריך", וזה בדיוק
-- `on_date`. בלי הגזירה הזו כל המאגר הקיים היה מאבד את קריטריון
-- המסירה ואת נקודות המוכנות עליו ביום העלייה לאוויר.
UPDATE properties SET entry_type = 'on_date' WHERE entry_date IS NOT NULL;
