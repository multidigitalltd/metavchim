-- הפקעת קרדיטים שפג תוקפם — תנועה שלילית עם kind='expiry' ו-ref_id
-- שמצביע על התנועה החיובית (המנה) שפגה.
--
-- האינדקס החלקי הוא **מנגנון הבטיחות של הכסף**: שני עותקי API
-- שסורקים במקביל היו כותבים שתי הפקעות לאותה מנה, כלומר מוחקים
-- אותה יתרה פעמיים. ייחודיות ברמת המסד הופכת את זה לבלתי אפשרי
-- במקום לתלות את הנכונות בתזמון. ref_id הוא ULID של שורת המנה,
-- ייחודי בפני עצמו, ולכן אין צורך ב-tenant_id במפתח.
CREATE UNIQUE INDEX IF NOT EXISTS credit_ledger_expiry_once
  ON credit_ledger (ref_id)
  WHERE kind = 'expiry';
