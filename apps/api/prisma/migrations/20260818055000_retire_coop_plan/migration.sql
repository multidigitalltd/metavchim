-- העברת משרדים ממסלול השת"פ שהוסר מהקטלוג המובנה.
--
-- ## למה הגירה ולא בדיקה ידנית
--
-- `PlanCatalogService.forTenant` פותר את המסלול לפי הקוד השמור על
-- המשרד. ברגע שהמסלול המובנה נעלם מהקוד, משרד שנשאר משויך אליו
-- מקבל `undefined` — כלומר **בלי אף פיצ'ר**, ויצירת נכס ופרסום
-- לרשת נופלים ב„המסלול של המשרד אינו מוגדר”.
--
-- „לבדוק לפני הפריסה” אינו מעבר אטומי: בין הבדיקה למשיכת הגרסה
-- אפשר להירשם, והתמונה שנבדקה כבר אינה נכונה. ההגירה רצה בתוך
-- אותה טרנזקציה של הפריסה ולכן אין בה חלון כזה (ביקורת Codex).
--
-- ## מה מועבר
--
-- ארבעה מקומות, בדיוק כמו זרימת `deletePlan` שכבר קיימת במסך
-- הפלטפורמה — כל אחד מהם היה שובר משהו אחר אילו נשכח:
--
--   * `tenants.plan`          — השער עצמו
--   * `subscriptions.plan_code` — מה ש-RenewalService מתמחר לפיו.
--     מסלול שאינו מוכר מדולג בשקט, כלומר לקוח משלם מפסיק להתחדש
--     בזמן שהמשרד שלו נראה תקין לגמרי.
--   * `coupons.plan_code`     — קופון שהוגבל למסלול שנעלם
--   * `tenants.coupon_plan_code` — ההנחה שכבר הובטחה בהרשמה
--
-- ## היעד
--
-- `basic` — ברירת המחדל של העמודה `tenants.plan`, והמסלול המובנה
-- הזול ביותר שנשאר. מסלול בתשלום ולא חינמי הוא הבחירה השמרנית:
-- משרד שקיבל בטעות גישה רחבה מדי מתגלה בשיחה, ומשרד שנחסם בטעות
-- מתגלה בתקלה שהוא חווה.
UPDATE "tenants" SET "plan" = 'basic' WHERE "plan" = 'coop';
UPDATE "subscriptions" SET "plan_code" = 'basic' WHERE "plan_code" = 'coop';
UPDATE "coupons" SET "plan_code" = 'basic' WHERE "plan_code" = 'coop';
UPDATE "tenants" SET "coupon_plan_code" = 'basic' WHERE "coupon_plan_code" = 'coop';

-- שורת קטלוג שנשמרה ב-DB עבור המסלול (אם מישהו ערך אותו במסך)
-- מסומנת כפרושה. בלי זה המיזוג ב-`PlanCatalogService.all` היה
-- מחזיר אותה לחיים כמסלול זמין — כלומר המסלול היה נמחק מהקוד
-- וממשיך להופיע במסך.
UPDATE "plans" SET "retired_at" = NOW() WHERE "code" = 'coop' AND "retired_at" IS NULL;
