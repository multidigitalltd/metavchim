-- שליטת הפלטפורמה במשרד יחיד: פיצ'רים ומחיר, מעל המסלול.
--
-- ## למה בכלל
--
-- המסלול הוא ברירת מחדל מסחרית, לא גזירה. משרד שסוגר עסקה מיוחדת,
-- לקוח ראשון שמקבל תוספת, פיילוט על תכונה אחת — כל אלה קורים לפני
-- שיש מסלול שמתאים להם, והחלופה היום היא ליצור מסלול חדש לכל חריג
-- עד שהקטלוג הופך לרשימת לקוחות.
--
-- ## הכיוונים
--
-- שתי רשימות ולא אחת עם סימנים: `feature_grants` פותחת תכונה שאינה
-- במסלול, `feature_denials` סוגרת תכונה שכן בו. הפרדה מפורשת הופכת
-- את השאלה "מה חריג כאן" לקריאה של שתי עמודות, ומאפשרת לשנות מסלול
-- בלי לאבד את החריגים שהוסכמו.
--
-- **דחייה גוברת על הענקה.** לא בגלל סדר מקרי אלא כדי שסגירה תהיה
-- ודאית: מי שסוגר תכונה למשרד — בגלל חוב, שימוש לרעה או תקלה —
-- חייב שהסגירה תחזיק גם אם אותה תכונה הוענקה קודם ונשכחה.
--
-- ## המחיר
--
-- שתי עמודות ולא אחת: מחיר חודשי ומחיר שנתי אינם נגזרים זה מזה
-- (עסקה שנתית היא הנחה, לא כפל ב-12), ועמודה אחת הייתה מחייבת לנחש
-- לאיזה מחזור היא מתייחסת. NULL = אין חריגה, כלומר מחיר המסלול.
--
-- הערך חייב להיות חיובי. "חינם למשרד הזה" אינו מחיר אפס אלא
-- הארכת חלון החינם (`trial_ends_at` / `paid_until`) — סכום אפס היה
-- נשלח לסולק כחיוב על אפס, וזו בקשה שנדחית. כך גם כל מנגנון עושה
-- דבר אחד: המחיר קובע כמה גובים, החלון קובע אם גובים בכלל.
ALTER TABLE "tenants"
  ADD COLUMN "feature_grants" TEXT[] NOT NULL DEFAULT '{}',
  ADD COLUMN "feature_denials" TEXT[] NOT NULL DEFAULT '{}',
  ADD COLUMN "price_override_monthly_agorot" INTEGER,
  ADD COLUMN "price_override_yearly_agorot" INTEGER;
