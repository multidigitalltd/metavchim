-- שם המספר הווירטואלי כפי שהיה ברגע השיחה — **צילום, לא הפניה**.
--
-- ההגדרה של מספר יכולה להימחק או לשנות שם, וההיסטוריה לא אמורה
-- להשתנות איתה. בלי הצילום, מחיקת קמפיין שהסתיים הייתה הופכת את כל
-- השיחות שהגיעו ממנו ל"מספר לא מוגדר" — כלומר מאבדת בדיוק את
-- המידע שבשבילו התכונה קיימת: מאיפה הגיע הלקוח הזה.
--
-- ‎`ON DELETE SET NULL`‎ על הגדרת המספר אינו פותר את זה: הוא שומר על
-- שלמות ההפניה, לא על משמעות ההיסטוריה.
ALTER TABLE "calls" ADD COLUMN "dialed_label" VARCHAR(60);

-- מילוי לאחור לשיחות שכבר נקלטו: השם הנוכחי של המספר, כשקיים.
-- זה הדבר הנכון ביותר שאפשר לדעת בדיעבד — ומכאן והלאה הצילום
-- נעשה ברגע השיחה.
UPDATE "calls" c
   SET "dialed_label" = v."label"
  FROM "virtual_numbers" v
 WHERE v."tenant_id" = c."tenant_id"
   AND v."phone" = c."dialed_number"
   AND c."dialed_number" IS NOT NULL;
