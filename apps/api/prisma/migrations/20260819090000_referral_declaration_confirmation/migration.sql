-- הצהרת המפנה, אישור הקולט, ומוניטין שמודד דיוק.
--
-- המודל הקודם היה דירוג הדדי **אחרי** ההפניה: כל צד נותן ציון
-- לשני. שני פערים בו:
--
-- 1. המשרד הקולט לא ידע דבר על הלקוח **לפני** ששילם. הוא ראה ציון
--    ממוצע של המשרד המפנה, שאינו אומר כלום על ההפניה שלפניו.
-- 2. המוניטין נבנה מ"כמה הלקוח היה טוב", כלומר העניש משרד שהצהיר
--    ביושר על לקוח בינוני ותגמל את מי שהיה לו מזל.
--
-- כאן: המפנה מצהיר על איכות הלקוח ברגע הפרסום, ההצהרה מוצגת בלוח
-- לפני התשלום, והקולט מאשר את אותם ממדים מניסיון ישיר. המוניטין
-- הוא **הפער בין השניים** — דבר שבשליטת המפנה במלואו.

-- ההצהרה יושבת על ההפניה ולא בטבלת הדירוגים: היא חלק מהמודעה.
ALTER TABLE "shared_leads" ADD COLUMN "client_scores" JSONB NOT NULL DEFAULT '{}';

-- הדירוג של המפנה על הקולט יורד. הוא לא נמדד מול דבר, לא הוצג
-- לאיש מחוץ לשני הצדדים, ואין לו מקום במודל שבו יש הצהרה אחת
-- ואישור אחד.
DELETE FROM "lead_referral_ratings" WHERE "rater_role" = 'referrer';
ALTER TABLE "lead_referral_ratings" DROP COLUMN "rater_role";

-- האישורים שנשארו הם ציוני **איכות**, ו-`score_tenths` מייצג
-- מעכשיו ציון **דיוק**. אין ממה לגזור דיוק לשורות האלה: אין להן
-- הצהרה להשוות אליה, כי השדה נולד עכשיו.
--
-- לכן הן נמחקות והמוניטין מתאפס, ולא מומרות. המרה הייתה שומרת
-- מספרים שנראים תקינים ומודדים דבר אחר — וזה גרוע מלהתחיל מאפס,
-- כי אי אפשר לזהות את זה בהסתכלות.
DELETE FROM "lead_referral_ratings";
