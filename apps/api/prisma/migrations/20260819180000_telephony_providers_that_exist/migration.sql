-- שני ספקי מרכזייה בקטלוג, ושניהם ממומשים.
--
-- Zadarma ו-Voicenter היו **שם בלבד**: אף שורת קוד לא קראה את הטוקן
-- או את מפתח ה-API שלהם, וקליטת השיחות ממילא אינה תלוית ספק. מי
-- שבחר בהם קיבל בדיוק את "מרכזייה כללית (Webhook)" — אחרי שמסר לנו
-- אישורי גישה שנשמרו מוצפנים ולא שימשו לדבר.
--
-- החיבורים הקיימים עוברים ל-`generic`, שהוא מה שהם היו בפועל:
-- כתובת ה-Webhook, מפתח הקליטה ויומן האירועים נשארים כמו שהם,
-- והשיחות ממשיכות להיכנס בלי שהמשרד יגע בדבר.
UPDATE "integrations"
   SET "provider" = 'generic',
       /*
        * והסודות נמחקים.
        *
        * אלה אישורי גישה למרכזייה של המשרד — מפתח API או טוקן —
        * שמעולם לא נקראו ואין להם עוד מקום להיקרא בו. שמירה שלהם
        * "ליום שבו יהיה מימוש" היא בדיוק ההצטברות שתקן אבטחת מידע
        * בא למנוע: מידע רגיש שנשמר בלי מטרה פעילה.
        *
        * העמודה מוגדרת NULL-able, ו-`readSecrets` מטפל ב-NULL
        * כבאין-סודות. המשרד יזין מחדש אם וכאשר יהיה מה להזין.
        */
       "secrets_encrypted" = NULL
 WHERE "kind" = 'telephony'
   AND "provider" IN ('zadarma', 'voicenter');

