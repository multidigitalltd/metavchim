 * ה-`config` נשאר. הוא מכיל שדות גלויים בלבד (שלוחה, מזהה מתקשר),
 * שאינם סוד ואינם מזיקים — ומחיקתם הייתה מוחקת גם הגדרה שהמשרד
 * הקליד ידנית ועשוי לרצות לראות. הספק הגנרי פשוט מתעלם ממה שאינו
 * מכיר.
 */
