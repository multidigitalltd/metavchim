-- „חינם” ו„בהתאמה” הם שתי הבטחות, לא אחת.
--
-- עד כה שתיהן נגזרו מאותו נתון: `monthly_price_agorot = 0`. התוצאה
-- הייתה שמסלול השת"פים החינמי — שכל הרעיון שלו הוא שאין בו מה
-- לשלם — הוצג ללקוח כ„בהתאמה”, כלומר „דבר איתנו על המחיר”. ההפך
-- הגמור ממה שהוא.
--
-- אפס יכול להיות „אין מחיר” ויכול להיות „לא נקבע מחיר”. הדגל הזה
-- אומר במפורש מי מהם, ואינו ניתן להסקה.
ALTER TABLE "plans"
  ADD COLUMN "price_on_request" BOOLEAN NOT NULL DEFAULT false;

/*
 * מסלול הרשת הוא היחיד שנסגר בשיחה — ולכן הזיהוי הוא לפי הקוד
 * שלו בלבד.
 *
 * הפיתוי היה לזהות לפי `is_public = false` ומחיר אפס, כלומר „לא
 * נמכר בכרטיס אשראי ולא הוזן לו מחיר”. זו הייתה חזרה על אותה
 * שגיאה בדיוק: מסלול השת"פים החינמי אינו בקטלוג המובנה אלא נוצר
 * ידנית ב-/platform, ואיננו יודעים מכאן אם סומן ציבורי. אילו לא
 * סומן, הכלל ההוא היה מסמן דווקא אותו כ„בהתאמה” — ומייצר שוב את
 * התקלה שהמיגרציה הזו באה לתקן.
 *
 * כל שאר השורות מקבלות את ברירת המחדל `false`. מסלול נוסף שנסגר
 * בשיחה מסומן ידנית בתיבה שבמסך המסלולים, ולא בהיסק ממספר.
 */
UPDATE "plans"
   SET "price_on_request" = true
 WHERE "code" = 'enterprise'
   AND "retired_at" IS NULL;
