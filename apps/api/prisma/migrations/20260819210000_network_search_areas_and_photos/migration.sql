-- ביקוש ברשת: איפה הקונה מחפש — גם כשהאזור סומן על המפה.
--
-- עד כה הועתקו לרשת הערים והשכונות בלבד. קונה שסימן אזור על המפה
-- ולא הקליד עיר התפרסם בלי שום אזור, ומשרד שראה את המודעה לא ידע
-- לאן להציע — כלומר בדיוק ההפך ממה שהרשת נועדה לעשות.
--
-- העמדה נשמרת כ-JSON ולא בעמודות: זו רשימה של נקודות עם רדיוס,
-- והיא נקראת כמקשה אחת לתצוגה ולחישוב מרחק.
--
-- **זה אינו מידע מזהה.** הנקודה מתארת איפה הלקוח מחפש לקנות, לא
-- איפה הוא גר, והיא בדיוק מה שהצד השני צריך כדי להחליט אם יש לו
-- נכס מתאים.
ALTER TABLE "shared_demands"
  ADD COLUMN "search_areas" JSONB NOT NULL DEFAULT '[]'::jsonb;

