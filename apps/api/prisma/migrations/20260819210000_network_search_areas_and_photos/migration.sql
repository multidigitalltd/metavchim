 * חדרים, שטח, קומה, מצב, מחיר ומועד — ולא כלל תמונה אחת. מתווך
 * אינו מציע נכס ללקוח שלו על סמך טבלה, והתוצאה הייתה שהפיד נקרא
 * ולא הופעל.
 *
 * מפתחות S3 ולא כתובות: הקישור נחתם בזמן הצפייה וחייו קצרים,
 * וכתובת חתומה ששמורה בטבלה הייתה פגה ומשאירה תמונה שבורה.
 *
 * הכתובת המדויקת ופרטי הבעלים ממשיכים לא להיות כאן — התמונות אינן
 * מרחיבות את מה שנחשף, הן מציגות את מה שכבר מותר.
 */
