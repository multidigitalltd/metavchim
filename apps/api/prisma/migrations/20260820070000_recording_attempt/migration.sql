-- מתי ניסינו למשוך את ההקלטה בפעם האחרונה.
--
-- בלי העמודה הזו סבב המשיכה בחר בכל פעם את אותן שורות: כישלון אינו
-- משנה דבר בשורה, ולכן שיחה עם נתיב פגום או אישורים שפגו הייתה
-- נבחרת שוב ושוב ותופסת את מכסת הסבב — עד שתזדקן שבוע, ובינתיים כל
-- שאר ההקלטות של אותו משרד אינן נמשכות כלל, וייתכן שהספק כבר מחק
-- אותן.
--
-- החותמת נכתבת על **כל** ניסיון, מוצלח או לא, והמיון הוא „מי שלא
-- נוסה מזמן ביותר קודם”. כך כישלון עיקש יורד לסוף התור במקום לחסום
-- אותו.
ALTER TABLE calls ADD COLUMN IF NOT EXISTS provider_recording_attempt_at TIMESTAMP(3);

-- אינדקס חלקי על מה שהסבב באמת שולף: שיחות שיש להן נתיב אצל הספק
-- ואין להן עדיין מפתח אצלנו. זו קבוצה קטנה מאוד מתוך טבלת השיחות,
-- ובלי האינדקס כל סבב היה סורק את הטבלה כולה לכל משרד.
CREATE INDEX IF NOT EXISTS calls_recording_pending_idx
  ON calls (tenant_id, provider_recording_attempt_at NULLS FIRST, occurred_at)
  WHERE provider_recording_path IS NOT NULL AND recording_key IS NULL;
