-- ניסוח משימת הליד-ללא-מענה בלי ז'רגון: "חלון ה-SLA חלף" הוחלף
-- בעברית פשוטה (דיווח המשתמש). הקבוע בקוד משנה רק משימות חדשות —
-- משימות שכבר נוצרו ממשיכות להציג את הניסוח הישן, כי האסקלציה
-- מזהה אותן לפי source_key ולא נוגעת בהן שוב (ביקורת Codex).
--
-- מעדכנים לפי הכותרת המדויקת בלבד: משימה שהמתווך ערך ידנית לא
-- נדרסת, וגם משימות שהושלמו מקבלות את הניסוח החדש — הן מופיעות
-- בהיסטוריית הכרטיס ואותה בעיית בהירות חלה עליהן.
UPDATE tasks
SET title = 'לחזור לליד — מחכה יותר מדי זמן בלי מענה'
WHERE source_key LIKE 'lead-sla:%'
  AND title = 'ליד ממתין למענה — חלון ה-SLA חלף';
