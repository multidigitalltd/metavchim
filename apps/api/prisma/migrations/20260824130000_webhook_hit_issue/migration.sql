-- „התקבלה” נרשמה עד כה על ההגעה בלבד — מפתח תקין, חיבור פעיל, מודול
-- במסלול — ולא על מה שקרה אחר כך. אירוע שנזרק שנייה לאחר מכן מפני
-- שלא היה בו מספר טלפון נראה ביומן זהה לאירוע שהפך לשיחה, וזו בדיוק
-- השאלה שמחפשים ביומן כשלקוח התקשר ואין רישום.
--
-- NULL בשורות קיימות, וגם בכל שורה שנקלטה כרגיל: הסיבה קיימת רק
-- כשיש כישלון להסביר.
ALTER TABLE "telephony_webhook_hits" ADD COLUMN "issue" varchar(20);

