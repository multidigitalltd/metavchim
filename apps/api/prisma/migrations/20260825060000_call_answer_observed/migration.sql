-- ראיית מענה שאינה תלויה במשך, ושמירת ההבחנה „ניתוב נפתר”.
--
-- 015 שולחת `Calling` ⟵ `Answer` ⟵ `Hangup`. אירוע ה-`Answer` הוא
-- אמירה מפורשת של המרכזייה שהשיחה נענתה — ועד כה הוא נזרק: הוא אינו
-- מסיים שיחה, ולכן לא נכתב ממנו דבר.
--
-- כל עוד „כל מה שאינו „לא נענתה” נרשם „נענתה”” זה לא הזיק. מרגע
-- שמענה דורש ראיה, ניתוק שמגיע בלי `talktime` נרשם „לא ידוע” — ולא
-- פותח ליד ממספר לא מוכר — למרות שהמרכזייה כבר אמרה שהשיחה נענתה.
-- הראיה הייתה קיימת, ופשוט נזרקה באירוע קודם.
--
-- ‎`call_routings` היא כבר בדיוק המחברת הזו: מפתח `(tenant_id,
-- provider_call_id)`, נכתבת באירוע הראשון, נמחקת כששורת השיחה נכתבת,
-- ומנוקה לפי גיל. לכן העובדה נשמרת כאן ולא בטבלה חדשה.
ALTER TABLE "call_routings"
  ADD COLUMN "answer_observed" BOOLEAN NOT NULL DEFAULT false;

-- ‎**למה נדרשת עמודה שנייה.**
--
-- ‎`virtual_number_id IS NULL` פירושו „נצפה מספר, ולא התאים אף
-- הגדרה”, וקיום השורה הוא הנתון. שורה שנוצרת כדי לזכור מענה בלבד
-- הייתה נקראת אחר כך כדחייה ודאית, וה-`Hangup` — זה שנושא את המספר
-- אצל מרכזיות ששולחות אותו רק בסוף — לא היה פותר את הניתוב. כלומר
-- כל שיחה הייתה מאבדת את מקור הקמפיין, הנכס והסוכן.
--
-- ברירת המחדל היא `false` בכוונה: שורה שנוצרה בלי לסמן נפתרת שוב
-- בפעם הבאה — שאילתה מיותרת אחת. ברירת מחדל `true` הייתה משתיקה את
-- הניתוב בשקט, וזה הכיוון שאסור לטעות בו.
ALTER TABLE "call_routings"
  ADD COLUMN "route_resolved" BOOLEAN NOT NULL DEFAULT false;

-- השורות הקיימות נכתבו כולן אחרי התאמת מספר — כלומר הן פתורות.
-- הטבלה מחזיקה שיחות באוויר בלבד, ולכן זה עדכון של דקות ולא של
-- היסטוריה.
UPDATE "call_routings" SET "route_resolved" = true;
