-- הפרטים שחולצו מהשיחה נשמרים, במקום להימחק אחרי שחושבו.
--
-- ‎`summarizeCall` כבר מחלץ תקציב, חדרים, עיר ומועד חזרה — הוא
-- מחזיר `highlights`, יש לו בדיקות, והוא רץ על כל תמלול. אבל
-- העובד משתמש רק בשורת הסיכום המשוטחת ומוחק את המבנה:
-- ‎`const { summary } = parsedCall`. מה שנשאר הוא מחרוזת אחת שאי
-- אפשר לסנן לפיה, להשוות אותה או להזין ממנה שדה בכרטיס הקונה.
--
-- ‎**למה עמודה ולא חישוב מחדש בקריאה.** אפשר היה להריץ את החילוץ
-- שוב על התמלול השמור, אבל זה לא היה מחזיר את אותה תוצאה: העובד
-- מזין למסכם את הטקסט הנקי (`body.text`), בלי תוויות הדובר
-- וחותמות הזמן — והטקסט הנקי אינו נשמר בשום מקום. חישוב מחדש
-- מהתמלול המתויג היה שובר את אותם ביטויי מפתח שהמסכם מחפש.
--
-- וגם מעבר לכך: מה שחולץ בזמן השיחה הוא עובדה שהמערכת קבעה, ולא
-- מסקנה שנוח לגזור מחדש בכל טעינת מסך. שינוי עתידי בביטויי
-- החילוץ לא אמור לשנות למפרע מה נאמר בשיחה משבוע שעבר.
--
-- ברירת המחדל `{}` ולא `NULL`: „לא חולץ דבר” הוא מצב תקין ושכיח
-- (שיחה קצרה, תמלול שלא הופעל), והוא אינו „חסר מידע”. אותה
-- החלטה כמו ב-`voice_intakes.extracted_fields`, שהיא בדיוק אותה
-- צורה במנגנון אחר.
ALTER TABLE "calls"
  ADD COLUMN "highlights" JSONB NOT NULL DEFAULT '{}';

-- שורות קיימות נשארות `{}`. אין ניסיון למלא אותן למפרע: הטקסט
-- הנקי שהחילוץ צריך לא נשמר, ולהריץ אותו על התמלול המתויג היה
-- מייצר שדות שגויים בשקט — גרוע יותר משדות ריקים.
