-- מתי המשימה הושלמה בפועל.
--
-- כרטיס „משימות שהושלמו” מבטיח למתווך את התאריך והשעה שבהם היא
-- הושלמה, ועד כה הוצג `due_at` — כלומר **המועד שנקבע לה**. משימה
-- שהושלמה מוקדם הציגה תאריך עתידי, ומשימה בלי מועד לא הציגה דבר.
--
-- `updated_at` אינו תחליף: כל עריכה מאוחרת דורסת אותו, ואז השדה
-- מדווח מתי נגעו במשימה ולא מתי היא נגמרה.
--
-- NULL על שורות קיימות ובכוונה: לא רשמנו את הרגע הזה קודם, ואין
-- דרך לשחזר אותו. המסך אינו מציג זמן על שורה כזו, במקום לנחש.
ALTER TABLE "tasks" ADD COLUMN "completed_at" TIMESTAMP(3);
