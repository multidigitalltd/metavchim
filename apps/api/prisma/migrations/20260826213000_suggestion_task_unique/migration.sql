-- ערובה קשה לכפילות של „משימה מוצעת”, בלי לאסור כפילות לגיטימית.
--
-- בדיקת קיום לפני כתיבה מצמצמת חלון ואינה סוגרת אותו: שתי
-- טרנזקציות מקבילות יכולות שתיהן לקרוא „אין”, ואז שתיהן לכתוב.
-- שני סוכנים על אותו כרטיס הם תרחיש רגיל כאן, כי הפאנל מציג
-- במכוון את משימות כל המשרד.
--
-- ‎**האינדקס חלקי, ומצומצם למרחב `suggestion:` בלבד** — משתי סיבות:
--
-- 1. משימה שהוקלדה ביד נושאת `source_key = NULL`, ולכן שתי משימות
--    „להתקשר” על אותו כרטיס נשארות מותרות. זה שימוש אמיתי.
-- 2. מפתחות מערכת קיימים (`lead-sla:`, `offer:`) עלולים כבר להופיע
--    בכפילות בנתונים קיימים, ואינדקס רחב היה **נכשל ביצירה** על
--    מסד חי. מרחב ה-`suggestion:` נולד בשינוי הזה ולכן ריק בוודאות.
CREATE UNIQUE INDEX "tasks_open_suggestion_unique"
  ON "tasks" ("tenant_id", "entity_type", "entity_id", "source_key")
  WHERE "source_key" LIKE 'suggestion:%' AND "status" = 'open';
