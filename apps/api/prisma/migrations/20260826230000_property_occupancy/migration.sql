--
-- ‎**אין ברירת מחדל** כי כל ניחוש כאן ממציא עובדה. נכס בלי שוכר
-- רשום אינו „הבעלים גר בו” ואינו „ריק” — הוא נכס שאיש לא נשאל
-- עליו. מיגרציה שהייתה כותבת 'owner' לכל השורות הקיימות הייתה
-- יוצרת בדיוק את השקר שהשדה נועד להחליף.
--
-- ‎**ואין אינדקס** כי המיגרציות רצות לפני שה-API עולה (docs/10 §65),
-- ובניית אינדקס על טבלה חיה נועלת אותה לכתיבה למשך הבנייה. אף
-- שאילתה כאן אינה מסננת לפי העמודות האלה.
