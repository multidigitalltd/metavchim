-- מצב השליחה של תשובה יוצאת מהתיבה.
--
-- הסדר היה: שולחים ללקוח, ואז כותבים למסד. כשהכתיבה נכשלה — הלקוח
-- קיבל את ההודעה, ולמערכת לא נשאר ממנה **דבר**: לא בתיבה, לא בציר
-- הלקוח, ולא ביומן הביקורת. הסוכן ראה שגיאה, ניסה שוב, והלקוח קיבל
-- את אותה הודעה פעמיים (ביקורת Codex).
--
-- זו בדיוק אותה מחלקה שתוקנה בהצעות האוטומטיות, בכיוון ההפוך:
-- פעולה חיצונית בלתי הפיכה חייבת להיות עטופה ברשומה עמידה — נכתבת
-- לפניה, ומאושרת אחריה.
--
-- NULL על הודעות **נכנסות**: לא אנחנו שלחנו אותן, ואין להן מצב
-- שליחה. השדה חל על `direction = 'out'` בלבד.
ALTER TABLE "email_messages" ADD COLUMN "send_state" VARCHAR(10);

-- היוצאות שכבר במסד נשלחו בפועל — הן נכתבו רק אחרי שהספק קיבל.
UPDATE "email_messages" SET "send_state" = 'sent' WHERE "direction" = 'out';

-- מה שממתין או נכשל הוא מה שדורש מבט; אינדקס חלקי, לא על הכול.
CREATE INDEX "email_messages_tenant_id_send_state_idx"
  ON "email_messages" ("tenant_id", "send_state")
  WHERE "send_state" IS NOT NULL AND "send_state" <> 'sent';
