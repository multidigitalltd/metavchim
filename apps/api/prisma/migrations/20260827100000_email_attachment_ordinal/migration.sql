-- מקומו של הקובץ בהודעה — זהות יציבה שאינה תלויה בניסיון.
--
-- הקבצים נכתבים אחרי טרנזקציית ההודעה, ומסירה חוזרת של הספק ממשיכה
-- מהמקום שנעצר. אם הספק מוסר שוב **בזמן** שהמסירה הראשונה עדיין
-- מעלה — וזה בדיוק המצב שגורם למסירה חוזרת, בקשה שחרגה מפסק הזמן —
-- שתי הבקשות רואות את אותה תמונת מצב חלקית, ושתיהן מעלות ומכניסות
-- את אותם קבצים תחת מזהים שונים. התוצאה: כפילות בתיבה ובאחסון
-- (ביקורת Codex).
--
-- הזיהוי היה לפי שם וגודל, בהשוואה בזיכרון — כלומר הכרעה שנעשית
-- **אחרי** הקריאה ולכן חסרת ערך מול מרוץ. `ordinal` הופך אותה
-- לאילוץ במסד: המפתח נגזר מההודעה ומהמקום, שני הכותבים מחשבים את
-- אותו מפתח אחסון בדיוק, ו-`ON CONFLICT DO NOTHING` מכריע ביניהם.
--
-- NULL על שורות קיימות: הן נכתבו לפני העמודה. אינדקס ייחודי
-- ב-Postgres מתייחס ל-NULL כערכים שונים זה מזה, ולכן הן אינן
-- מתנגשות ואינן דורשות מילוי אחורה.
ALTER TABLE "email_attachments" ADD COLUMN "ordinal" INTEGER;

CREATE UNIQUE INDEX "email_attachments_tenant_id_message_id_ordinal_key"
  ON "email_attachments" ("tenant_id", "message_id", "ordinal");

-- ‏"נתבע" אינו "הועלה".
--
-- השורה נכתבת לפני ההעלאה והיא התביעה על המקום, ולכן קיומה אינו
-- מעיד שהאובייקט קיים. תהליך שנפל בין השתיים משאיר תביעה בלי קובץ —
-- ומסירה חוזרת שדילגה עליה כי המקום "תפוס" הותירה צירוף גלוי
-- שהורדתו נכשלת לנצח (ביקורת Codex).
--
-- העמודה מפרידה בין השתיים: NULL = נתבע וטרם הועלה, וערך = הושלם.
-- ‏‎`uploaded_at` הוא גם מה שקובע מה מוצג בשיחה: צירוף שטרם הועלה
-- אינו מופיע, במקום להופיע עם קישור שבור.
ALTER TABLE "email_attachments" ADD COLUMN "uploaded_at" TIMESTAMP(3);

-- השורות הקיימות נכתבו **אחרי** העלאה מוצלחת — הן הושלמו בהגדרה.
UPDATE "email_attachments" SET "uploaded_at" = "created_at";
