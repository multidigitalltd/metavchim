--
-- מחיקת משרד אוספת את מפתחות ה-S3 ואז מוחקת את השורות שמכירות אותם.
-- בין שני השלבים אין דבר שחוסם כתיבה, והעלאה שרצה במקביל מסתיימת
-- באחד משני סידורים — ושניהם משאירים קובץ של לקוח אחרי שהמשרד ביקש
-- להימחק (#258):
--
--   ה-COMMIT לפני האיסוף  ⟵ השורה נמחקת, המפתח לא נאסף, הקובץ נשאר
--   ה-COMMIT אחרי האיסוף  ⟵ גם השורה וגם הקובץ שורדים את המחיקה
--
-- זה חל על שבע טבלאות, לא על אחת: תמונות נכסים, הקלטות שיחה, צילומי
-- מסך של פניות, סריקות הסכמים, קבצי תיבת המייל, קבצי תיבת התמיכה,
-- ומפתח הלוגו שיושב ב-settings. כולן נושאות PII של לקוחות.
--
-- הדגל נקבע ונסגר בטרנזקציה **משלו**, לפני האיסוף, ו-
-- `StorageService.put` בודק אותו אחרי ההעלאה ומוחק את מה שהעלה אם
-- הוא נקבע בינתיים. הבדיקה ב-`put` ולא בכל נתיב בנפרד היא כל
-- הנקודה: זו נקודה אחת שכל העלאה עוברת בה, כולל טבלה שמינית שתיכתב
-- בעוד שנה בלי לזכור את הכלל הזה. המשטח כבר גדל מחמש לשבע מאז
-- שהנושא נכתב.
