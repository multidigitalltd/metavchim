-- הקבצים בתיבת התמיכה — אותה צורה שתיבת הלקוחות התכנסה אליה.
--
-- תיבת התמיכה נכתבה כהעתק של תיבת הלקוחות **לפני** שישה סבבי
-- ביקורת פירקו שם את מסלול הקבצים. מה שהיה כאן עד עכשיו:
--
--   העלאה ואז שורה   ⟵ תהליך שנפל ביניהן משאיר אובייקט בלי שורה,
--                       ומחיקת לקוח ומחיקת משרד עוברות על שורות —
--                       כלומר קובץ של אדם ששורד כל מחיקה
--   מזהה אקראי       ⟵ אין זהות יציבה, ולכן מסירה חוזרת אינה
--                       יכולה להמשיך מהמקום שנעצר
--   הכשל נבלע ב-200  ⟵ לספק אין סיבה למסור שוב
--   ומסירה חוזרת דילגה על הקבצים לגמרי — ההזדמנות האחרונה להשלים
--   אותם נזרקה
--
-- התוצאה: הפנייה נראית שלמה, והצילום שהלקוח צירף פשוט איננו.
--
-- ‏`ordinal` הוא מקומו של הקובץ בהודעה — זהות יציבה שאינה תלויה
-- בניסיון. שני כותבים מקבילים מחשבים את אותו מפתח אחסון בדיוק,
-- והאינדקס הייחודי מכריע ביניהם.
ALTER TABLE "support_attachments" ADD COLUMN "ordinal" INTEGER;

CREATE UNIQUE INDEX "support_attachments_message_id_ordinal_key"
  ON "support_attachments" ("message_id", "ordinal");

-- ‏"נתבע" אינו "הועלה".
--
-- השורה נכתבת **לפני** ההעלאה, וזו התכונה שסוגרת את חור המחיקה
-- מהשורש: אין אובייקט שנכתב בלי שורה שתמצא אותו. המחיר הוא שקיום
-- השורה אינו מעיד שהאובייקט קיים, ו-`uploaded_at` מפריד ביניהם:
-- NULL = נתבע וטרם הועלה, וערך = הושלם.
--
-- הוא גם מה שקובע מה מוצג בשרשור: צירוף שטרם הועלה אינו מופיע,
-- במקום להופיע עם קישור שבור.
--
-- ואין כאן חכירה ואין השתלטות. שתיהן נוסו בתיבת הלקוחות וילדו שתי
-- תקלות; המפתח דטרמיניסטי, ולכן העלאה חוזרת של אותם בתים לאותו
-- מפתח היא אידמפוטנטית — אין מה לתאם ואין למי לתת בעלות זמנית.
ALTER TABLE "support_attachments" ADD COLUMN "uploaded_at" TIMESTAMP(3);

-- השורות הקיימות נכתבו **אחרי** העלאה מוצלחת — הן הושלמו בהגדרה.
UPDATE "support_attachments" SET "uploaded_at" = "created_at";
