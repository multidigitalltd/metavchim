-- תזכורת לפני סיור — מתי היא נשלחה, כדי שלא תישלח פעמיים.
--
-- **חותמת אחת לסיור ולא אחת לנמען.** הסבב שולח לשני הצדדים באותו
-- מעבר, ומי שלא הצליח לקבל מקבל משימה לסוכן — כלומר אין מצב של
-- "חצי נשלח" שממתין להשלמה. חותמת פר-נמען הייתה מזמינה ניסיון
-- חוזר על הודעה שכבר יצאה, וזה הכיוון היקר יותר: לקוח שמקבל את
-- אותה תזכורת פעמיים.
--
-- NULL = טרם נשלחה. סיור שנדחה למועד אחר מנוקה ב-API יחד עם
-- `rescheduled_from`, ולכן מקבל תזכורת חדשה למועד החדש.
ALTER TABLE "appointments" ADD COLUMN "reminder_sent_at" TIMESTAMPTZ;

-- הסבב שואל "מי מתחיל בשעות הקרובות וטרם קיבל תזכורת" — אינדקס
-- חלקי, כי אחרי השליחה השורה יוצאת מהשאלה לתמיד.
CREATE INDEX "appointments_reminder_pending_idx"
  ON "appointments" ("tenant_id", "starts_at")
  WHERE "reminder_sent_at" IS NULL;
