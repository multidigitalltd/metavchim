-- צד העסקה שהטופס נענה עליו, והטיוטה שנוצרה ממנו.
--
-- ‏`side` שמור על השורה ואינו נגזר מהתשובות: הלקוח פותח את הקישור
-- שוב אחרי השליחה כדי לתקן, והעמוד חייב לדעת לאיזה מסלול לחזור בלי
-- לנחש לפי אילו שדות מלאים. ברירת המחדל היא הצד היחיד שהיה קיים עד
-- כה, ולכן כל השורות הקיימות נכונות בלי מיגרציית נתונים.
--
-- ‏`property_id` הוא הטיוטה שהמוכר יצר. בלעדיו שליחה שנייה מאותו
-- קישור — „שכחתי לציין שיש מעלית” — הייתה פותחת נכס שני במאגר של
-- המשרד, וכפילות כזו מתגלה רק כשמישהו שואל למה יש שתי מודעות לאותה
-- דירה.
ALTER TABLE "intake_requests"
  ADD COLUMN "side" VARCHAR(10) NOT NULL DEFAULT 'buyer',
  ADD COLUMN "property_id" CHAR(26);

-- מזהה הטיוטה מגיע מאותו דייר, ולכן החיפוש שלה מוגבל בו: אינדקס על
-- המזהה לבדו היה מזמין שאילתה חוצת-דיירים שה-RLS חוסם ממילא, וכאן
-- אין טעם לשלם עליו.
CREATE INDEX "intake_requests_property_idx"
  ON "intake_requests" ("tenant_id", "property_id")
  WHERE "property_id" IS NOT NULL;
