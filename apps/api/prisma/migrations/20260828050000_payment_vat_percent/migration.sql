-- שיעור המע"מ נצרב על התשלום, ולא נקרא מחדש בעת הפקת המסמך.
--
-- המחירון של הפלטפורמה נקוב **לפני מע"מ**, והסכום שנגבה הוא הוא
-- ועוד מע"מ. המסמך נבנה מהברוטו שנגבה בפועל — הוא חייב להסתכם
-- בדיוק בשקל שקארדקום גבתה — ולכן הוא מפרק אותו בחזרה.
--
-- הפירוק הזה קרא עד עכשיו את **השיעור הנוכחי** בעת ההפקה. זה נכון
-- כל עוד הוא לא השתנה בין הגבייה למסמך, וזו הנחה שנשברת בדיוק
-- ביום שהיא הכי יקרה: שינוי חקיקה. תשלום של 100 ₪ נטו שנגבה
-- כ-118 ₪ בשיעור 18%, ומפורק אחרי השינוי ב-19%, נרשם כנטו של
-- 99.16 ₪ — כלומר שורת חשבונית שאינה המחיר שהובטח, על כל
-- התשלומים שהיו באוויר באותו רגע (ביקורת Codex).
--
-- החלון אינו תיאורטי: דף תשלום פתוח, סבב חידושים שרץ, וסורק
-- החשבוניות שעובר כל חמש דקות — כולם מפרידים בין הרגע שהסכום
-- נקבע לרגע שהמסמך נוצר.
--
-- הערך נכתב ברגע שהסכום נקבע, ומשמש את המסמך שלו בלבד.
ALTER TABLE "payments" ADD COLUMN "vat_percent" INTEGER;

