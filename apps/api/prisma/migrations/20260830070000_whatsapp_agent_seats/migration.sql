-- מקומות לסוכן הוואטסאפ: מוקצים במפורש, ולא נגזרים מתפקיד.
--
-- עד כה בעל המשרד היה מורשה אוטומטית לפי `role`, ולכן הדגל שלו לא
-- נשמר בשום מקום — ולא הייתה שום דרך להעביר את המקום לסוכן אחר.

-- מקום אחד מגיע מהמסלול עצמו (כל מסלול שכולל את הסוכן), ולכן כאן
-- נספר רק מה שנרכש **מעבר** לו. אפס הוא המצב הרגיל.
ALTER TABLE "tenants"
  ADD COLUMN "whatsapp_agent_seats_extra" INTEGER NOT NULL DEFAULT 0;

-- 1 · בעל המשרד מקבל במפורש את מה שכבר היה לו בפועל.
--
-- בלי זה הפריסה הייתה מנתקת **את כל בעלי המשרדים** בבת אחת: הגישה
-- שלהם נגזרה מהתפקיד, ומרגע שההכרעה קוראת את הדגל בלבד — הדגל ריק.
UPDATE "users"
   SET "whatsapp_access" = TRUE
 WHERE "role" = 'owner'
   AND "is_active" = TRUE
   AND "whatsapp_access" = FALSE;

-- 2 · מקום אחד לכל משרד שהמסלול שלו כולל את הסוכן, ומי שמעבר נחסם.
--
-- ‎**החלטה של בעל הפלטפורמה, ולא ברירת מחדל טכנית.** אפשר היה לקבע
-- את המכסה לפי מה שכל משרד משתמש בו היום ולא לחסום איש; ההכרעה
-- הייתה הפוכה: מקום אחד כלול, וכל מקום נוסף כרוך בתשלום — ולכן
-- סוכנים שהופעלו בלי חיוב נחסמים, ומופעלים מחדש כשהמשרד רוכש.
--
-- הגישה נשללת מכל מי שאינו בעל המשרד. הקישור עצמו נשאר — הזכאות
-- נבדקת בכל הודעה, והמסך מציג למי המקום מוקצה ומאפשר לנתק.
UPDATE "users"
   SET "whatsapp_access" = FALSE
 WHERE "role" <> 'owner'
   AND "whatsapp_access" = TRUE;
