-- מקור המקום: נקנה בידי המשרד, או הוענק בידי בעל הפלטפורמה.
--
-- ‎`granted` אינו מחויב לעולם — גם כשיש לו תאריך סיום. ההבחנה נדרשת
-- דווקא בגלל התאריך: מקום ניסיון חייב `current_period_end` כדי שמשהו
-- יסגור אותו, וסורק החידושים אוסף כל שורה שהתאריך שלה עבר. בלי
-- העמודה הזאת הוא היה מנסה לחייב כרטיס על מקום שניתן במתנה.
--
-- ברירת המחדל `purchased` היא הנכונה לשורות הקיימות: עד היום כל
-- שורה כאן נוצרה מדף תשלום.
ALTER TABLE "whatsapp_seats"
  ADD COLUMN "origin" VARCHAR(10) NOT NULL DEFAULT 'purchased';

-- סורק השחרור מחפש מקומות שהוענקו ותקופתם נגמרה. הם מיעוט מבין
-- השורות, וסריקה לפי התאריך בלבד הייתה קוראת גם את כל מה שנקנה.
CREATE INDEX "whatsapp_seats_origin_current_period_end_idx"
  ON "whatsapp_seats" ("origin", "current_period_end");
