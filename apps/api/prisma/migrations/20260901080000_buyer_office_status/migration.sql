-- סטטוס המשרד על כרטיס הקונה — שכבה ב'.
--
-- העמודה מחזיקה **מזהה** מתוך רשימת הסטטוסים שבהגדרות המשרד
-- (`tenants.settings -> 'buyerStatuses'`), ולא את התווית: משרד
-- שמשנה „בסבב סיורים” ל„בסיורים” אינו מתכוון לאבד את הסטטוס מכל
-- הכרטיסים שנושאים אותו.
--
-- `null` הוא המצב הרגיל ולא חריג: כרטיס יכול להיות מסומן בשכבה א'
-- בלבד. `maturity` נשארת עמודת חובה בדיוק כפי שהייתה, וכל מי שקורא
-- אותה — דשבורד, התאמות, התראות, ייצוא — אינו יודע שהעמודה הזו
-- קיימת.
ALTER TABLE "buyers"
  ADD COLUMN "office_status" VARCHAR(24);

-- שני צרכנים, שניהם על תת-קבוצה קטנה מהטבלה: סינון הרשימה לפי
-- סטטוס, והבדיקה „האם מישהו נושא את הסטטוס הזה” לפני מחיקתו
-- מההגדרות. אינדקס חלקי, כי הרוב המכריע של השורות הוא `null`
-- ואין טעם לאנדקס אותן.
CREATE INDEX "buyers_tenant_office_status_idx"
  ON "buyers" ("tenant_id", "office_status")
  WHERE "office_status" IS NOT NULL;
