-- ‏מועד התפוגה של הטוקן העסקי — הסוף של כשל שקט בן 60 יום.
--
-- ‏תצורת ה-Embedded Signup שמטא מאפשרת ליצור היום מנפיקה טוקן
-- ‏קצוב. עד כאן שמרנו את הטוקן בלבד: בלי מועד תפוגה, בלי רענון,
-- ‏ובלי דרך לדעת שהוא מת. וטוקן שפג אינו מודיע על עצמו — Meta
-- ‏אינה שולחת `account_update`, המסך ממשיך להציג „מחובר”, והלידים
-- ‏פשוט מפסיקים להיכנס. המתווך מגלה את זה מלקוח שמתלונן.
--
-- ‏העמודה היא מה שמאפשר לסורק לשאול „מה פג בשבועיים הקרובים”
-- ‏ולרענן מראש. NULL נשאר משמעותי: טוקן שאינו פג (כך הונפקו
-- ‏חיבורים קודמים) אינו נכנס לסבב, ולכן העמודה nullable ולא
-- ‏ברירת-מחדל כלשהי — „אין תפוגה” ו„תפוגה שאיננו יודעים” אינם
-- ‏אותו דבר, וערך מומצא היה שולח את הסורק לרענן טוקנים תקינים.
ALTER TABLE "whatsapp_business_connections"
    ADD COLUMN "access_token_expires_at" TIMESTAMP(3);

-- ‏הסורק שואל „מה פג בקרוב” כל שש שעות. בלי אינדקס זו סריקת טבלה
-- ‏מלאה שגדלה עם כל קו שמתחבר.
CREATE INDEX "whatsapp_business_connections_access_token_expires_at_idx"
    ON "whatsapp_business_connections" ("access_token_expires_at");
