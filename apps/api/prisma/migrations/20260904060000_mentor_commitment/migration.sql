-- ‎**מחויבות מפורשת לבקשה של המנטור (docs/13 §2).**
--
-- הסיכום השבועי מבקש דבר אחד לשבוע הבא. עד עכשיו הבקשה נאמרה
-- ונעלמה: המנטור לא ידע אם המתווך קיבל אותה, ובשבוע שאחרי לא היה
-- מול מה לבדוק. מנטורים חיים על המחויבות הזאת — „כן, אני מתחייב”
-- הוא מה שהופך בקשה לעסקה בין שניים, ו„עמדת בזה” בשבוע הבא הוא
-- מה שהופך את העסקה לאמון.
--
-- שלוש עמודות על הסיכום עצמו, כי המחויבות היא תשובה לסיכום מסוים:
-- מה הוחלט, מתי, ומילה של המתווך אם רצה („רק ארבע השבוע, יש
-- מילואים”). מה נתבקש כבר יושב ב-`body` (השדה `ask`).
ALTER TABLE "mentor_reviews"
  ADD COLUMN "commitment"      VARCHAR(10),
  ADD COLUMN "committed_at"    TIMESTAMP(3),
  ADD COLUMN "commitment_note" VARCHAR(300);
