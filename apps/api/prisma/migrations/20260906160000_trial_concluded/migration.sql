-- ‎**למה הסיבה נשמרת ואינה נגזרת.**
--
-- ‏`trial_ends_at` ריק נראה אותו דבר בשני מצבים שונים לחלוטין:
-- ‏ניסיון שנגמר (מעבר למסלול חינמי, הענקת תקופה) וערך שאופס
-- ‏זמנית ממסך החיוב ויכול לחזור. הראשון סוגר את רישום המשפך,
-- ‏השני חייב להשאיר אותו פתוח — וזו הכרעה הפוכה על אותה שורה.
--
-- ‏הגרסה הקודמת ניחשה את ההבדל מ-`status` ומ-`paid_until`, וזה
-- ‏נשבר בדיוק במקום שבו ניחוש נשבר: „פתח ללא תפוגה” שולח
-- ‏`paidUntil: null`, מוחק את תאריך הניסיון, ומשאיר את הסטטוס
-- ‏„ניסיון” — כלומר מצב שאינו ניתן להבחנה מהאיפוס הזמני (ביקורת
-- ‏Codex). הסיבה אינה נמצאת בנתונים, ולכן היא נרשמת.
ALTER TABLE "tenants" ADD COLUMN "trial_concluded_at" TIMESTAMP(3);

COMMENT ON COLUMN "tenants"."trial_concluded_at" IS
  'מתי הניסיון נגמר בכוונה (מעבר לחינמי / הענקת תקופה). NULL = לא נגמר, כולל תאריך שאופס זמנית.';

-- ‎**מילוי חד-פעמי — והפעם הניחוש מותר.**
--
-- ‏שורות קיימות נכתבו לפני שהעמודה הייתה, ולכן אין להן סיבה
-- ‏רשומה. בלי המילוי כל משרד שכבר עבר לחינמי היה נקרא „הערך רק
-- ‏חסר”, ורישום המשפך שלו היה נשאר פתוח לנצח — בדיוק התור התקוע
-- ‏שהעמודה נועדה למנוע.
--
-- ‏זה בדיוק הכלל הנגזר שנדחה כאן, ועכשיו הוא במקומו הנכון:
-- ‏**הסקה חד-פעמית על העבר**, ולא כלל שרץ בכל החלטה. משרד שהתאריך
-- ‏שלו אופס זמנית ממסך החיוב אינו נכלל — הוא נשאר בסטטוס „ניסיון”
-- ‏ובלי `paid_until`, כלומר נשאר פתוח, וזה הצד הבטוח.
UPDATE "tenants"
   SET "trial_concluded_at" = COALESCE("updated_at", now())
 WHERE "trial_ends_at" IS NULL
   AND ("status" <> 'trial' OR "paid_until" IS NOT NULL);
