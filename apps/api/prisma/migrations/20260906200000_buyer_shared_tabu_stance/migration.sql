-- ‎**עמדת הקונה כלפי טאבו משותף — ושני האינדקסים שהופכים אותה לסינון.**
--
-- ‏המיגרציה הקודמת סימנה את **העובדה**: הנכס רשום במושאע, והלקוח
-- ‏קשור לרישום כזה. העמדה כאן היא שאלה אחרת לגמרי — מה הקונה מוכן
-- ‏לקנות — ולכן היא יושבת על `buyers` ולא על `contacts`. אילו
-- ‏השתיים היו חולקות עמודה, בעל חלקה משותפת שמוכר אותה היה מסומן
-- ‏אוטומטית כמי שמוכן לקנות מושאע.
--
-- ‎`NULL` הוא ערך ולא היעדר: **טרם נשאל.** זהו המצב של כל הכרטיסים
-- ‏שקדמו לשדה, ואסור שהוא ייקרא כסירוב — קריאה כזו הייתה מסתירה
-- ‏נכסים בטאבו משותף מכל הקונים הקיימים באותו רגע, בלי שאיש בחר
-- ‏בכך. במנוע ההתאמות: `NULL` מציג את הנכס ומצרף שאלה, `refuses`
-- ‏פוסל, `accepts` מצרף גם לשידוך שותפים.
--
-- ‏העמודה **נגזרת מ-`requirements`** ונכתבת יחד איתה, בדיוק כמו
-- ‏`has_search_areas`: הסינון הגס במנוע ורשימת הקונים במסך אינם
-- ‏יכולים לפתוח JSON בכל שורה.
ALTER TABLE "buyers"
  ADD COLUMN "shared_tabu_stance" VARCHAR(10);

-- ‏אינדקס **חלקי**: רוב הקונים לא נשאלו, ושורה שלא נשאלה אינה
-- ‏מסוננת לעולם — הסינון במסך שואל „מי אישר” או „מי סירב”.
CREATE INDEX "buyers_tenant_id_shared_tabu_stance_idx"
  ON "buyers" ("tenant_id", "shared_tabu_stance")
  WHERE "shared_tabu_stance" IS NOT NULL AND "deleted_at" IS NULL;

-- ‏ומהצד השני: נכסים בטאבו משותף הם מיעוט, ולכן אינדקס חלקי על
-- ‏ה-`true` בלבד. הוא משרת גם את סינון הרשימה וגם את איתור הנכסים
-- ‏שמועמדים לשידוך שותפים.
CREATE INDEX "properties_tenant_id_shared_tabu_idx"
  ON "properties" ("tenant_id")
  WHERE "shared_tabu" AND "deleted_at" IS NULL;
