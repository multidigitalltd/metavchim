-- ‎**„טאבו משותף” — עובדה אחת שהיו לה שני בתים** (ביקורת Codex, P1).
--
-- ‏`shared_tabu` קיים ב-`PropertyTypeSchema` מלפני הדגל שנוסף
-- ‏במיגרציה הקודמת, והמסלולים שמזינים אותו חיים: מחלץ הנכס
-- ‏מהקלטה (`logic/extract-property.ts`), ייבוא ה-CSV, וכל שורה
-- ‏שנרשמה כך עד היום.
--
-- ‏שתי דליפות הפוכות זו לזו נבעו מכך: דירה שסומן עליה הדגל נפסלה
-- ‏מקונה שביקש את **הסוג**, ונכס שנרשם בסוג נשאר עם דגל `false` —
-- ‏כלומר בלי האזהרה המשפטית, בלי הסינון ובלי שידוך שותפים. דווקא
-- ‏הנכסים שהתכונה נבנתה בשבילם היו היחידים שלא מקבלים אותה.
--
-- ‏ההכרעה: **הדגל הוא הבית, והסוג הוא קלט לגיטימי שנכתב אליו.**
-- ‏הדגל מדויק יותר — הוא מרכיב עם כל סוג מבנה, בעוד שהסוג תופס את
-- ‏המשבצת היחידה ומוחק את „פנטהאוז” או „דירת גן”. הסוג נשאר, כי
-- ‏שורות קיימות נושאות אותו וקונים ביקשו אותו ברשימת הסוגים שלהם.

-- ‏מילוי לאחור: כל נכס שנרשם בסוג נושא מעכשיו גם את הדגל.
UPDATE "properties"
   SET "shared_tabu" = true
 WHERE "property_type" = 'shared_tabu'
   AND "shared_tabu" = false;

-- ‏והאינדקס נבנה על **אותו תנאי** שהסינון שואל.
--
-- ‏אינדקס על הדגל בלבד היה תקין רק כל עוד המילוי לאחור מכסה הכול
-- ‏— והוא אינו מכסה את המקרה שבו מתווך מסיר את הסימון מנכס שסוגו
-- ‏עדיין `shared_tabu`. `sharedTabuWhere` שואל את הדיסיונקציה,
-- ‏ולכן זה מה שמאונדקס.
DROP INDEX IF EXISTS "properties_tenant_id_shared_tabu_idx";

CREATE INDEX "properties_tenant_id_shared_tabu_idx"
  ON "properties" ("tenant_id")
  WHERE ("shared_tabu" OR "property_type" = 'shared_tabu') AND "deleted_at" IS NULL;
