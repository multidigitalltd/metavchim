-- ‎**קונה שביקש את סוג הנכס הישן כבר אמר „מקבל”** (ביקורת Codex, P1).
--
-- ‏`shared_tabu` היה ערך ב-`propertyTypes` הרבה לפני עמודת העמדה,
-- ‏והוא האמירה היחידה שהייתה קיימת. ההגירה שהוסיפה את העמודה
-- ‏השאירה את כל השורות הקיימות `NULL` — „טרם נשאל” — ולכן דווקא
-- ‏הקונים שכבר הצהירו על נכונות נפלו מחוץ לשידוך השותפים, עד
-- ‏שמישהו יערוך כל כרטיס ביד.
--
-- ‏רק `NULL` מתמלא: עמדה מפורשת היא אמירה של הלקוח, וגם „מסרב”
-- ‏שנאמר לצד דרישה ישנה נשאר סירוב. אותו כלל בדיוק כתוב
-- ‏ב-`buyerSharedTabuStance`, וזו ההתממשות שלו לשורות שכבר קיימות.
UPDATE buyers
   SET shared_tabu_stance = 'accepts'
 WHERE shared_tabu_stance IS NULL
   AND requirements -> 'propertyTypes' @> '["shared_tabu"]'::jsonb;
