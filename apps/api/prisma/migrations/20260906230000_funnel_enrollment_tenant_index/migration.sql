-- ‎**האינדקס שהוצהר בסכמה ומעולם לא נוצר** (ביקורת Codex, P2).
--
-- ‏`@@index([tenantId, track])` מוצהר על `FunnelEnrollment` מאז
-- ‏המיגרציה הראשונה, אבל המיגרציה יצרה רק את הייחודי **החלקי**
-- ‏`WHERE ended_at IS NULL`. השניים נראים זהים בשורת ההגדרה, ולכן
-- ‏קל להניח שאחד מהם ממלא את מקום השני — והוא אינו:
--
-- ‎`reopenLapsed` שולף בדיוק את המשלים, `ended_at IS NOT NULL`,
-- ‏ולכן האינדקס החלקי אינו יכול לשרת אותו כלל. בלי האינדקס הזה
-- ‏החצי-חיבור שהוסבר בסבב הקודם — נהיגה מקבוצת הניסיונות החיים
-- ‏אל הרישומים לפי `tenant_id` — אין לו דרך גישה, ו-PostgreSQL
-- ‏חוזר לסרוק את היסטוריית המשלמים הגדלה. כלומר העבודה הבלתי
-- ‏חסומה שהתיקון ההוא בא לסגור חזרה מהדלת האחורית.
--
-- ‎`IF NOT EXISTS` כי `prisma migrate diff` מייצר את השם הזה
-- ‏בדיוק, ומסד שכבר יושר ידנית לא ייפול.
CREATE INDEX IF NOT EXISTS "funnel_enrollments_tenant_id_track_idx"
  ON "funnel_enrollments"("tenant_id", "track");
