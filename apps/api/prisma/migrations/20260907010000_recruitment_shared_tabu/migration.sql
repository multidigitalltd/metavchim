-- ‎**שורת גיוס נושאת את הרישום המשותף בעצמה** (ביקורת Codex, P1).
--
-- ‏הדגל הפך למקור האמת, והסוג הוותיק (`shared_tabu`) ירד מבורר
-- ‏הסוגים — אבל טופס הגיוס הוא הטופס הרביעי שמשתמש באותו בורר,
-- ‏והוא לא קיבל תיבה משלו. התוצאה בשלושה מצבים:
--
-- ‏  • שורת גיוס חדשה לא יכולה לרשום „טאבו משותף” בכלל.
-- ‏  • עריכת שורה שנושאת את הסוג הוותיק נפלה לאפשרות הראשונה
-- ‏    בבורר ושמרה מעליה — הסימון נמחק בשקט.
-- ‏  • וההמרה יוצרת נכס רגיל, שמוצע לקונים שסירבו במפורש למושאע.
--
-- ‏העמודה כאן היא אותה עמודה שיש לנכס ולאיש הקשר, ובאותו שם.
ALTER TABLE "recruitment_targets"
  ADD COLUMN IF NOT EXISTS "shared_tabu" BOOLEAN NOT NULL DEFAULT false;

-- ‏מילוי לאחור מהצורה הישנה: שורה שנרשמה בסוג הוותיק אכן משותפת.
-- ‏אותו כלל בדיוק כמו ב-`properties` וב-`shared_listings`.
UPDATE "recruitment_targets"
   SET "shared_tabu" = true
 WHERE "property_type" = 'shared_tabu';
