--
-- ‏כתובת ה-Reply-To זוהתה בלקוח בלבד, ולכן קליטת התשובה שאלה „מי
-- ‏אחראי על הלקוח הזה” — שאלה נכונה לשיחה נכנסת שאיש לא יזם, ושגויה
-- ‏לתשובה על הודעה שסוכן מסוים שלח. סוכן ב׳ שלח הסכם על נכס שלו
-- ‏ללקוח שגם לסוכן א׳ יש עליו כרטיס קונה; „קונים” קודם ל„נכסים”
-- ‏בתור, ולכן ההתראה — ואיתה שם הלקוח ותמצית ההודעה — הגיעה לא׳.
--
-- ‎`NULL` ולא ברירת מחדל: טוקן שנוצר לפני השדה, ושליחה אוטומטית
-- ‏שאין לה סוכן, נשארים על הסדר הרגיל. זהו בדיוק המצב שבו הוא נכון.
