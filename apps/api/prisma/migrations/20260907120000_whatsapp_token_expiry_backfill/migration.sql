-- ‏חיבורים שנוצרו לפני שהעמודה קיימת — „לא ידוע” ולא „אינו פג”.
--
-- ‏המיגרציה הקודמת הוסיפה את `access_token_expires_at` והשאירה NULL
-- ‏בשורות הקיימות, מתוך הנחה שהטוקנים שלהן אינם פגים. ההנחה אינה
-- ‏ניתנת לאימות: הקוד הישן החליף את אותו `code` באותו
-- ‏`/oauth/access_token` בדיוק, ופשוט **זרק** את `expires_in`. כלומר
-- ‏ל-NULL בשורות האלה יש שתי משמעויות אפשריות, והסורק מדלג על שתיהן
-- ‏(`accessTokenExpiresAt: { not: null }`) — כך שטוקן בן 60 יום שכבר
-- ‏קיים ימשיך למות בשקט, וזה בדיוק הכשל שהעמודה נועדה למנוע
-- ‏(ביקורת Codex).
--
-- ‏מכיוון שאי אפשר לדעת, בוחרים את ההנחה שהטעות בה זולה יותר:
--
-- ‏„אינו פג” בטעות ⇒ הקו מת בשקט, והמתווך מגלה מלקוח שמתלונן.
-- ‏„60 יום מהחיבור” בטעות ⇒ רענון אחד מיותר, ש-Meta עונה עליו
-- ‏בטוקן חדש, והסורק כותב את מה שהיא באמת אמרה. כלומר ההערכה
-- ‏מתקנת את עצמה בסבב הראשון.
--
-- ‏60 יום הם מה שתצורת Embedded Signup מנפיקה היום, ו-`connected_at`
-- ‏הוא מועד ההנפקה: הטוקן נוצר בהמרת ה-`code` בשמירת החיבור. הערכה
-- ‏מוקדמת מדי מרעננת מוקדם (לא מזיק); מאוחרת מדי מסמנת קו שכבר מת,
-- ‏וזו התוצאה הנכונה ממילא.
--
-- ‏רק שורות מחוברות שיש להן טוקן: מנותקות אין להן מה לרענן.
UPDATE "whatsapp_business_connections"
   SET "access_token_expires_at" = "connected_at" + INTERVAL '60 days'
 WHERE "access_token_expires_at" IS NULL
   AND "access_token_encrypted" IS NOT NULL
   AND "disconnected_at" IS NULL;
