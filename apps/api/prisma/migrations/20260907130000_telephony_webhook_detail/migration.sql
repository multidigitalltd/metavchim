-- ‎**יומן הוובהוקים — שיהיה אפשר לעקוב אחריו בפועל.**
--
-- ‏שלוש חסרות שהפכו אותו לבלתי-שמיש בדיוק כשנזקקים לו:
--
-- ‎**1 · אין קשר בין שורת יומן לשיחה.** „נקלטה” אמר שהאירוע הפך
-- ‏לשיחה, ולא **לאיזו**. אי אפשר היה ללכת משורה לשיחה שהיא יצרה,
-- ‏ולא מהשיחה חזרה לאירוע שהוליד אותה.
--
-- ‎**2 · אין סוג אירוע.** ההערה על העמודה `outcome` מתארת בעצמה
-- ‏תקלה אמיתית — „מרכזייה ששולחת Calling ומאבדת את ה-Hangup” —
-- ‏אבל היומן לא שמר **איזה** אירוע הגיע, ולכן דווקא את האבחנה הזו
-- ‏אי אפשר היה לעשות ממנו.
--
-- ‎**3 · מאתיים שורות לכל הפלטפורמה.** על מערכת פעילה זו היסטוריה
-- ‏של דקות: מי שנכנס לברר למה שיחה לא נקלטה מוצא שהשורה כבר נגרסה.
-- ‏השמירה עוברת לחלון זמן, שהוא מה שהופך יומן למשהו שאפשר לעקוב
-- ‏אחריו; התקרה נשארת כרשת ביטחון מול הצפה.
ALTER TABLE "telephony_webhook_hits"
  ADD COLUMN "call_id"   VARCHAR(120),
  ADD COLUMN "action"    VARCHAR(20),
  ADD COLUMN "direction" VARCHAR(10);

-- ‏„הראה לי את הוובהוקים של המשרד הזה” היא השאלה הראשונה שנשאלת,
-- ‏והיא סרקה עד עכשיו את כל הטבלה לפי זמן בלבד.
CREATE INDEX "telephony_webhook_hits_tenant_received_idx"
  ON "telephony_webhook_hits" ("tenant_id", "received_at" DESC);

-- ‏„כל האירועים של השיחה הזו” — הצירוף שהופך שלוש שורות נפרדות
-- ‏(Calling / Answer / Hangup) לסיפור אחד.
CREATE INDEX "telephony_webhook_hits_call_idx"
  ON "telephony_webhook_hits" ("call_id");

-- ‎**4 · אי אפשר היה לחפש לפי מספר.** „לקוח התקשר ואין רישום” היא
-- ‏השאלה שבשבילה היומן קיים, והנתון היחיד שיש למי ששואל אותה הוא
-- ‏מספר הטלפון של הלקוח. עד עכשיו הוא לא היה בטבלה בשום צורה.
--
-- ‏חתימה ולא מספר: יומן פלטפורמה שנקרא בעיניים אינו המקום שבו
-- ‏יישמרו מספרי הלקוחות של כל המשרדים בטקסט גלוי — זה בדיוק מה
-- ‏שההצפנה בכל שאר המערכת מונעת. אותה חתימת ‎HMAC‎ שכל זיהוי נכנס
-- ‏כבר עובד מולה (‎contacts.phone_hash‎), ולכן חיפוש מדויק אפשרי
-- ‏בלי שהמספר עצמו יישמר.
--
-- ‏ארבע הספרות האחרונות נשמרות בנפרד ובגלוי, כדי שאפשר יהיה לראות
-- ‏ברשימה לא מסוננת ששתי שורות הן אותו מתקשר. חתימה לבדה עונה רק
-- ‏למי שכבר יודע את המספר שהוא מחפש.
ALTER TABLE "telephony_webhook_hits"
  ADD COLUMN "peer_hash"   CHAR(64),
  ADD COLUMN "peer_suffix" VARCHAR(4);

CREATE INDEX "telephony_webhook_hits_peer_idx"
  ON "telephony_webhook_hits" ("peer_hash");
