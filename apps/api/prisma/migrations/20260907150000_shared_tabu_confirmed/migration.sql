-- ‎**מי כבר נשאל על רישום משותף — ולא „מצב שלישי”.**
--
-- ‏העמודה `shared_tabu` נשארת בוליאנית בדיוק כפי שהיא, ומאותו
-- ‏נימוק שכתוב עליה: „לא סומן” אינו „לא ידוע”, ומצב שלישי שאיש
-- ‏אינו מתחזק גרוע משניים.
--
-- ‏אבל יש פער אמיתי מתחתיו: המנוע **פוסל** נכס בטאבו משותף מקונה
-- ‏שסירב, ונכס שבאמת רשום במשותף ואיש לא סימן אותו נקרא `false`
-- ‏— כלומר הוא כן מוצע לקונה שסירב במפורש. זו בדיוק ההבטחה בלי
-- ‏כיסוי שהפיצ'ר קיים כדי למנוע.
--
-- ‏הפתרון אינו לשנות את מה שהמנוע קורא, אלא לתעד **מי כבר נשאל**:
-- ‏חותמת שנכתבת רק כשאדם ענה על השאלה במפורש. ההתאמות, הסינון
-- ‏והדגל עצמו אינם משתנים כלל — העמודה היא תיעוד, לא שער.
--
-- ‏כל השורות הקיימות מתחילות ב-NULL, וזו האמת: אף אחת מהן לא
-- ‏נשאלה. המסך „רישום משותף — מה שטרם נבדק” הוא המעבר החד-פעמי
-- ‏עליהן, והוא מתקצר בכל תשובה.
ALTER TABLE "properties"
  ADD COLUMN "shared_tabu_confirmed_at" TIMESTAMPTZ;

-- ‏המסך שואל תמיד את אותה שאלה — „מה עוד לא נבדק” — ולכן אינדקס
-- ‏חלקי על ה-NULL בלבד: הוא מתכווץ ככל שהמעבר מתקדם, ובמשרד
-- ‏שסיים אותו הוא כמעט ריק.
CREATE INDEX "properties_shared_tabu_unconfirmed_idx"
  ON "properties" ("tenant_id", "updated_at" DESC)
  WHERE "shared_tabu_confirmed_at" IS NULL AND "deleted_at" IS NULL;
