-- ‎**מי קיבל את השיחה — נשמר, במקום להישאל בדיעבד.**
--
-- ‏שורת השיחה לא נשאה שום סוכן. המנהל ראה „שיחה נכנסת ב-14:03”
-- ‏ולא לאיזה סוכן היא הגיעה — כלומר בדיוק השאלה שבשבילה הוא פותח
-- ‏את המסך.
--
-- ‏שתי עמודות ולא אחת, כי אלה שתי עובדות שונות:
--
-- ‎* `agent_extension` — השלוחה שהמרכזייה דיווחה עליה. **מי ענה
--   ‏בפועל.** נשמרת גם כשאין לה סוכן מוכר במערכת, כי „שלוחה 203”
--   ‏היא תשובה שימושית בהרבה מכלום.
-- ‎* `agent_user_id` — הסוכן שהשיחה הגיעה אליו, **כצילום ברגע
--   ‏השיחה** ולא כהפניה חיה. אותו נימוק בדיוק כמו `property_id`:
--   ‏הניתוב של מספר וירטואלי משתנה בדיעבד, ושיחה שכבר קרתה אינה
--   ‏אמורה לשנות בעלים כשמישהו עורך הגדרה.
--
-- ‏שורות שנכתבו לפני העמודות נשארות NULL בכוונה — ניחוש בדיעבד
-- ‏הוא בדיוק מה שהעמודות מונעות.
ALTER TABLE "calls" ADD COLUMN "agent_user_id" CHAR(26);
ALTER TABLE "calls" ADD COLUMN "agent_extension" VARCHAR(20);

-- ‏„השיחות של הסוכן הזה” — הסינון שהמנהל באמת מריץ.
CREATE INDEX "calls_agent_idx" ON "calls" ("tenant_id", "agent_user_id", "occurred_at" DESC);
