-- ‎**מספר הלקוח הסגיר כמה משרדים יש למערכת.**
--
-- ‏הרצף חילק 100000, 100001, 100002. כלומר משרד שנרשם וראה
-- ‏„100004” ידע מיד שהוא הרביעי — ושתי ספרות בלבד מתוך שש היו
-- ‏פעילות, כך שגם בלי לחשוב על זה המספר נקרא כמונה (בקשת המשתמש).
--
-- ‏זה גם עובד לכיוון השני: שני משרדים שמשווים מספרים יודעים כמה
-- ‏הצטרפו ביניהם, וכמה זמן לוקח למערכת לגייס לקוח.
--
-- ‎**מה שהוחלף הוא התצוגה, לא המנגנון.** הרצף נשאר בדיוק כפי
-- ‏שהוא — הוא מה שמבטיח שכל מספר מחולק פעם אחת ואינו חוזר, וזו
-- ‏הסיבה שהוא נבחר מלכתחילה. מה שנוסף הוא **תמורה** מעליו: פונקציה
-- ‏חד-חד-ערכית שמפזרת את הרצף על כל תחום שש הספרות.
--
-- ‏חד-חד-ערכית פירושה שהייחודיות נשמרת בלי להסתמך על מזל: אין שני
-- ‏מקומות ברצף שמגיעים לאותו מספר, ולכן האינדקס הייחודי אינו
-- ‏„מנגנון הגנה” אלא בדיקה שאמורה לעולם לא לירות. זו הסיבה שלא
-- ‏נבחר כאן `random()` עם ניסיון חוזר: הוא היה עובד עד היום שבו
-- ‏שתי הרשמות בו-זמנית קיבלו את אותו מספר.

-- ‎**רשת Feistel — הדרך הסטנדרטית לערבב טווח בלי לאבד חד-חד-ערכיות.**
--
-- ‏ארבעה סבבים על שני חצאים בני עשר סיביות (2^20 = 1,048,576),
-- ‏ולאחריהם „הליכה מחזורית”: כל עוד התוצאה גדולה מהטווח שאנחנו
-- ‏רוצים, מפעילים עליה את אותה רשת שוב. גם זו תמורה — על תת-הקבוצה
-- ‏שבטווח — ולכן הייחודיות שורדת גם אותה.
--
-- ‎**התחום: 900,000 מספרים** (100000–999999), כלומר בדיוק שש ספרות
-- ‏תמיד, וכל שש פעילות. משרד ‎900,001 היה מתנגש; הוא ייפול על
-- ‏האינדקס הייחודי בקול, ולא ידרוס איש בשקט.
CREATE OR REPLACE FUNCTION tenant_customer_no(seq bigint)
RETURNS integer
LANGUAGE plpgsql
IMMUTABLE
AS $$
DECLARE
  -- ‏הרצף מתחיל ב-100000; כאן עובדים על מיקום מאופס
  v    bigint := (seq - 100000) % 1048576;
  l    integer;
  r    integer;
  t    integer;
  i    integer;
  -- ‏מפתחות הסבבים. שרירותיים בכוונה — תפקידם לפזר, לא להסתיר סוד
  keys integer[] := ARRAY[733271, 195409, 884203, 421787];
BEGIN
  -- ‏רצף שלילי אינו קיים, אבל מודולו של שלילי ב-Postgres שלילי גם הוא
  IF v < 0 THEN
    v := v + 1048576;
  END IF;

  LOOP
    l := (v / 1024)::integer;
    r := (v % 1024)::integer;
    FOR i IN 1..4 LOOP
      t := r;
      -- ‏„כפל וקח את הסיביות האמצעיות” — פיזור זול ודטרמיניסטי
      r := l # (((((r + keys[i])::bigint * 2654435761) / 1024) % 1024)::integer);
      l := t;
    END LOOP;
    v := (l::bigint * 1024) + r;
    EXIT WHEN v < 900000;
  END LOOP;

  RETURN (100000 + v)::integer;
END;
$$;

-- ‎**וגם המספרים שכבר חולקו.**
--
-- ‏משרד קיים נושא היום את מיקומו ברצף גלוי לעין. מספר לקוח שמשתנה
-- ‏הוא מחיר אמיתי — הוא נאמר בטלפון ונרשם אצל הלקוח — אבל הוא משתנה
-- ‏פעם אחת, עכשיו, כשמספר המשרדים קטן. לדחות את זה פירושו לשלם
-- ‏אותו מחיר בדיוק על יותר לקוחות, ובינתיים להמשיך להסגיר.
--
-- ‏המיפוי הוא של הערך הנוכחי, שהוא בדיוק ערך הרצף שממנו הוא הגיע.
-- ‏לכן משרד קיים ומשרד חדש עוברים באותה פונקציה, ואין כאן „כלל
-- ‏להיסטוריה” לצד „כלל לעתיד”.
--
-- ‏האינדקס יורד לרגע: `UPDATE` יחיד על כל השורות עלול לעבור דרך
-- ‏מצב ביניים שבו שתי שורות חולקות ערך, גם כשהמצב הסופי ייחודי.
DROP INDEX IF EXISTS "tenants_customer_no_key";

UPDATE "tenants" SET "customer_no" = tenant_customer_no("customer_no"::bigint);

CREATE UNIQUE INDEX "tenants_customer_no_key" ON "tenants" ("customer_no");

-- ‏מכאן ההקצאה עוברת דרך התמורה, בשני מסלולי ההקמה כאחד
ALTER TABLE "tenants"
  ALTER COLUMN "customer_no"
  SET DEFAULT tenant_customer_no(nextval('tenant_customer_no_seq'));
