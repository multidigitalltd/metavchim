-- ‎**משוב על הודעה בשיחה, ונעיצה.**
--
-- ‏משוב על **רעיונות** קיים מ-§7.2 („עזר לי” / „לא בשבילי” על כרטיס
-- ‏פעולה), ומחליף רעיון שלא עבד. מה שלא היה הוא משוב על מה שהמנטור
-- ‏**אמר בשיחה** — כלומר על התשובה עצמה.
--
-- ‎**שתי עמודות ולא אחת, כי אלה שתי פעולות שונות.** דירוג אומר „זה
-- ‏היה טוב”; נעיצה אומרת „אני רוצה למצוא את זה שוב”. הודעה יכולה
-- ‏להיות שתיהן, ואיחודן לעמודה אחת היה מכריח לבחור.
--
-- ‎`pinned_at` ולא `pinned BOOLEAN`: לרשימת הנעוצים יש סדר, והוא
-- ‏„מתי נעצתי” — לא „מתי נאמר”. משפט שנעצת היום חשוב לך היום, גם אם
-- ‏נאמר לפני חודש.
ALTER TABLE "mentor_messages"
  -- helpful | not_helpful. NULL = לא דורג, וזה הרוב המוחלט.
  ADD COLUMN "feedback"  VARCHAR(12),
  ADD COLUMN "pinned_at" TIMESTAMP(3);

-- ‏חלקי: הרשימה שואלת „מה נעוץ אצלי”, ורוב ההודעות אינן. אינדקס על
-- ‏כל השורות היה גדול פי כמה בלי לשרת שאילתה אחת.
CREATE INDEX "mentor_messages_tenant_id_user_id_pinned_at_idx"
  ON "mentor_messages"("tenant_id", "user_id", "pinned_at")
  WHERE "pinned_at" IS NOT NULL;
