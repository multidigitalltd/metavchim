-- ‎**הכרטיס שצורף לשיחה — על ההודעה, ולא על השיחה.**
--
-- ‏אין טבלת שיחות (ראו ההגירה של `thread_id`), ולכן ממילא אין לאן
-- ‏לתלות שדה ברמת השיחה. אבל גם אילו הייתה — המקום הנכון הוא
-- ‏ההודעה: מתווך פותח שיחה על קונה אחד, ובאמצעה עובר לשאול על אחר.
-- ‏שדה ברמת השיחה היה מכריח את השאלה הראשונה להיקרא בהקשר של
-- ‏הכרטיס האחרון שצורף — כלומר משכתב למפרע על מה נשאלה.
--
-- ‏הכרטיס הפעיל של שיחה נגזר: הכרטיס של ההודעה האחרונה שיש לה אחד.
-- ‏אותו דפוס כמו הכותרת — נגזרת אינה יכולה לחלוק על מה שהיא מתארת.
--
-- ‎**אין מפתח זר, בכוונה.** הכרטיס יכול להימחק, והשיחה עליו נשארת
-- ‏אמת היסטורית: „מה שאלתי אז” אינו משתנה כשהכרטיס נסגר.
-- ‎`ON DELETE SET NULL` היה מוחק את ההקשר של שיחה שכבר התקיימה,
-- ‏ו-`CASCADE` היה מוחק את השיחה עצמה. השרת מרענן את העובדות מהכרטיס
-- ‏בכל שאלה, וכרטיס שאיננו פשוט אינו נטען.
ALTER TABLE "mentor_messages"
  -- buyer | property | none — ראו האילוץ בסוף הקובץ
  ADD COLUMN "subject_kind" VARCHAR(10),
  ADD COLUMN "subject_id"   CHAR(26);

-- ‏„מה הכרטיס הפעיל בשיחה הזו” — שאלה שנשאלת על כל הודעה שנשלחת,
-- ‏ולכן על השיחה ולא על המשתמש. חלקי, כי רוב ההודעות בלי כרטיס.
--
-- ‎`subject_kind` ולא `subject_id`: גם „ניתקתי” הוא אמירה שצריך
-- ‏למצוא, ראו האילוץ מתחת.
CREATE INDEX "mentor_messages_tenant_id_thread_id_subject_idx"
  ON "mentor_messages"("tenant_id", "thread_id", "created_at")
  WHERE "subject_kind" IS NOT NULL;

-- ‎**שלושה מצבים, לא שניים.**
--
-- ‎`NULL` — ההודעה לא אמרה דבר על כרטיס, וזה הרוב המוחלט.
-- ‎`'none'` — המתווך **ניתק** את הכרטיס במפורש.
-- ‎`'buyer'` / `'property'` — כרטיס מצורף, ואז חייב להיות מזהה.
--
-- ‏המצב האמצעי אינו קישוט: הכרטיס הפעיל נגזר מההודעה האחרונה בשיחה
-- ‏שאמרה משהו, ובלי „ניתקתי” שמור, ניתוק היה נבלע — השאלה הבאה
-- ‏הייתה מדלגת אחורה אל הכרטיס הקודם וממשיכה לשלוח את פרטיו.
--
-- ‏המזהה חייב להתלוות דווקא לשני הסוגים האמיתיים: סוג בלי מזהה אינו
-- ‏ניתן לטעינה, ומזהה בלי סוג אינו ניתן לפירוש.
-- ‎`CASE` ולא שרשרת `OR`, וזו אינה העדפת סגנון.
--
-- ‏הניסוח `kind = 'none' OR kind IN (...)` מחזיר **NULL** כש-`kind`
-- ‏ריק — ו-CHECK עובר על NULL, כי „לא ידוע” אינו „שקר”. כלומר שורה
-- ‏עם מזהה בלי סוג הייתה נכנסת בשקט, בדיוק מה שהאילוץ נכתב למנוע.
-- ‏בדקתי את זה מול המסד: היא נכנסה.
--
-- ‎`COALESCE` הופך את הביטוי לוודאי, וה-`ELSE false` פוסל גם סוג
-- ‏שאיש לא הגדיר — כך שערך שיתווסף לקוד ולא כאן ייעצר, ולא יישמר
-- ‏כמשהו שאיש אינו יודע לקרוא.
ALTER TABLE "mentor_messages"
  ADD CONSTRAINT "mentor_messages_subject_pair"
  CHECK (
    CASE COALESCE("subject_kind", '')
      WHEN ''         THEN "subject_id" IS NULL
      WHEN 'none'     THEN "subject_id" IS NULL
      WHEN 'buyer'    THEN "subject_id" IS NOT NULL
      WHEN 'property' THEN "subject_id" IS NOT NULL
      ELSE false
    END
  );
