-- ‎**חזית או עורף — לאיזה כיוון הדירה פונה.**
--
-- ‏בשוק הישראלי זו אחת השאלות הראשונות בטלפון, ועד עכשיו לא היה
-- ‏לה שדה: מי ששאל רשם בהערות הפנימיות, ומשם זה לא חוזר לאף מסך
-- ‏ולא לשום סינון (בקשת המשתמש).
--
-- ‎**שלושה ערכים ולא שניים.** דירה שפונה לשני הכיוונים היא מצב
-- ‏נפוץ, ובבחירה של „חזית או עורף” בלבד היא נרשמת בשקר — אותה
-- ‏תקלה בדיוק שבגללה למועד הכניסה יש מצב ולא רק תאריך.
--
-- ‎`NULL` = לא צוין, וזו האמת על כל השורות הקיימות. ברירת מחדל
-- ‏הייתה קובעת עליהן עובדה שאיש לא בדק.
ALTER TABLE "properties" ADD COLUMN "facing" VARCHAR(10);

-- ‏ערך שאיש אינו יודע לקרוא גרוע מחוסר: המסך היה מציג מחרוזת
-- ‏גולמית, וסינון עתידי היה מחמיץ אותו בשקט. `NULL` עובר, כי
-- ‏„לא צוין” אינו „שקר”.
ALTER TABLE "properties"
  ADD CONSTRAINT "properties_facing_known"
  CHECK ("facing" IS NULL OR "facing" IN ('front', 'rear', 'both'));
