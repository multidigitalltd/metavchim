-- ‏מתי העסקה נסגרה — הרגע שבו הסטטוס עבר ל-`sold`/`rented`.
--
-- ‎**למה זו עמודה ולא `updated_at`** (ביקורת Codex, P1): `updated_at`
-- ‏הוא „מתי מישהו נגע בשורה”, ולכן כל עריכה על נכס שנמכר לפני חצי
-- ‏שנה הזיזה אותו לתקופה הנוכחית — ניפחה את מונה העסקאות של החודש
-- ‏ושינתה את הדירוג בטבלת המשרד.
--
-- ‏הפער היה קיים גם קודם. מה שהשתנה הוא שסימון „סוכן שותף” הופך
-- ‏עריכה על עסקה ישנה לפעולה **שגרתית** — זה בדיוק מה שהשדה מזמין.
ALTER TABLE "properties" ADD COLUMN "closed_at" TIMESTAMP(3);

-- ‎**מילוי לאחור מ-`updated_at`, ורק לשורות שכבר סגורות.**
--
-- ‏זה לא מדויק — `updated_at` של נכס שנמכר ואז נערך אינו רגע
-- ‏הסגירה — אבל הוא ההערכה הטובה ביותר שקיימת, והוא **בדיוק מה
-- ‏שהקוד קרא עד עכשיו**. כלומר המילוי אינו משנה שום מספר קיים;
-- ‏הוא רק מקפיא אותו, כך שמהיום עריכה כבר לא תזיז אותו.
UPDATE "properties"
   SET "closed_at" = "updated_at"
 WHERE "status" IN ('sold', 'rented')
   AND "deleted_at" IS NULL;

-- ‏„העסקאות של התקופה” היא השאילתה היחידה שקוראת אותו, והיא
-- ‏מסננת גם על הדייר וגם על הטווח.
CREATE INDEX "properties_closed_idx"
  ON "properties" ("tenant_id", "closed_at")
  WHERE "closed_at" IS NOT NULL;
