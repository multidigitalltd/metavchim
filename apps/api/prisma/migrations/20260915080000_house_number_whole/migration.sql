-- ‎**מספר בית שנשמר כ„5.0” חוזר להיות „5”.**
--
-- ‏הכלל עצמו נאכף מעכשיו בסכימה (`normalizeHouseNumber`), ולכן כל
-- ‏כתיבה חדשה — טופס, ייבוא, חילוץ מקול והסוכן בוואטסאפ — כבר
-- ‏נקייה. אבל שורות שיובאו לפני כן נשארו כפי שהן, והן מה שהמתווך
-- ‏רואה בכרטיס, בפירורי הלחם ובכל כתובת שנבנית מהן.
--
-- ‎**רק שארית אפס.** אותו כלל של הקוד, תו בתו: „5.0” ו„12.00” הם
-- ‏5 ו-12, ואילו „5.5”, „5א”, „12/2” ו„7-9” אינם נגועים כלל.
-- ‏מספרי בית בישראל אינם מספרים, וזה בדיוק מה שנרמול גס הורס.
--
-- ‎**והביטוי סופג רווחים בשני הקצות, מפני שהכלל בקוד מתחיל ב-`trim`.**
-- ‏הסכימה הישנה הייתה `z.string()` בלי גזירת רווחים, ולכן תא
-- ‏באקסל שנשמר כ„ 7.0 ” נכנס כלשונו. ביטוי מעוגן בלי גזירה אינו
-- ‏תופס אותו — כלומר בדיוק השורות שהמיגרציה קיימת בשבילן היו
-- ‏נשארות מאחור, והמסך היה ממשיך להציג „7.0” (ביקורת Codex).
--
-- ‎**`\s` ולא `btrim`**: ברירת המחדל של `btrim` גוזרת רווחים בלבד,
-- ‏ו-`trim` של JavaScript גוזר גם טאב ושבירת שורה. שורה שהגיעה
-- ‏מגיליון עם טאב הייתה נשארת מאחור בדיוק כמו עם רווח —
-- ‏אותה תקלה, בתו אחר (אומת מול Postgres אמיתי).
--
-- ‏הגזירה חלה **רק על השורות שהביטוי תופס**: „ 5א ” אינו נוגע
-- ‏בזה, כי המיגרציה מתקנת שארית אפס ולא מנקה רווחים בכל המאגר.
UPDATE properties
   SET house_number = regexp_replace(house_number, '^\s*(\d+)\.0+\s*$', '\1')
 WHERE house_number ~ '^\s*\d+\.0+\s*$';

-- ‎**ואותה עמודה יושבת גם על שורת הגיוס.**
--
-- ‏`recruitment_targets.house_number` הוא שדה נפרד עם אותו מקור —
-- ‏ייבוא אקסל וצילום מודעה — ולכן אותן שורות פגומות. הוא מוצג
-- ‏בכל מסכי הגיוס דרך `recruitmentAddress()`, ו**מועתק לנכס חדש**
-- ‏בהמרת גיוס. לתקן טבלה אחת פירושו שהערך חוזר דרך ההמרה
-- ‏(ביקורת Codex).
--
-- ‏אותו ביטוי בדיוק — אותו כלל, ולא ניסוח שני שיסטה ביום שמישהו
-- ‏יגע באחד מהם.
UPDATE recruitment_targets
   SET house_number = regexp_replace(house_number, '^\s*(\d+)\.0+\s*$', '\1')
 WHERE house_number ~ '^\s*\d+\.0+\s*$';
