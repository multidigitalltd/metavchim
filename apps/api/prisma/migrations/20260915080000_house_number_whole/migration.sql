-- ‎**מספר בית שנשמר כ„5.0” חוזר להיות „5”.**
--
-- ‏הכלל עצמו נאכף מעכשיו בסכימה (`normalizeHouseNumber`), ולכן כל
-- ‏כתיבה חדשה — טופס, ייבוא, חילוץ מקול והסוכן בוואטסאפ — כבר
-- ‏נקייה. אבל שורות שיובאו לפני כן נשארו כפי שהן, והן מה שהמתווך
-- ‏רואה בכרטיס, בפירורי הלחם ובכל כתובת שנבנית מהן.
--
-- ‎**רק שארית אפס.** אותו כלל של הקוד, תו בתו: „5.0” ו„12.00” הם
-- ‏5 ו-12, ואילו „5.5”, „5א”, „12/2” ו„7-9” אינם נגועים כלל.
-- ‏מספרי בית בישראל אינם מספרים, וזה בדיוק מה שנרמול גס הורס.
UPDATE properties
   SET house_number = regexp_replace(house_number, '^(\d+)\.0+$', '\1')
 WHERE house_number ~ '^\d+\.0+$';
