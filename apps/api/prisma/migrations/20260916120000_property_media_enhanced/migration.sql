-- שיפור תמונות נכס (docs/03 — property_media).
--
-- ‏כל תמונה שמועלית מעכשיו נשמרת אחרי שיפור (יישור, אור, חדות,
-- ‏כיווץ ל-WebP) — והמקור אינו נשמר: עותק מקור לכל תמונה היה
-- ‏מכפיל את האחסון של כל משרד לכל החיים בשביל ביטול שאיש לא מבקש.
--
-- ‎`enhanced_at` — מתי שופרה; NULL על תמונה שהועלתה לפני הכלי,
-- ‏ואז המסך מציע „לשפר”. `bytes_updated_at` — מתי הקובץ עצמו
-- ‏השתנה לאחרונה (שיפור או טשטוש): הדפדפן שומר את התמונה במטמון
-- ‏לשעה לפי הכתובת, והחותמת נכנסת לכתובת כדי שתמונה שטושטשה לא
-- ‏תוצג עוד שעה עם הפנים שטושטשו.

ALTER TABLE "property_media"
  ADD COLUMN "enhanced_at" TIMESTAMP(3),
  ADD COLUMN "bytes_updated_at" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP;
