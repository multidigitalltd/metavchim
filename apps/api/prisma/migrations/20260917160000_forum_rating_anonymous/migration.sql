-- ‏מיגרציה `20260917140000_forum_rating_named` הסירה את העמודה הזו,
-- ‏מנימוק שנשאר נכון: חוות דעת היא אמירה על **העסק של מישהו אחר**,
-- ‏והוא זה שנושא את המחיר שלה.
--
-- ‏מה שהתברר הוא שהמחיר של הכלל ההפוך גבוה יותר. מתווך שעבד עם
-- ‏עורך דין או שמאי שמופיע גם אצל הקולגה ממול פשוט **אינו כותב** את
-- ‏חוות הדעת השלילית, והמדריך מתמלא בחמישה כוכבים בלבד — כלומר
-- ‏מפסיק להיות מדריך. ההכרעה כאן היא של בעל המוצר.
--
-- ‏מה שלא חוזר אחורה הוא האחריות, ולכן שתי עמודות ולא אחת:
--
-- ‏1. ‎`anonymous` — מה שמוצג. שורה אנונימית אינה נושאת `user_id`
-- ‏    ואינה נושאת `rater_tenant_id`, בדיוק כמו שרשור אנונימי
-- ‏    ב-`forum_threads`: „מוסתר” כאן פירושו שאין מה לחשוף.
--
-- ‏2. ‎`rater_ref` — ‏`tenantId:userId` **מוצפן במפתח הנתונים**, כמו
-- ‏    ‎`author_ref` בשרשור. הוא אינו נקרא בשום מסלול תצוגה; הוא
-- ‏    קיים כדי שהפלטפורמה תוכל לטפל בהתעללות חוזרת בלי שהזהות
-- ‏    תיחשף לאיש — ובלעדיו „אנונימי” היה גם „בלי אחריות”.
--
-- ‏`rater_key` (חותם HMAC) ממשיך לאכוף „דירוג אחד לכל מדרג” בשני
-- ‏המצבים, ולכן החלפה בין בשם לעילום שם מעדכנת שורה קיימת ואינה
-- ‏פותחת שנייה.
--
-- ‏השורות שהמיגרציה הקודמת מחקה אינן חוזרות — הן נמחקו, ואין ממה
-- ‏לשחזר אותן. ברירת המחדל `false` היא הנכונה לכל מה שנשמר מאז:
-- ‏הוא אכן נשמר בשם.
ALTER TABLE "forum_ratings" ADD COLUMN "anonymous" BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE "forum_ratings" ADD COLUMN "rater_ref" VARCHAR(255);
