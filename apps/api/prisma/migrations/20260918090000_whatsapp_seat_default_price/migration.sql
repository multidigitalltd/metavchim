-- ‎**המחיר למקום וואטסאפ נוסף — גם על מסלולים שכבר נשמרו.**
--
-- ‏`DEFAULT_PLANS` בקוד קיבל 4900 (49 ₪), אבל **ברירת מחדל אינה
-- ‏מגיעה למסלול שכבר נשמר**: `PlanCatalogService` ממזג שורה שמורה
-- ‏במקום ברירת המחדל **במלואה** (`stored.get(p.code) ?? p`), ולא
-- ‏שדה-שדה. כלומר מסלול שבעל הפלטפורמה שמר פעם אחת — ולו רק כדי
-- ‏לשנות תיאור — היה ממשיך לשאת `NULL` לנצח, וכפתור „הוספת מקום”
-- ‏לא היה מופיע אף שהקוד אומר שהוא נמכר.
--
-- ‏השורה הזו היא מה שהופך את השינוי בקוד למשהו שנראה במסך.
--
-- ‎**ארבעת הקודים המובנים בלבד, ולא „כל מסלול פעיל”.** קוד המסלול
-- ‏אינו רשימה סגורה (`PlanCodeSchema` הוא מחרוזת חופשית), ו-`load`
-- ‏מוסיף במפורש כל שורה שמורה שקודה אינו ב-`DEFAULT_PLANS` — כלומר
-- ‏בעל הפלטפורמה יכול לבנות מסלול משלו. שם `NULL` אינו „טרם נקבע”
-- ‏אלא **החלטה**: „המסלול הזה אינו מוכר מקומות נוספים”, בדיוק כפי
-- ‏שהסכימה מתעדת. מילוי גורף היה הופך את ההחלטה הזו להצעת רכישה
-- ‏ב-49 ₪ שאיש לא אישר למסלול הזה (ביקורת Codex, P1).
--
-- ‎`WHERE ... IS NULL` ולא עדכון גורף גם בתוך הארבעה: מסלול מובנה
-- ‏שבעל הפלטפורמה נקב בו מחיר — כל מחיר, גם נמוך יותר — הוא החלטה
-- ‏מסחרית שנעשתה, ומיגרציה אינה המקום לדרוס אותה.
--
-- ‎`retired_at IS NULL` כי מסלול פרוש אינו נמכר ממילא; מחיר עליו
-- ‏היה מבלבל את מי שיחזיר אותו לחיים מתישהו.
UPDATE "plans"
SET "whatsapp_seat_monthly_agorot" = 4900
WHERE "code" IN ('basic', 'pro', 'agency', 'enterprise')
  AND "whatsapp_seat_monthly_agorot" IS NULL
  AND "retired_at" IS NULL;
