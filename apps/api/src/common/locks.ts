import type { TenantTx } from "../core/prisma.service";

/**
 * נעילות ייעוץ ברמת הטרנזקציה (`pg_advisory_xact_lock`) — משתחררות
 * לבד ב-COMMIT או ב-ROLLBACK, ולכן אין מסלול שבו נעילה נשארת תקועה.
 *
 * ## סדר הנעילות — כרטיס לפני נכס
 *
 * שתי נעילות שונות במערכת נוגעות באותם שני עולמות: הנעילות שכאן,
 * על כרטיס איש קשר, ו-`SELECT … FOR UPDATE` על שורת נכס (מוכנות —
 * ראו `readiness.writer.ts`). טרנזקציה שנוגעת בשתיהן **חייבת לנעול
 * את הכרטיס ראשון.**
 *
 * זה לא סגנון אלא כשל אמיתי: מחיקת לקוח נועלת את הכרטיס ואז מנתקת
 * את הנכסים שהוא היה בעליהם, כלומר ממתינה לשורות שלהם. עריכת נכס
 * שנעלה קודם את השורה ואז ביקשה את הכרטיס סגרה מעגל, ו-Postgres
 * מפיל אחת מהשתיים — או שהעריכה נכשלת, או שבקשת מחיקה של אדם
 * נכשלת (ביקורת Codex).
 *
 * ## וגם: נכס לפני כל מה שתלוי בו
 *
 * אותו כלל בדיוק, בזוג הבא. העלאת תמונה ומחיקתה נועלות את שורת
 * הנכס ואז נוגעות בכל מה שנגזר ממנה — `property_media` והפרסום
 * ברשת (`syncPhotoKeys`). מחיקה לצמיתות ומחיקת משרד מחקו את
 * הנגזרות **לפני** הנכס, כלומר בסדר ההפוך, ולכן אותו deadlock
 * (ביקורת Codex).
 *
 * ‎**הניסוח הראשון של הכלל היה „נכס לפני המדיה”, וזה לא הספיק:**
 * הזזתי את הנעילה לפני מחיקת המדיה והשארתי לפניה את מחיקת
 * הפרסום — כלומר סגרתי מעגל אחד והשארתי את הבא (ביקורת Codex,
 * הסבב שאחריו). הכלל הנכון אינו „לפני טבלה X” אלא:
 *
 * ‎**נעילת הנכס היא הפעולה הראשונה בטרנזקציה שמוחקת אותו או את
 * נגזרותיו.** כשהיא ראשונה אין מה שיקדם לה, ואין צורך לדעת מראש
 * איזו טבלה מתנגשת עם מי.
 *
 * הסדר המלא, מלמעלה למטה: **כרטיס איש קשר → שורת נכס → כל מה
 * שתלוי בנכס** (מדיה, פרסום ברשת, התאמות, הצעות).
 */

/**
 * נעילת כרטיס איש קשר.
 *
 * הטבלאות שמצביעות על `contacts` עושות זאת בעמודה סקלרית בלי מפתח זר
 * (זו הדרישה של RLS רב-דיירי כאן), ולכן המסד **אינו** מונע מחיקת
 * כרטיס שרשומה חדשה בדיוק התחילה להצביע עליו. בלי הנעילה הזו, ליד
 * נכנס מאותו טלפון שמגיע בזמן שמוחקים ליד זבל היה יכול להיווצר
 * ולהצביע על כרטיס שנמחק שבריר שנייה אחריו — כלומר ליד שאי אפשר
 * לפתוח.
 *
 * הכלל: **כל מי שמוחק כרטיס וכל מי שממחזר כרטיס קיים** נועל אותו
 * קודם, ומי שממחזר קורא אותו שוב אחרי הנעילה. קריאה חוזרת שמחזירה
 * `null` פירושה שהכרטיס נמחק בינתיים — ואז נוצר כרטיס חדש במקומו.
 */
export async function lockContact(tx: TenantTx, contactId: string): Promise<void> {
  await tx.$executeRaw`SELECT pg_advisory_xact_lock(hashtextextended(${`contact:${contactId}`}, 0))`;
}

/**
 * נעילת **מספר** — לפני שידוע אם יש לו כרטיס.
 *
 * `lockContact` נועלת כרטיס קיים, ולכן היא חסרת תועלת בדיוק במקרה
 * שבו שני נתיבים יוצרים את **אותו** אדם בו-זמנית: שניהם קוראים „אין
 * כרטיס למספר הזה”, שניהם כותבים, והאינדקס הייחודי
 * `(tenant_id, phone_hash)` מפיל את השני. בתוך טרנזקציה זו אינה
 * שגיאה שאפשר לתפוס — משפט שנכשל מבטל את הטרנזקציה כולה (`25P02`),
 * ולכן הפנייה כולה נופלת.
 *
 * זה אינו תרחיש תיאורטי: טופס פתוח שנשלח פעמיים, ליד מוובהוק שמגיע
 * במקביל לשיחה נכנסת מאותו מספר, ושתי לשוניות פתוחות — כולם מגיעים
 * לאותה שורה מאותו מספר.
 *
 * הנעילה נלקחת **לפני** החיפוש, ולכן מי שמגיע שני רואה את הכרטיס
 * שהראשון יצר במקום ליצור שני. סדר הנעילות קבוע — מספר, ואז כרטיס —
 * ומי שמוחק נועל כרטיס בלבד, ולכן אין מעגל המתנה.
 *
 * הדייר במפתח: אותו מספר יכול להיות לקוח של שני משרדים, ואלה שני
 * כרטיסים שונים לגמרי.
 */
export async function lockContactPhone(
  tx: TenantTx,
  tenantId: string,
  phoneHash: string,
): Promise<void> {
  await tx.$executeRaw`SELECT pg_advisory_xact_lock(hashtextextended(${`phone:${tenantId}:${phoneHash}`}, 0))`;
}

/**
 * נעילת בקשת טופס — לקישור הפתוח בלבד.
 *
 * הקישור הפתוח יוצר את הכרטיס בשליחה, ולכן שתי שליחות שלו יוצרות
 * שני כרטיסים לאותו אדם. `lockContactPhone` אינה מספיקה כאן: היא
 * מסדרת את יצירת **איש הקשר**, בעוד השאלה היא אם כבר נוצר **קונה**
 * ואם שורת הבקשה כבר מצביעה עליו.
 */
export async function lockIntakeRequest(
  tx: TenantTx,
  tenantId: string,
  requestId: string,
): Promise<void> {
  await tx.$executeRaw`SELECT pg_advisory_xact_lock(hashtextextended(${`intake:${tenantId}:${requestId}`}, 0))`;
}

/**
 * נעילת שיחה לפי מזהה הספק — סדרוּר של פניות חוזרות מהמרכזייה.
 *
 * קליטת אירוע היא קרא־ואז־כתוב: מחפשים שורת שיחה עם אותו
 * `provider_call_id`, וכותבים רק אם אין. מרכזייה ששולחת את אותו
 * אירוע פעמיים — כי לא קיבלה 200, או סתם — יכולה לשלוח את שתי
 * הפניות במקביל, ואז שתיהן קוראות „אין” ושתיהן כותבות.
 *
 * מפתח זר או אילוץ ייחודיות על `(tenant_id, provider_call_id)` לא
 * יעזרו כאן: העמודה ריקה לשיחות ידניות ולהקלטות פגישה, ואילוץ
 * חלקי היה מפיל את הקליטה בשגיאה במקום להתעלם ממנה בשקט. הנעילה
 * מסדרת את שתי הפניות זו אחר זו, והשנייה רואה את מה שהראשונה
 * כתבה.
 *
 * הדייר נכלל במפתח: `provider_call_id` ייחודי אצל הספק, לא אצלנו,
 * ושני משרדים באותה מרכזייה יכולים לקבל אותו מזהה.
 */
export async function lockProviderCall(
  tx: TenantTx,
  tenantId: string,
  providerCallId: string,
): Promise<void> {
  await tx.$executeRaw`SELECT pg_advisory_xact_lock(hashtextextended(${`call:${tenantId}:${providerCallId}`}, 0))`;
}

/**
 * נעילת שורת נכס — נקודת הסנכרון של כל מי שכותב מוכנות או מוחק מדיה.
 *
 * ‎`readiness_score` נגזר גם ממה שאינו בשורה עצמה — תמונות יושבות
 * בטבלה אחרת — ולכן שתי טרנזקציות שקוראות „יש תמונות” ומוחקות כל
 * אחת את התמונה שלה משאירות ציון שמתאר מצב שכבר אינו קיים. הנעילה
 * מסדרת אותן זו אחר זו.
 *
 * ‎**זו גם הנעילה הראשונה בסדר מול המדיה** — ראו ההערה בראש הקובץ.
 * נכס שכבר נמחק אינו שגיאה: אין שורה לנעול, והקורא ייכשל מיד אחר כך
 * על היעדרה.
 */
export async function lockProperty(
  tx: TenantTx,
  tenantId: string,
  propertyId: string,
): Promise<void> {
  await tx.$queryRaw`SELECT id FROM properties WHERE id = ${propertyId} AND tenant_id = ${tenantId} FOR UPDATE`;
}

/**
 * נעילת **כל** נכסי המשרד — למחיקת משרד בלבד.
 *
 * מחיקת משרד מוחקת את המדיה ואז את הנכסים, כלומר בסדר ההפוך
 * ל-`lockProperty` שלוקחת העלאה או מחיקת תמונה. סוכן שמוחק תמונה
 * ברגע שהמשרד נמחק היה סוגר מעגל. הקבוצה חסומה — נכסיו של משרד
 * אחד — והמיון לפי מזהה קובע סדר יציב גם בין שתי מחיקות משרד
 * שרצות במקביל.
 */
export async function lockTenantProperties(
  tx: TenantTx,
  tenantId: string,
): Promise<void> {
  await tx.$queryRaw`SELECT id FROM properties WHERE tenant_id = ${tenantId} ORDER BY id FOR UPDATE`;
}
