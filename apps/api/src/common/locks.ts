import type { TenantTx } from "../core/prisma.service";

/**
 * נעילות ייעוץ ברמת הטרנזקציה (`pg_advisory_xact_lock`) — משתחררות
 * לבד ב-COMMIT או ב-ROLLBACK, ולכן אין מסלול שבו נעילה נשארת תקועה.
 */

/**
 * נעילת כרטיס איש קשר.
 *
 * הטבלאות שמצביעות על `contacts` עושות זאת בעמודה סקלרית בלי מפתח זר
 * (זו הדרישה של RLS רב-דיירי כאן), ולכן המסד **אינו** מונע מחיקת
 * כרטיס שרשומה חדשה בדיוק התחילה להצביע עליו. בלי הנעילה הזו, ליד
 * נכנס מאותו טלפון שמגיע בזמן שמוחקים ליד זבל היה יכול להיווצר
 * ולהצביע על כרטיס שנמחק שבריר שנייה אחריו — כלומר ליד שאי אפשר
 * לפתוח.
 *
 * הכלל: **כל מי שמוחק כרטיס וכל מי שממחזר כרטיס קיים** נועל אותו
 * קודם, ומי שממחזר קורא אותו שוב אחרי הנעילה. קריאה חוזרת שמחזירה
 * `null` פירושה שהכרטיס נמחק בינתיים — ואז נוצר כרטיס חדש במקומו.
 */
export async function lockContact(tx: TenantTx, contactId: string): Promise<void> {
  await tx.$executeRaw`SELECT pg_advisory_xact_lock(hashtextextended(${`contact:${contactId}`}, 0))`;
}
