import { WHATSAPP_SEAT_LIVE_STATUSES } from "@metavchim/shared";

/**
 * ‎**אילו שורות מקום נספרות במכסה — תנאי אחד, לכל הסופרים.**
 *
 * ארבעה מקומות סופרים מקומות בתשלום: מסך ההגדרות, אכיפת ההקצאה,
 * שער הפלטפורמה, וסגירת מקום שפג. ארבעה עותקים של התנאי הם ארבעה
 * מקומות שייפרדו ביום שהתנאי משתנה — וזה בדיוק מה שקרה: כולם בדקו
 * ‎`active | past_due`, ולכן **מקום שבוטל נעלם מהמכסה מיד**, למרות
 * שהביטול מבטיח שהוא יישאר עד תום התקופה ששולמה.
 *
 * התוצאה הייתה משרד שרואה פחות מקומות ממה ששילם עליהם, ובעל משרד
 * שכיבה מחזיק כדי להעביר מקום **ששולם** נחסם בהקצאה החוזרת (ביקורת
 * Codex).
 *
 * ‎`now` נמסר ואינו נלקח מהשעון כאן: הסופרים רצים בתוך טרנזקציה עם
 * נעילה, ושתי קריאות לשעון באותה בדיקה הן שתי מכסות שונות.
 */
export function whatsappSeatQuotaWhere(tenantId: string, now: Date) {
  return {
    tenantId,
    OR: [
      { status: { in: [...WHATSAPP_SEAT_LIVE_STATUSES] } },
      /*
       * מקום שבוטל וטרם פג. `null` בתקופה = מעולם לא שולם (ביטול
       * לפני תשלום), ואז אין מה לספור.
       */
      { status: "cancelled", currentPeriodEnd: { gt: now } },
    ],
  };
}
