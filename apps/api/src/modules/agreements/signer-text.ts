import { z } from "zod";

/**
 * ‎**טקסט שהחותם מזין — שורה אחת, ובלי תווים שמשנים את מראה המסמך.**
 *
 * ‏שם, כתובת, תיאור הנכס והמחיר נכנסים לגוף ההסכם כמות שהם, והמסמך
 * ‏מוצג עם ירידות השורה שלו. ירידת שורה בשדה הייתה מאפשרת לחותם להוסיף
 * ‏למסמך שהוא עצמו חותם עליו שורות שנראות כמו סעיפים — „5. דמי התיווך
 * ‏בטלים” — והגיבוב היה מעיד שזה מה שנחתם. השדות במסך הם `<input>` של
 * ‏שורה אחת, אבל הבקשה עצמה אינה עוברת דרך המסך בהכרח; השער כאן.
 *
 * ‏נחסמים:
 * ‏- תווי בקרה (`\p{Cc}`): ירידות שורה, טאב, NUL.
 * ‏- מפרידי שורה ופסקה של Unicode‏ (U+2028, U+2029) — ירידת שורה בשם אחר.
 * ‏- תווי כיווניות שמחליפים סדר תצוגה (U+202A–U+202E, U+2066–U+2069) —
 * ‏  טקסט שנקרא אחרת ממה שנשמר.
 * ‏- ‏U+2060 (WORD JOINER) — הסימון של שורות המילוי (`SIGNER_BLANK`).
 *
 * ‏סימני כיוון רגילים (RLM/LRM) וצירופי אמוג'י מותרים: מקלדות מוסיפות
 * ‏אותם, והם אינם משנים סדר.
 */
const SIGNER_LINE = /^[^\p{Cc}\p{Zl}\p{Zp}⁠‪-‮⁦-⁩]*$/u;

export function signerText(min: number, max: number) {
  return z
    .string()
    .min(min)
    .max(max)
    .regex(SIGNER_LINE, "יש להזין שורה אחת, בלי ירידות שורה או תווים מיוחדים");
}
