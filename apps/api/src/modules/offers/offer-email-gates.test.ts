import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

/**
 * ‎**שער שחל על מסלול אחד ולא על הניסיון החוזר שלו.**
 *
 * הזכאות הראשונית של ההצעות האוטומטיות דורשת נכס `active` שאינו
 * מחוק. הניסיון החוזר — שרץ על הצעות שנשארו `pending_email` אחרי
 * פסק זמן או תקלת ספק — בדק את **הלקוח** בלבד (הסרה מרשימת
 * התפוצה), ולא את הנכס.
 *
 * התוצאה: שליחה שנכשלה, הנכס נמכר, והסבב הבא שלח בכל זאת. הלקוח
 * מקבל הצעה על דירה שהמשרד כבר משך — ומאז שהשליחה מתעדת פעולת
 * שיווק, גם נרשמת פעולה על נכס שהוסר (ביקורת Codex).
 *
 * ‎**מה הבדיקה מחזיקה:** לא את הניסוח, אלא את **קיומו של השער בשני
 * המסלולים**. זו משפחת התקלות שחוזרת כאן — תנאי שנכתב פעמיים ואחד
 * העותקים נשאר מאחור — ובדיקה מבנית היא הדרך הזולה לתפוס אותה.
 *
 * אין הרנס בדיקות ל-`OfferEmailService` (Prisma, RLS, ספק דואר),
 * ולכן זו בדיקה על המקור — כמו `match-created-at` ו-`office-names`.
 */

const RAW = readFileSync(join(import.meta.dirname, "offer-email.service.ts"), "utf8");

/**
 * ‎**הקוד בלי ההערות — והסיבה שזה כאן ולא בכל טענה בנפרד.**
 *
 * הקובץ הזה מתעד למה כל שער קיים, ולכן ההערות שלו נוקבות במפורש
 * בדיוק במה שהטענות מחפשות: `optedOutAt`, `hasSigned`, `draft`.
 * שלוש פעמים בסבב אחד עברה כאן טענה **על ההערה של עצמה** — הקוד
 * הוסר, הפרוזה שמסבירה אותו נשארה, והשער נשאר ירוק ולא שמר על דבר.
 *
 * תיקון פרטני לכל טענה („חפש `signedPairs(` ולא `signedPairs`”)
 * מטפל במופע ולא במחלקה, וכל טענה חדשה מתחילה מאפס. הפשטת ההערות
 * פעם אחת סוגרת את הדלת לכולן.
 *
 * ‎`//` מוסר רק כשהוא שורה שלמה, כדי ש-`https://` בתוך מחרוזת לא
 * ייחתך באמצע.
 */
const SOURCE = RAW.replace(/\/\*[\s\S]*?\*\//gu, "").replace(/^[ \t]*\/\/.*$/gmu, "");

/** גוף פונקציה פרטית אחת, עד הפונקציה הבאה באותה רמת הזחה. */
function body(name: string): string {
  const start = SOURCE.indexOf(`private async ${name}(`);
  expect(start, `${name} לא נמצאה בקובץ`).toBeGreaterThan(-1);
  const rest = SOURCE.slice(start + 1);
  const end = rest.search(/\n {2}(?:private|public|async)/u);
  return end === -1 ? rest : rest.slice(0, end);
}

/**
 * ‎**תנאי ה-`where` של שאילתת ה**נכסים** בלבד — ולא של הפונקציה.**
 *
 * הניסוח הראשון של הבדיקה הזו חיפש `deletedAt: null` בכל גוף
 * הפונקציה, והוא נמצא שם — על שאילתת ה**קונה**. כלומר הבדיקה עברה
 * גם כשהסרתי את התנאי מהנכס: שער שנראה ירוק ואינו שומר על דבר,
 * שהוא בדיוק סוג הבדיקה שהקובץ הזה קיים כדי למנוע. אומת בשבירה.
 */
function propertyWhere(fn: string): string {
  const match = /tx\.property\.find(?:First|Many)\(\{[\s\S]*?\n {12}\},/u.exec(body(fn));
  expect(match, `${fn}: אין שאילתת נכסים כלל`).not.toBeNull();
  return match![0];
}

describe("שער הנכס בהצעות האוטומטיות", () => {
  it("הזכאות הראשונית דורשת נכס פעיל שאינו מחוק", () => {
    const where = propertyWhere("scanBatch");
    expect(where).toContain('status: "active"');
    expect(where).toContain("deletedAt: null");
  });

  /*
   * ‎**וזה הצד שנשבר.** בין היצירה לניסיון החוזר עוברות עשר דקות
   * לפחות, ובהן הנכס יכול להימכר, לרדת לטיוטה או להימחק.
   */
  it("והניסיון החוזר בודק אותו שוב", () => {
    const where = propertyWhere("retryPending");
    expect(where).toContain('status: "active"');
    expect(where).toContain("deletedAt: null");
  });

  /*
   * ‎**וגם את הלקוח** — הבדיקה שכן הייתה שם. אילו הייתי מחליף אותה
   * בבדיקת הנכס במקום להוסיף לצידה, הבדיקה שמעל הייתה עוברת.
   */
  it("ואת ההסרה מרשימת התפוצה", () => {
    expect(body("retryPending")).toContain("optedOutAt");
  });

  /*
   * ‎**ההסרה מרשימת התפוצה נבדקת בשני המסלולים.**
   *
   * ‎`eligibleMatches` בונה תמונת מצב של „מי ניתן להשגה”, ובין הרגע
   * ההוא לרגע היצירה הלקוח יכול ללחוץ על קישור ההסרה.
   * ‎`ContactsService.getById` אינו שולף `optedOutAt` — הוא מפענח שם,
   * טלפון ואימייל בלבד — ולכן הבדיקה במסלול היצירה **נראתה קיימת
   * ולא הייתה**: המייל יצא ללקוח שכבר הסיר את עצמו, בניגוד לחוק
   * התקשורת §30א (ביקורת Codex).
   */
  it("שני המסלולים קוראים את ההסרה מהמסד, ולא נשענים על getById", () => {
    for (const fn of ["scanBatch", "offerAndEmail", "retryPending"]) {
      expect(body(fn), fn).toContain("optedOutAt");
    }
  });

  /*
   * ‎**„טיוטה” אינה נכללת באוטומציה, וזו הסיבה שלא נעשה כאן שימוש
   * חוזר ב-`offerPropertyMarketable`.** הוא מתיר `draft | active`,
   * כי מתווך רשאי להציע טיוטה במודע; האוטומציה משווקת רק מה שהמשרד
   * סימן פעיל. שימוש חוזר בו היה מרחיב את האוטומציה בשקט.
   */
  it("האוטומציה אינה משווקת טיוטות", () => {
    for (const fn of ["scanBatch", "retryPending"]) {
      expect(body(fn), fn).not.toMatch(/status:\s*\{\s*in:\s*\[[^\]]*"draft"/u);
    }
  });
});

/**
 * ‎**עבודה חסומה בתוך טרנזקציה.**
 *
 * שער ההחתמה נבדק לכל מועמד בנפרד (`hasSigned` — שתי שאילתות
 * לקריאה), בלולאה, בתוך טרנזקציה אחת. מספר המועמדים לא היה חסום:
 * ייבוא או חישוב-מחדש המוני מייצרים אלפי התאמות חזקות, ותקרת
 * עשרים הלקוחות שבהמשך אינה חוסמת זאת — היא חלה **אחרי**. משרד
 * אחד היה מחזיק טרנזקציה פתוחה לאלפי שאילתות כל עשר דקות ומעכב
 * את כל השאר (ביקורת Codex).
 */
describe("חסימת העבודה בסבב", () => {
  it("שער ההחתמה נבדק בקבוצה ולא בלולאה", () => {
    const batch = body("scanBatch");
    expect(batch).toContain("signedPairs(");
    expect(batch).not.toContain("hasSigned");
  });

  it("הסריקה חסומה", () => {
    expect(body("eligibleMatches")).toContain("MAX_MATCH_SCAN_PER_SWEEP");
  });

  /*
   * ‎**החסימה היא על הסריקה ולא על הבחירה — וזה ההבדל כולו.**
   *
   * הניסוח הקודם היה `take` דטרמיניסטי על מיון לפי ציון. משרד עם 400
   * התאמות חזקות שאינן זכאות לצמיתות — לקוחות שלא חתמו, או שהסירו את
   * עצמם — קיבל בכל סבב את **אותן** 400, והתאמות זכאות בציון נמוך
   * יותר לא הגיעו לעיבוד לעולם (ביקורת Codex).
   *
   * הסמן שובר את זה רק אם הוא מתקדם גם כשאף שורה במנה לא נבחרה.
   */
  it("הסמן מתקדם לפי מה שנסרק, לא לפי מה שנבחר", () => {
    const batch = body("scanBatch");
    // הסמן נלקח מהשורות שחזרו מהשאילתה, ולא מהרשימה המסוננת
    expect(batch).toMatch(/cursor:\s*candidates\[candidates\.length - 1\]/u);
    expect(batch).not.toMatch(/cursor:\s*batch\[/u);
  });

  /*
   * מיון לפי ציון בלבד אינו ייחודי, ובלי שובר שוויון יציב הסמן אינו
   * מוגדר היטב — שורות היו נדלגות או חוזרות בין מנות.
   */
  it("המיון נושא שובר שוויון יציב", () => {
    expect(body("scanBatch")).toMatch(/orderBy:\s*\[\{ score: "desc" \}, \{ id: "asc" \}\]/u);
  });

  /*
   * ‎**וחיתוך נאמר בקול.** מגבלה שקטה נקראת כמו „זה הכול”, וזה בדיוק
   * הכשל שהמערכת הזו חוזרת ומגנה מפניו — תשובה שנראית מלאה ומדברת
   * על שאלה אחרת. אותו נימוק כמו בוויסות הלקוחות שכבר מדווח.
   */
  it("והחיתוך מדווח", () => {
    expect(body("eligibleMatches")).toContain("this.logger");
  });
});

/**
 * ‎**הסמן חוצה סבבים — ושלוש גרסאות נכשלו בזה.**
 *
 * ‎`take` דטרמיניסטי בחר את אותן 400 שורות בכל סבב. סמן מקומי אותחל
 * ל-`undefined` בכל קריאה, כלומר אותה הרעבה בגודל 2,000. **ובשתיהן
 * כתבתי ביומן משפט שאינו נכון** — „השאר בסבב הבא”, „הסמן יימשך בסבב
 * הבא” — ושתיהן נתפסו רק בביקורת (שתי ביקורות Codex על אותו קוד).
 *
 * מה שהופך את זה לניתן לבדיקה מבנית: הסמן חייב **להיכנס** לפונקציה
 * ולצאת ממנה, ולהישמר. סמן שנולד ומת בתוך קריאה אחת אינו סמן.
 */
describe("הסמן בין סבבים", () => {
  it("הסמן מגיע מבחוץ ואינו מאותחל בפנים", () => {
    const scan = body("eligibleMatches");
    expect(scan).toContain("startCursor");
    // `let cursor: string | undefined;` — האתחול שהחזיר את ההרעבה
    expect(scan).not.toMatch(/let cursor:\s*string \| undefined;/u);
  });

  it("והוא מוחזר לשמירה", () => {
    expect(body("eligibleMatches")).toContain("nextCursor");
  });

  /*
   * ‎**נשמר גם כשלא נשלח דבר.** דווקא סבב שכולו לא-זכאי חייב להתקדם;
   * שמירה מותנית בשליחה הייתה משחזרת את ההרעבה במדויק.
   */
  it("הסבב שומר את הסמן ללא תנאי", () => {
    const sweep = body("sweepTenant");
    expect(sweep).toContain("saveCursor(");
    expect(sweep).not.toMatch(/if\s*\([^)]*\)\s*await this\.saveCursor/u);
  });

  /*
   * ‎**כתיבה של שדה אחד ולא של ההגדרות כולן.** `settings` נשמר
   * במלואו מהמסך, וקריאה-שינוי-כתיבה מהסבב הייתה דורסת שינוי שבעל
   * המשרד עשה באותן עשר דקות.
   */
  it("השמירה נוגעת במפתח אחד בלבד", () => {
    const save = body("saveCursor");
    expect(save).toContain("jsonb_set");
    expect(save).toContain("COALESCE");
    expect(save).not.toContain("tenant.update");
  });
});

/**
 * ‎**מה שלא טופל אינו נחשב לטופל.**
 *
 * הסמן קודם לסוף המנה גם כשהמנה הכילה יותר קונים ממה שהסבב שולח
 * אליהם. מנה עם 30 קונים זכאים נצברה במלואה, נשלח ל-20, והעשרה
 * הנותרים דולגו עד שהסמן יסיים סיבוב שלם (ביקורת Codex) — כלומר
 * ההרעבה שהסמן בא לפתור, בקנה מידה קטן יותר.
 */
describe("הסמן והקונים שנדחו", () => {
  it("הצבירה נעצרת בתקרת הקונים", () => {
    const scan = body("eligibleMatches");
    expect(scan).toMatch(/buyersFound\.size >= MAX_BUYERS_PER_TENANT_SWEEP/u);
    expect(scan).toContain("deferred");
  });

  /*
   * ‎**התאמה נוספת של קונה שכבר נאסף אינה נחסמת** — היא נשלחת באותו
   * מייל ואינה מוסיפה נמען. חסימה שלה הייתה מפצלת לקוח לשני סבבים
   * ולשני מיילים, שזו בדיוק הקיבוץ שהסבב קיים בשבילו.
   */
  it("קונה שכבר נאסף אינו שובר את המנה", () => {
    expect(body("eligibleMatches")).toContain("!buyersFound.has(row.buyerId)");
  });

  /*
   * וכשנעצרנו — הסמן מצביע על השורה האחרונה **שנלקחה**, לא על סוף
   * המנה. אחרת הקונה שנדחה נמצא מאחורי הסמן, וזה בדיוק הדילוג.
   */
  it("הסמן מצביע על מה שנלקח ולא על סוף המנה", () => {
    expect(body("eligibleMatches")).toMatch(/cursor = deferred \? \(lastTaken \?\? cursor\)/u);
  });
});

/**
 * ‎**הסמן והחותמת שייכים לאותה תקופת הפעלה — בשני קבצים.**
 *
 * ‎`autoEmailOffersSince` נמחק בכיבוי, כדי שהדלקה מחדש תפתח קו
 * „מכאן והלאה” נקי. הסמן נוסף מאוחר יותר, בקובץ אחר, ולא הצטרף
 * למחיקה: הדלקה מחדש קיבלה חותמת חדשה ו**מיקום סריקה ישן**.
 * ההתאמות החדשות נכנסות לפי ציון, כלומר לפני הסמן — והן דולגו עד
 * שהסורק יסיים סיבוב שלם (ביקורת Codex).
 *
 * זו בדיוק משפחת הצימוד שבדיקה מבנית זולה תופסת: שני שדות שחייבים
 * לחיות ולמות יחד, ונכתבים במקומות שונים.
 */
describe("איפוס הסמן בכיבוי", () => {
  const SETTINGS = readFileSync(
    join(import.meta.dirname, "..", "settings", "settings.controller.ts"),
    "utf8",
  );

  it("הקובץ נקרא ומכיל את הכיבוי — אחרת הבדיקה בודקת מחרוזת ריקה", () => {
    expect(SETTINGS).toContain('delete settings["autoEmailOffersSince"]');
  });

  it("הכיבוי מוחק גם את הסמן", () => {
    expect(SETTINGS).toContain('delete settings["autoEmailOffersCursor"]');
  });

  /*
   * והשם זהה בשני הצדדים: מפתח שיישתנה בקובץ אחד ולא בשני היה
   * משאיר מחיקה שאינה מוחקת דבר — שורה שנראית כמו כיסוי.
   */
  it("אותו מפתח בדיוק שהסורק קורא וכותב", () => {
    expect(SOURCE).toContain("autoEmailOffersCursor");
  });
});
