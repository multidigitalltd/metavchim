import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

/**
 * ‎**„ההקלטה בדרך מהמרכזייה” שנמשך שעות — ולא מגיע.**
 *
 * ## ‏מה קרה
 *
 * ‏מהשטח: „יש לי שיחות שהכיתוב ההקלטה בדרך מהמרכזייה מופיע כבר
 * ‏הרבה שעות וזה לא מגיע בפועל”.
 *
 * ‎`recordingStateOf` קוראת „ממתינה” לצירוף **אין מפתח, יש נתיב,
 * ‏ואין סיבת כישלון רשומה**. כל מסלול כישלון מוכר בסבב רושם סיבה
 * ‏בעצמו, ולכן הצירוף הזה אמור להימשך דקות — אלא שחריגה בלתי
 * ‏צפויה בתוך המשיכה עקפה את כולם: הסבב תפס אותה, כתב שורת יומן,
 * ‏והשאיר את השורה **נקייה מסיבה**. כלומר בדיוק „ממתינה”, שוב
 * ‏ושוב, בכל סבב.
 *
 * ## ‏למה מבנית
 *
 * ‏מה שנשבר כאן אינו חישוב אלא **שורה חסרה במסלול שאין לו בדיקה
 * ‏טבעית**: `catch` שמחזיר ערך ואינו כותב. אפשר להסיר אותה בלי
 * ‏שדבר ייכשל, והתוצאה תיראה בדיוק כמו קודם — מסך שמבטיח ואינו
 * ‏מקיים.
 */

const service = readFileSync(new URL("./recording-fetch.service.ts", import.meta.url), "utf8");
const shared = readFileSync(
  new URL("../../../../../packages/shared/src/logic/recording-state.ts", import.meta.url),
  "utf8",
);

describe("כישלון שקט אינו נראה כהמתנה", () => {
  it("חריגה בלתי צפויה בסבב נרשמת על השורה, ולא רק ביומן", () => {
    expect(service).toContain("await this.note(job, RECORDING_ERRORS.unexpected);");
    expect(service).toContain('unexpected: "unexpected_error"');
  });

  /*
   * ‏הקוד שנרשם חייב להיות **מוכר לניסוח**. קוד בלי `case` נופל
   * ‏ל„הסיבה אינה ידועה” — כלומר בדיוק מה שנאמר על היעדר סיבה,
   * ‏והמסך חוזר להיות חסר אבחנה.
   */
  it("והקוד שנרשם הוא קוד שיש לו ניסוח", () => {
    expect(shared).toContain('case "unexpected_error":');
  });

  /*
   * ‎**וגם כשהכתיבה עצמה נכשלת — ההבטחה פגה.**
   *
   * ‎`note` בולעת את שגיאתה בכוונה (כישלון רישום אינו אמור לעצור
   * ‏את הסבב), ולכן התיקון שלמעלה אינו ערובה מלאה: שורה יכולה
   * ‏להישאר „נוסתה ואין סיבה” גם אחריו. שם „בדרך” מפסיק להיות
   * ‏מצב נצחי — אחרי שעה, שהיא כפול מהניסיון החוזר הארוך ביותר,
   * ‏המסך אומר „לא קיבלנו תשובה” במקום לנקוב בזמן.
   */
  it("ומעבר לחלון הניסיון החוזר המסך מפסיק לנקוב בזמן", () => {
    expect(shared).toContain("const attemptAt = row.providerRecordingAttemptAt ?? null;");
    expect(shared).toContain(
      'if (attemptAt !== null && now - attemptAt.getTime() > RECORDING_YOUNG_CALL_MS) {',
    );
  });
});
