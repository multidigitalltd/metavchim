/* ==========================================================================
 * ‎**2 · עמוד הנכסים: הפעולות מעל הטבלה, והמונים לצד החיפוש.**
 *
 * ‏שתי בקשות של בעל המוצר על אותו מסך, ושתיהן על מקום:
 *
 * ‎**הפעולות.** סרגל הבחירה ישב בתחתית הכרטיס, מתחת לשורות. עם שש
 * שורות זה עבד; עם מאה נכסים המתווך מסמן שורה בראש הרשימה וגולל
 * עמוד שלם כדי להגיע לכפתור שיפעל עליה — „כשיש הרבה נכסים זה פשוט
 * לא נוח”. ההערה שהייתה שם נימקה את המיקום הישן במילים שלה, וזה
 * בדיוק הסוג של נימוק שמחזיר את הסרגל למטה בקריאה הבאה.
 *
 * ‎**המונים.** ארבעה אריחים ברוחב מלא מתחת לכרטיס חיפוש ברוחב מלא
 * דחקו את השורה הראשונה אל מתחת לקיפול, במסך שכל תפקידו הרשימה.
 * ========================================================================== */

/** מיקום יחיד ומחייב בעמוד הנכסים. */
function onlyIn(code, needle, what, where) {
  const first = code.indexOf(needle);
  if (first === -1) {
    problems.push(`${what} לא נמצא ב${where} (חיפשתי \`${needle}\`)`);
    return null;
  }
  if (code.indexOf(needle, first + 1) !== -1) {
    problems.push(`${what} מופיע יותר מפעם אחת ב${where}`);
    return null;
  }
  return first;
}

