"use client";

import { IconWarning } from "./icons";

/**
 * פעולות שאין מהן חזרה — **במקום אחד, בתחתית, ומקופלות.**
 *
 * מחיקת הכרטיס ומחיקת הלקוח ישבו בשני מקומות שונים בכרטיס: אחת
 * בתוך רשימת אנשי הקשר ואחת בתחתית הטור. שתיהן הוצגו פתוחות, עם
 * טקסט אדום, בעוד סוכן פותח את הכרטיס עשרות פעמים ביום כדי לקרוא
 * דרישות לפני שיחה — ובכל פעם קיבל שתי אזהרות אדומות על פעולות
 * שהוא מבצע פעם בשנה.
 *
 * שלוש החלטות, וכולן נובעות מאותה עובדה:
 *
 * - **יחד.** שתי המחיקות הן אותה שאלה — "מה אני מוריד מכאן" —
 *   וכשהן פזורות המשתמש לא רואה שיש בחירה ביניהן.
 * - **בתחתית.** אחרי כל התוכן, ולא בין השדות. מי שמחפש אותן מגלגל;
 *   מי שלא, לא נתקל בהן.
 * - **מקופל.** `details` ולא פתוח: לחיצה אחת מפרידה בין קריאה
 *   שגרתית לפעולה הרסנית, וזה בדיוק הרווח שהיה חסר.
 *
 * ה-`summary` נשאר בגוון הטקסט הרגיל ולא באדום. אדום במצב סגור אינו
 * אזהרה אלא רעש — אין עדיין מה להזהיר מפניו; האזהרה האמיתית מחכה
 * בפנים, ליד הכפתור שבאמת מוחק.
 */
export function DangerZone({ children }: { children: React.ReactNode }) {
  return (
    <details className="mv-danger-zone">
      <summary>
        <IconWarning s={14} /> פעולות מחיקה
      </summary>
      <div className="mv-danger-zone-body">{children}</div>
    </details>
  );
}
