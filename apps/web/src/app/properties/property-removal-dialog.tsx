"use client";

import { useEffect, useState } from "react";
import { ConfirmDialog } from "../confirm-dialog";
import { Notice } from "../notice";

/**
 * ‎**„למחוק?” — שאלה אחת, שני מקומות ששואלים אותה.**
 *
 * ‏הכרטיס מוחק נכס אחד; הרשימה מוחקת את מה שסומן. הפעולות שונות
 * ‏(נתיב יחיד מול נתיב אצווה), אבל **השאלה זהה** — אותה אזהרה,
 * ‏אותה חלופה, אותו כלל „אין אישור לפני שהגילוי הגיע”. שני חלונות
 * ‏היו נפרדים ביום שאחד מהם מתוקן, ולכן הניסוח והכללים יושבים כאן
 * ‏פעם אחת והקוראים מוסרים רק את מה שבאמת שונה: כמה, ומה לעשות.
 *
 * ## ‏שלוש יציאות, ולא שתיים
 *
 * ‏„למחוק?” היא שאלה שהתשובה השימושית לה לרוב אינה „כן” ואינה
 * ‏„ביטול” אלא **„לא, רק להוציא מהרשימה”**. כשהחלופה אינה בחלון,
 * ‏מי שהתכוון אליה סוגר, מחפש אותה במקום אחר, ולעיתים מוותר ומוחק.
 *
 * ‏ה-`X` בפינה ולא כפתור „ביטול” שלישי: שלוש מילים באותה שורה
 * ‏נקראות כשלוש אפשרויות שקולות, וטשטוש כזה על פעולה שאינה הפיכה
 * ‏הוא בדיוק מה שאסור כאן.
 *
 * ## ‏הגילוי לפני האישור
 *
 * ‏מחיקה לצמיתות מוחקת גם **כרטיס של אדם** שהנכס הוא העוגן היחיד
 * ‏שלו — שם, טלפונים והיסטוריית תקשורת. מתווך שמנקה כפילות אינו
 * ‏מתכוון לזה, ולכן השאלה נשאלת בשרת ברגע שהחלון נפתח והתשובה
 * ‏מוצגת לפני שאפשר לאשר.
 *
 * ‎**וכישלון הבדיקה אינו „לא יימחק אף כרטיס”.** שלושה מצבים ולא
 * ‏שניים — נטען, ידוע, ולא ידוע — כי „כל מה שאינו מספר = אפס” היה
 * ‏מבטיח שקט בדיוק כשאין לנו מושג. במצב „לא ידוע” האישור נשאר
 * ‏חסום: זו ההכרעה שכבר נקבעה גם במסך הקונים.
 */

/** ‎`"loading"` עד שהשרת ענה; `"unknown"` כשהבדיקה עצמה נכשלה. */
type Impact = number | "loading" | "unknown";

export function PropertyRemovalDialog({
  open,
  count,
  impact: loadImpact,
  archive,
  remove,
  onClose,
}: {
  open: boolean;
  /** ‏כמה נכסים בשאלה. משנה ניסוח בלבד — לא כללים. */
  count: number;
  /**
   * ‏מה עוד תגרור המחיקה. זריקה = „לא ידוע”, ואז אין אישור — ולא
   * ‏„אפס כרטיסים”.
   */
  impact: () => Promise<number>;
  /**
   * ‏הפעולה השנייה. `undefined` כשאין לאן להעביר (הנכס כבר
   * ‏בארכיון) — ואז גם הניסוח אומר זאת.
   */
  archive?: (() => Promise<void>) | undefined;
  /** ‏המחיקה עצמה. הודעת השגיאה שנזרקת היא מה שיוצג. */
  remove: () => Promise<void>;
  onClose: () => void;
}): React.JSX.Element {
  const [impact, setImpact] = useState<Impact>("loading");
  const [busy, setBusy] = useState<null | "archive" | "delete">(null);
  const [error, setError] = useState<string | null>(null);

  /*
   * ‏חלון שנפתח מחדש מתחיל נקי, וגם שולף מחדש: גילוי מבחירה קודמת
   * ‏הוא בדיוק סוג המספר שנראה נכון ואינו.
   */
  useEffect(() => {
    if (!open) return;
    setError(null);
    setBusy(null);
    setImpact("loading");
    let live = true;
    loadImpact()
      .then((contacts) => {
        if (live) setImpact(contacts);
      })
      .catch(() => {
        if (live) setImpact("unknown");
      });
    return () => {
      live = false;
    };
    /*
     * ‎`loadImpact` נוצרת מחדש בכל רינדור של הקורא, ולכן היא **אינה**
     * ‏בתלויות: הכללתה הייתה מריצה את הבדיקה שוב על כל הקלדה במסך
     * ‏שמאחור. מה שקובע מתי לשאול מחדש הוא הפתיחה ומה שנבחר.
     */
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [open, count]);

  async function run(what: "archive" | "delete"): Promise<void> {
    const action = what === "archive" ? archive : remove;
    if (action === undefined) return;
    setBusy(what);
    setError(null);
    try {
      await action();
    } catch (err: unknown) {
      setError(
        err instanceof Error && err.message !== ""
          ? err.message
          : what === "archive"
            ? "ההעברה לארכיון נכשלה"
            : "המחיקה נכשלה",
      );
      setBusy(null);
    }
  }

  const many = count !== 1;

  return (
    <ConfirmDialog
      open={open}
      title={many ? `למחוק ${count} נכסים?` : "למחוק את הנכס?"}
      tone="danger"
      confirmLabel="כן, מחק"
      busyLabel={busy === "archive" ? "מעביר…" : "מוחק…"}
      busy={busy !== null}
      /*
       * ‎**חסום כל עוד הגילוי אינו מספר — גם כשהבדיקה נכשלה**
       * ‎(ביקורת Codex, P1).
       *
       * ‏התנאי היה `impact === "loading"` בלבד, ולכן כשל רגעי של
       * ‏התצוגה המקדימה **פתח** את „כן, מחק”: המצב עבר מ„נטען”
       * ‏ל„לא ידוע”, התנאי נעשה שקר, והמחיקה שאין עליה גילוי הפכה
       * ‏אפשרית בלחיצה. ההודעה האדומה אמרה „בדקו לפני המחיקה”
       * ‏ונשענה על כך שמישהו יקרא אותה.
       *
       * ‏זה גם מה שמסך הקונים כבר עושה — הוא **עוצר** כשהבדיקה
       * ‏נכשלת ואינו שואל בכלל. „לא ידוע” לעולם אינו מוצג כ„לא
       * ‏יימחק”, וגם אינו מתפקד ככזה.
       *
       * ‏החלופה נשארת פתוחה: „העבר לארכיון” אינו תלוי בגילוי, כי
       * ‏הוא הפיך.
       */
      confirmDisabled={typeof impact !== "number"}
      onConfirm={() => void run("delete")}
      /* ‎`X` בפינה במקום כפתור טקסט שלישי שיתחרה על שתי הפעולות */
      cancelLabel={null}
      dismissIcon
      {...(archive === undefined
        ? {}
        : { secondary: { label: "העבר לארכיון", onClick: () => void run("archive") } })}
      onClose={onClose}
    >
      <p className="m-0">
        {archive === undefined
          ? "הנכס כבר בארכיון. מחיקה לצמיתות מסירה אותו מהמערכת יחד עם התמונות שלו מהאחסון — ואי אפשר לשחזר."
          : many
            ? "מחיקה לצמיתות מסירה את הנכסים מהמערכת יחד עם התמונות שלהם מהאחסון — ואי אפשר לשחזר. העברה לארכיון משאירה אותם בהיסטוריה, מחוץ לרשימת הנכסים הפעילים."
            : "מחיקה לצמיתות מסירה את הנכס מהמערכת יחד עם התמונות שלו מהאחסון — ואי אפשר לשחזר. העברה לארכיון משאירה אותו בהיסטוריה, מחוץ לרשימת הנכסים הפעילים."}
      </p>
      {/*
        ‎**האזהרה על כרטיסי האדם — לפני האישור ולא אחריו.**

        ‏זה הגילוי שבגללו המחיקה הייתה דו-שלבית מלכתחילה: בעלים
        ‏שהנכס הוא העוגן היחיד שלו יורד איתו, על שמו וטלפוניו.
      */}
      {impact === "loading" ? (
        <p className="m-0 mt-2" style={{ color: "var(--color-text-muted)" }}>
          בודקים מה עוד תגרור המחיקה…
        </p>
      ) : impact === "unknown" ? (
        <Notice tone="danger">
          לא הצלחנו לבדוק אם יימחקו גם כרטיסי לקוח — בדקו לפני המחיקה.
        </Notice>
      ) : impact > 0 ? (
        <Notice tone="danger">
          {impact === 1
            ? `יימחק גם כרטיס לקוח אחד, ש${many ? "הנכסים האלה הם הקישור היחיד" : "הנכס הזה הוא הקישור היחיד"} אליו — כולל שם, טלפונים והיסטוריית התקשורת.`
            : `יימחקו גם ${impact} כרטיסי לקוח, ש${many ? "הנכסים האלה הם הקישור היחיד" : "הנכס הזה הוא הקישור היחיד"} אליהם — כולל שם, טלפונים והיסטוריית התקשורת.`}
        </Notice>
      ) : null}
      {error !== null ? <Notice tone="danger">{error}</Notice> : null}
    </ConfirmDialog>
  );
}
