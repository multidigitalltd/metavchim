"use client";

import { apiGet, apiPatch } from "@/lib/api";
import {
  A11Y_CHANGE_EVENT,
  A11Y_DEFAULTS,
  applyA11y,
  clampFontScale,
  clearA11y,
  saveA11y,
  type A11yPrefs,
} from "@/lib/a11y-prefs";


/**
 * סנכרון העדפות הנגישות מהשרת — נקודה אחת, לכל מסך.
 *
 * הסנכרון יושב כאן ולא בעמוד הפרופיל, כי המשתמש כמעט אף פעם לא
 * מתחיל שם: הוא מתחבר ונוחת בדשבורד. כשהטעינה ישבה בפרופיל בלבד,
 * מכשיר חדש המשיך לעבוד בברירות מחדל עד שבמקרה נכנסו להגדרות —
 * כלומר ההעדפה "האישית" לא הייתה אישית בפועל.
 */

/** נשלח פעם אחת לכל טעינת עמוד, ולא בכל מעבר מסך. */
let synced = false;

/**
 * מונה דורות — עולה בכל החלפת משתמש.
 *
 * הבקשה ל-`/auth/profile` היא אסינכרונית, והיציאה יכולה לקרות
 * בזמן שהיא באוויר. בלי המונה הזה התשובה **הישנה** הייתה ממשיכה
 * לרוץ אחרי האיפוס, מחילה את ההעדפות של המשתמש היוצא ושומרת
 * אותן שוב במטמון — כלומר הניקוי היה זמני, וההגדרות של אחד היו
 * חוזרות במסך ההתחברות או אצל הבא אחריו (ביקורת Codex).
 *
 * דור נלכד כשהבקשה יוצאת ונבדק כשהיא חוזרת. תשובה מדור שאינו
 * הנוכחי נזרקת בשקט — היא נכונה למישהו שכבר אינו כאן.
 */
let generation = 0;

/**
 * מונה עריכות מקומיות — עולה בכל שינוי שהמשתמש עושה בעצמו.
 *
 * הכפתור הצף זמין מהשנייה הראשונה, גם כשהבקשה ל-`/auth/profile`
 * עדיין באוויר על חיבור איטי. בלי המונה, תשובת השרת — תמונת מצב
 * **מלפני** השינוי — הייתה מוחלת ללא תנאי ומחזירה את המסך ואת
 * המטמון אחורה, רגע אחרי שהמשתמש ראה את ההתאמה נכנסת לתוקף
 * (ביקורת Codex). השינוי המקומי כבר נשלח לשרת, ולכן הוא החדש
 * משניהם: תשובה שיצאה לפניו נזרקת.
 */
let localEdits = 0;

export interface ProfilePrefsResponse {
  preferences?: { a11y?: Partial<A11yPrefs> };
}

/**
 * מושך את ההעדפות של המשתמש המחובר ומחיל אותן.
 *
 * מחזיר את ההעדפות שהוחלו, או null כשאין משתמש מחובר (הקריאה
 * נכשלת בשקט — מסכים ציבוריים לא אמורים לדווח על שגיאה).
 */
export async function syncA11yFromServer(): Promise<A11yPrefs | null> {
  if (synced) return null;
  synced = true;
  const mine = generation;
  const editsBefore = localEdits;
  try {
    const res = await apiGet<ProfilePrefsResponse>("/auth/profile");
    /*
     * החלפת משתמש קרתה בזמן שהבקשה הייתה באוויר — התשובה הזו
     * שייכת למי שכבר יצא, והחלתה הייתה מבטלת את הניקוי.
     */
    if (mine !== generation) return null;
    /*
     * המשתמש כבר שינה משהו בזמן ההמתנה — מה שעל המסך חדש יותר
     * ממה שהשרת זוכר מלפני רגע, וכבר בדרכו אליו.
     */
    if (editsBefore !== localEdits) return null;
    const fromServer = res.preferences?.a11y;
    /*
     * שרת בלי העדפות = איפוס, לא "השאר מה שיש".
     *
     * מפתח המטמון גלובלי לדפדפן ולא למשתמש, ולכן משתמש שני שנכנס
     * באותו דפדפן היה יורש את הפונט, הניגודיות וקו הקריאה של הראשון
     * — ללא הגבלת זמן (ביקורת Codex). החזרה המפורשת לברירות המחדל
     * מנקה גם את המטמון.
     */
    /*
     * הסקלה מקוצצת גם כאן ולא רק ב-CSS: מי ששמר 90% לפני שנקבעה
     * הרצפה מקבל מהשרת את הערך הישן. `applyA11y` כבר מציג 100%,
     * אבל האובייקט שנשמר ומשודר היה נושא 90% — והפאנל היה מציג
     * „90%” שלחיצת A+ ראשונה עליו רק מיישרת עם מה שכבר על המסך
     * (ביקורת Codex).
     */
    const merged = fromServer ? { ...A11Y_DEFAULTS, ...fromServer } : A11Y_DEFAULTS;
    const next = { ...merged, fontScale: clampFontScale(merged.fontScale) };
    applyA11y(next);
    if (fromServer) saveA11y(next);
    else clearA11y();
    window.dispatchEvent(new CustomEvent(A11Y_CHANGE_EVENT, { detail: next }));
    return next;
  } catch {
    return null; // לא מחובר, או רשת — המטמון המקומי נשאר בתוקף
  }
}

/**
 * יציאה: מחזיר את המסך לברירות המחדל **בפועל**, לא רק מתיר סנכרון הבא.
 *
 * הגרסה הראשונה כאן רק אפסה את הדגל, וזה לא הספיק: `router.replace`
 * אינו טוען את הדף מחדש, `AccessibilityRuntime` נשאר מורכב
 * ו-`useEffect([])` שלו לא רץ שוב — כלומר הפונט, הניגודיות וקו
 * הקריאה של המשתמש היוצא נשארו על המסך, וגם המטמון המקומי נשאר
 * (ביקורת Codex). דגל שמתיר סנכרון עתידי אינו תחליף לניקוי.
 *
 * הניקוי כאן ולא בכל מוקד יציאה בנפרד: שלושת המוקדים היו צריכים
 * לזכור את אותם שלושה צעדים, ומי שיוסיף רביעי היה שוכח.
 */
export function resetA11ySync(): void {
  synced = false;
  generation += 1;
  if (typeof window === "undefined") return;
  clearA11y();
  applyA11y(A11Y_DEFAULTS);
  window.dispatchEvent(new CustomEvent(A11Y_CHANGE_EVENT, { detail: A11Y_DEFAULTS }));
}

/**
 * כניסה: משיכה מחודשת של ההעדפות למשתמש שנכנס עכשיו.
 *
 * `syncA11yFromServer` הוא חד-פעמי לטעינת עמוד, ומסך ההתחברות כבר
 * צרך את הפעם הזו — הקריאה שלו נכשלה שם כצפוי (אין Session) אבל
 * הדגל נשאר דלוק. בלי הכפייה כאן, המשתמש שנכנס דרך `router.replace`
 * לא היה מקבל את הגדרות הנגישות **שלו** עד רענון ידני. זהו הצד
 * השני של אותה בעיה שהיציאה פותרת.
 */
export async function resyncA11yForUser(): Promise<A11yPrefs | null> {
  synced = false;
  // דור חדש גם כאן: בקשה שיצאה עבור המשתמש הקודם לא תיושם על זה
  generation += 1;
  return syncA11yFromServer();
}

/**
 * שמירה בשרת — מה שהופך את ההעדפה לאישית ולא למכשירית.
 *
 * נשלח ולא מומתן: המשתמש כבר רואה את השינוי מהמטמון, וכישלון רשת
 * לא צריך להחזיר לו את המסך אחורה — הוא ייסנכרן בשינוי הבא.
 *
 * ‎**רק `a11y`, ולא כל ה-preferences.** השרת ממזג את המפתח העליון
 * לתוך מה שכבר שמור (`auth.service.ts`), ולכן אין צורך לשלוח את
 * שאר ההעדפות — ושליחתן הייתה מסוכנת: עותק ישן של ההעדפות שנשלח
 * מלשונית אחת היה דורס מתג וואטסאפ שהוחלף בלשונית אחרת.
 *
 * במסכים ציבוריים — התחברות, דף ההצעה, דף החתימה — אין משתמש
 * מחובר, והשרת עונה 401. הכישלון נבלע בכוונה: ההתאמה כבר הוחלה
 * ונשמרה במכשיר, וזה כל מה שמבקר לא-מחובר יכול לצפות לו.
 */
export function persistA11yToServer(next: A11yPrefs): void {
  localEdits += 1;
  apiPatch("/auth/profile", { preferences: { a11y: next } }).catch(() => undefined);
}
