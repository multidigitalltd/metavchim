export const EMBEDDED_COOKIE = "mv_embedded";

export function isEmbedded(): boolean {
  if (typeof document === "undefined") return false;
  return document.cookie.split(";").some((part) => part.trim() === `${EMBEDDED_COOKIE}=1`);
}
