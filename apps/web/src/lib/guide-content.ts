/**
 * סעיף העמקה — מה שאינו „צעד” אבל בהחלט צריך להיכתב.
 *
 * הצעדים עונים „איך עושים”; הסעיפים עונים „מה קורה מאחורי”,
 * „למה זה ככה” ו„מה עושים כשזה לא עובד”. עד עכשיו כל זה נדחס
 * לתוך גוף הצעד, והצעדים התארכו עד שהם הפסיקו להיקרא כצעדים.
 */
export interface GuideSection {
  title: string;
  body: string;
  /** רשימה קצרה ומדויקת — לא פסקה שנחתכה לשורות. */
  bullets?: string[];
  /** מה שחייב להיקרא לפני הפעולה ולא אחריה. */
  note?: string;
  image?: string;
}

export interface Guide {
  id: string;
  area: GuideArea;
  title: string;
  /** שורה אחת לכרטיס באינדקס — לא הפסקה הראשונה של המדריך. */
  summary: string;
  intro: string;
  image?: string;
  steps: { title: string; body: string }[];
  sections?: GuideSection[];
  /** שאלות שנשאלות בפועל, ולא שאלות שנוח לענות עליהן. */
  faq?: { q: string; a: string }[];
  /** מדריכים סמוכים — מזהים בלבד; שם שגוי נתפס בבדיקה. */
  related?: string[];
  tip?: string;
}

