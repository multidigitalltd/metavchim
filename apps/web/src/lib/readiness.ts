/**
 * רצועות המוכנות — **מקום אחד, שני מסכים.**
 *
 * ## למה מודול ולא שתי פונקציות
 *
 * המוכנות מוצגת גם ברשימת הנכסים וגם בכרטיס הנכס, וכל אחד מהם
 * החזיק עותק משלו של הספים. כשעדכנתי את הרשימה לספים של החבילה
 * (90 ו-60) נוצר מצב שבו **אותו נכס בדיוק** מוצג ירוק במסך אחד
 * וענבר בשני — בלי שאיש שינה נתון.
 *
 * החבילה מנסחת את הכלל פעמיים ובשני מסמכים שונים:
 * „That count, the grid below and the percentage above MUST agree.
 * Never three numbers for one listing” (SPEC-3b §4), ו„The
 * percentage, the ‏‎`N מתוך 9`‎ line and the ‏‎`חסר`‎ pills derive
 * from ONE server-side computation” (SPEC-3c §7). האחוז עצמו אכן
 * מגיע מהשרת ומשותף; מה שנשבר היה דווקא **הצבע** שלו, וצבע הוא
 * מידע — הוא אומר „דחוף / בסדר / כמעט”.
 *
 * ## למה לא הגוונים של החבילה
 *
 * ‎`#3FBF63`‎ ו-`#B4801F`‎ נותנים 2.01:1 ו-2.94:1 מול מסילת הפס.
 * מילוי של פס התקדמות הוא „חלק מאובייקט גרפי שנדרש להבנת התוכן”
 * וכפוף ל-3:1 של WCAG 1.4.11 — כלומר דווקא הרכיב שכל תכליתו לומר
 * „מה חסר בנכס” היה זה שאי אפשר לקרוא. האדום-חמרה עובר (4.22:1).
 *
 * במקומם הטוקנים הסמנטיים של המערכת: אותן שלוש משמעויות, ערכים
 * שעומדים בסף, ומיפוי נכון בשלוש הערכות בלי הצהרה נוספת.
 *
 * המילוי והטקסט נפרדים כי הסף שונה — 3:1 לגרפיקה, 4.5:1 לטקסט.
 */

/** הספים מהחבילה: 90–100 ירוק · 60–89 ענבר · מתחת ל-60 אדום-חמרה. */
const READY = 90;
const PARTIAL = 60;

export interface ReadinessBand {
  /** מילוי פס ההתקדמות — סף 3:1 מול המסילה */
  bar: string;
  /** הטקסט שלצידו — סף 4.5:1 מול המשטח */
  text: string;
}

export function readinessBand(score: number): ReadinessBand {
  if (score >= READY) {
    return { bar: "var(--color-primary-accent)", text: "var(--color-primary)" };
  }
  if (score >= PARTIAL) {
    return { bar: "var(--color-warning)", text: "var(--color-warning)" };
  }
  return { bar: "var(--color-danger)", text: "var(--color-danger)" };
}

/**
 * „‎2 מתוך 9 שדות מלאים” — הניסוח מ-SPEC-3b §4, **מדויק**.
 *
 * ## המכנה מגיע מהמקור ולא נכתב קשיח
 *
 * החבילה כותבת „2 מתוך 9”, ובמערכת הרשימה היא
 * ‎`PROPERTY_READINESS_FIELDS` — אותה רשימה עצמה שממנה השרת מחשב את
 * ‎`missingFields`‎ ואת האחוז. ‎`9`‎ קבוע היה הופך לשקר ברגע שתשתנה
 * הרשימה, ואז שוב יהיו שני מספרים לנכס אחד — בדיוק מה שהכלל אוסר.
 *
 * ## „שדות” ולא „שדות חובה”
 *
 * הניסוח היה „שדות חובה”, וזה היה תיקון נכון לחישוב שקדם: הציון
 * נתן 80% לשדות החובה ועוד 10% לכותרת ו-10% לתיאור, ולכן „10 מתוך
 * 10 שדות מלאים” הופיע לצד „90%” והמילה „חובה” היא שהסבירה את
 * הפער. מרגע שהציון הוא ‎`filled / 9`‎ בדיוק, אין פער להסביר —
 * והמילה הפכה לסייג על משפט שאינו מסויג. הניסוח חוזר למסמך.
 */
export function readinessCount(missing: number, total: number): string {
  return `${total - missing} מתוך ${total} שדות מלאים`;
}

/**
 * שני שדות המוכנות ש**אין להם פקד בטופס העריכה.**
 *
 * טופס העריכה הוא שדות של שורת הנכס: מחיר, שטח, חדרים, קומה,
 * מעלית, חניה ותיאור שיווקי. תמונות יושבות בטבלה אחרת ומועלות
 * דרך רכיב ההעלאה שבסקירה, ובעל הנכס הוא קישור לכרטיס איש קשר
 * שנבחר בלשונית שלו. שניהם נספרים במוכנות מאז המעבר לתשעת
 * השדות — ולכן ההמלצה יכולה עכשיו להצביע על חוסר שהיעד שלה
 * אינו יודע לתקן.
 */
const FIELDS_OUTSIDE_EDIT_FORM = ["images", "owner"];

/**
 * לאן שולח „השלם פרטים” — **למקום שבו באמת אפשר להשלים.**
 *
 * ## הבאג
 *
 * הכפתור שלח תמיד ל-`/properties/:id/edit`. לנכס שחסרות בו רק
 * תמונות ובעלים — מצב שנעשה שכיח בדיוק מפני שהוספנו את שניהם
 * למוכנות — ההמלצה נקבה בשני החוסרים ואז פתחה מסך שאין בו לא
 * מעלה תמונות ולא בורר איש קשר. המשתמש שמר טופס בלי לשנות דבר,
 * הציון לא זז, וההמלצה חזרה מחר (ביקורת Codex).
 *
 * ## הכלל
 *
 * יש ולו חוסר אחד שהטופס יודע לתקן — הטופס. אחרת כרטיס הנכס:
 * בעלים-בלבד נפתח היישר בלשונית „בעל הנכס”, וכל מקרה שכולל
 * תמונות נוחת על עוגן רכיב ההעלאה שבסקירה. השדות עצמם מגיעים
 * מהשרת, כך שהניתוב הוא תוצאה של אותו חישוב שהפיק את הגלולות
 * ולא ניחוש מקביל.
 *
 * העוגן חשוב במיוחד לכפתור שבכרטיס עצמו: בלעדיו „השלם פרטים”
 * היה קישור לעמוד שהמשתמש כבר נמצא בו, כלומר לחיצה שאינה עושה
 * דבר. עם העוגן היא גוללת אל מעלה התמונות.
 */
export function readinessHref(propertyId: string, missingFields: readonly string[]): string {
  const fixableInForm = missingFields.some((f) => !FIELDS_OUTSIDE_EDIT_FORM.includes(f));
  if (fixableInForm) return `/properties/${propertyId}/edit`;
  if (missingFields.length === 1 && missingFields[0] === "owner") {
    return `/properties/${propertyId}?tab=owner`;
  }
  return `/properties/${propertyId}#media-heading`;
}
