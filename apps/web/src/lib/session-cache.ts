"use client";

import type { AuthUser } from "./use-auth";
import { apiGet } from "./api";

/**
 * זהות המשתמש — **נשלפת פעם אחת, לא בכל מסך.**
 *
 * ## מה היה איטי
 *
 * `useRequireAuth` ירה `GET /auth/me` בכל טעינת עמוד, וה-AppShell
 * ירה אותו בנפרד. כלומר כל מעבר בין מסכים שילם על אותה תשובה
 * פעמיים — ובעיקר, כל מסך המתין לה לפני שהתחיל למשוך את **הנתונים
 * שלו**:
 *
 * ```
 * useEffect(() => { if (authLoading) return; apiGet("/properties") … })
 * ```
 *
 * זה מפל סדרתי: ניווט ⟵ ‎/auth/me‎ ⟵ ‎/properties‎ ⟵ ציור. שתי
 * הלוך-חזור מלאות לפני שמופיע משהו על המסך, בכל מעבר, על תשובה
 * שאינה משתנה. זו הסיבה העיקרית לתחושת האיטיות.
 *
 * ## שלוש התכונות שהופכות את זה לנכון ולא רק למהיר
 *
 * **איחוד בקשות באוויר.** שני רכיבים שנטענים יחד (המעטפת והמסך)
 * מקבלים את **אותה** הבטחה, ולא שתי בקשות מקבילות. זה מה שמסיר את
 * הכפילות גם בטעינה ראשונה, לא רק בניווט.
 *
 * **תפוגה של דקה.** בלעדיה שינוי הרשאות שמנהל משרד עשה לא היה
 * משתקף עד רענון מלא — נסיגה אמיתית, כי היום כל טעינת מסך שואלת
 * מחדש. דקה מכווצת את מפל הניווט ועדיין מתקנת את עצמה מהר יותר
 * ממה שלוקח למנהל לומר לסוכן „רענן”.
 *
 * **כישלון אינו נשמר.** ‎401‎ שנכנס למטמון היה נועל את המשתמש מחוץ
 * למערכת עד לרענון. שגיאה מנקה את המטמון ונזרקת הלאה.
 */

const TTL_MS = 60_000;

/**
 * נשלח על `window` ברגע ש-`/auth/me` ענה — כלומר יש session מאומת.
 *
 * הרכיבים שמורכבים בכל מסך (סנכרון הנגישות) אינם יודעים אם המבקר
 * מחובר: העוגייה היא `HttpOnly`. עד כה הם פשוט ביקשו, וכל מסך
 * ציבורי — התחברות, תיעוד, דף הצעה — ייצר 401 בקונסול. האירוע הזה
 * הוא הסימן: מי שממתין לו מבקש רק אחרי שידוע שיש למי.
 */
export const SESSION_READY_EVENT = "mv:session-ready";

let cached: { user: AuthUser; at: number } | null = null;
let inflight: Promise<AuthUser> | null = null;

/** `now` מוזרק לבדיקות; בפרודקשן תמיד השעון. */
export function cachedUser(now: number = Date.now()): AuthUser | null {
  if (cached === null) return null;
  return now - cached.at < TTL_MS ? cached.user : null;
}

export async function fetchMe(): Promise<AuthUser> {
  const fresh = cachedUser();
  if (fresh !== null) return fresh;
  /*
   * בקשה שכבר באוויר מוחזרת כפי שהיא. בלי זה המעטפת והמסך יורים
   * שתי בקשות זהות באותה מילישנייה — בדיוק מה שהמטמון בא למנוע,
   * ודווקא בטעינה הראשונה שהיא האיטית ביותר.
   */
  inflight ??= apiGet<{ user: AuthUser }>("/auth/me")
    .then((res) => {
      cached = { user: res.user, at: Date.now() };
      window.dispatchEvent(new CustomEvent(SESSION_READY_EVENT));
      return res.user;
    })
    .finally(() => {
      inflight = null;
    });
  return inflight;
}

/**
 * ניקוי — **בכל מקום שמחליף את העוגייה.**
 *
 * ## למה זה קריטי ולא רק מסודר
 *
 * המעבר אחרי התחברות, הרשמה או החלפת סיסמה הוא `router.replace`
 * ולא טעינה מחדש, ולכן ה-JS — והמטמון הזה בתוכו — שורד אותו. בלי
 * הניקוי המטמון נושא את הזהות **הקודמת** בעוד שהעוגייה כבר חדשה,
 * וכל בקשה הולכת למשרד אחר מזה שהמסך מציג.
 *
 * המקרה החמור הוא החלפת סיסמה זמנית: המטמון נושא
 * `mustChangePassword: true`, המסך הבא מפנה חזרה למסך ההחלפה, וזה
 * חוזר עד שהתפוגה חולפת — לולאה של דקה (ביקורת Codex).
 *
 * ## הרשימה המלאה
 *
 * `login` (סיסמה **וגם** קוד אימייל), `signup`, `change-password`,
 * ויציאה משני המקומות שיוצאים בהם — המעטפת והפרופיל.
 *
 * מה ש**אינו** ברשימה ולמה: `reset-password` מעביר ל-`/login`
 * ומנוקה שם · כניסה עם Google היא ניווט דפדפן מלא, ולכן המודול
 * נטען מאפס ממילא · `sessions/revoke-others` אינו נוגע בסשן הנוכחי.
 */
export function clearSessionCache(): void {
  cached = null;
  inflight = null;
}

/**
 * ‎**שינוי מסלול — המטמון בלבד אינו מספיק, צריך טעינה מלאה.**
 *
 * ## ‏הבאג שזה סוגר
 *
 * ‏מסלול השת״פ הוא חינמי, ולכן מעבר אליו **פותח מיד** משרד שתקופתו
 * ‏נגמרה: `planIsFree` מבטל את התפוגה בשרת. אבל המסך לא ידע: הבקשה
 * ‏הצליחה, כרטיס המנוי התעדכן — והמשתמש נשאר תקוע במעטפת המצומצמת
 * ‏של „חיוב בלבד”, בלי תפריט ובלי דרך לדשבורד, עד שיעבור זמן וירענן
 * ‏ידנית (דיווח המשתמש).
 *
 * ## ‏למה `router.replace` לא היה מספיק
 *
 * ‏שני מטמונים נושאים את התשובה הישנה, ורק אחד מהם הוא זה שכאן:
 * ‏ה-`AppShell` שולף `me` פעם אחת ב-`useEffect` שתלוי ב-`isPublic`
 * ‏בלבד, ולכן ניווט פנימי **אינו** קורא מחדש. מעבר רך היה מגיע
 * ‏לדשבורד ועדיין מצייר את המעטפת החסומה סביבו.
 *
 * ‏זה נכון גם למי ש**לא** היה חסום: המסלול קובע גם את רשימת
 * ‏הפיצ׳רים, ומעטפת שנושאת את הרשימה הישנה מציגה כפתורים חסומים
 * ‏ומסתירה פעילים — בדיוק התקלה שה-`AppShell` כבר מתגונן מפניה
 * ‏במעבר בין משתמשים.
 */
export function reloadWithFreshSession(path: string): void {
  clearSessionCache();
  window.location.assign(path);
}
