#!/bin/sh
# ============================================================
# עליית ה-API — root לרגע אחד, ואז המשתמש node.
#
# ‏התהליך עצמו רץ בלי root, כמו ה-Workers וה-Web: קוד שנפרץ ב-API אינו
# ‏מקבל את הקונטיינר כולו, ואינו קורא את הדאמפים של המסד.
#
# ‏מה שעוד דורש root הוא תיקיית הגיבויים. היא ממופה מהמארח ונכתבת
# ‏בקונטיינר הגיבוי (root, ‏`umask 077`), ומסך הפלטפורמה צריך בה שלושה
# ‏דברים בלבד: לרשום את הקבצים, למחוק קובץ, ולקרוא את `verify.json`
# ‏(תוצאת תרגיל השחזור). לכן התיקייה עוברת לקבוצה של node עם רשימה,
# ‏כתיבה ומעבר, והדאמפים עצמם נשארים 0600 של root: node רואה אותם
# ‏ויכול למחוק אותם, ואינו יכול לקרוא אותם. `verify.sh` משתף את התוצאה
# ‏שהוא כותב עם אותה קבוצה.
#
# ‏זה קורה כאן, בכל עלייה, ולא רק בסקריפטי הגיבוי: כפתור „עדכן גרסה”
# ‏מושך תמונות ואינו מעדכן את `infra/backup` שעל השרת — ו-API שעלה
# ‏כ-node מול תיקייה של root היה מאבד את מסך הגיבויים.
# ============================================================
set -u

# ‏הורץ כבר בלי root (למשל `--user`) — אין מה להעביר, ואין ממי לרדת
if [ "$(id -u)" != "0" ]; then
  exec "$@"
fi

BACKUPS="${BACKUP_PATH:-/backups}"
if [ -d "$BACKUPS" ]; then
  chgrp node "$BACKUPS" && chmod g+rwx "$BACKUPS" ||
    echo "[api] ✗ ${BACKUPS} לא הועברה לקבוצת האפליקציה — מסך הגיבויים לא יציג אותה" >&2
  # ‏תוצאה שנכתבה לפני ש-verify.sh למד לשתף אותה
  if [ -f "${BACKUPS}/verify.json" ]; then
    chgrp node "${BACKUPS}/verify.json" && chmod g+r "${BACKUPS}/verify.json" ||
      echo "[api] ✗ verify.json אינו קריא לאפליקציה — תרגיל השחזור יוצג כאילו לא רץ" >&2
  fi
fi

exec su-exec node "$@"
