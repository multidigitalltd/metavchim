/**
 * הפרומפט — **נבנה מהקטלוג, לא נכתב לידו.**
 *
 * בגרסה הקודמת רשימת הפעולות הייתה מחרוזת ידנית בתוך הבקר. כל
 * פעולה שנוספה לסכימה ולא לפרומפט הפכה לפעולה שהמודל אינו יודע
 * שקיימת, וכל פעולה שנמחקה מהקוד ונשארה בפרומפט הפכה להצעה שהשרת
 * זורק. כאן אין שתי רשימות.
 */

import { AGENT_ACTIONS } from "./actions.js";
import { fieldDescription } from "./field-spec.js";
import { currentSubject } from "./history.js";

/**
 * תור אחד בשיחה — מה נאמר, מה בוצע, ומה חזר.
 *
 * `resultSummary` הוא לב הזיכרון: "ומה עם רמת גן?" דורש לדעת שהשאלה
 * הקודמת הייתה על קונים בגבעתיים, ו"תתקשר לראשון מהם" דורש לדעת מי
 * הראשון ברשימה שחזרה. השמות ברשימה — לא מזהים: המודל מפנה בשם,
 * והקוד פותר אותו מול המאגר כרגיל.
 */
export interface AgentHistoryTurn {
  transcript: string;
  action: string;
  params: Record<string, unknown>;
  resultSummary?: string;
  /**
   * מי דיבר בתור הזה. היעדרו = המתווך, כי כך היה עד שהסוכן התחיל
   * ליזום. `"assistant"` = עדכון ש**הסוכן** שלח מיוזמתו (התראה
   * בוואטסאפ), ולא משהו שהמתווך ביקש.
   *
   * בלי ההבחנה הזו „תזכיר לי להתקשר אליו” אחרי התראה על שיחה שלא
   * נענתה הגיע למודל בלי שום „הוא”: הסוכן שלח את ההודעה ולא רשם
   * לעצמו שהוא שלח אותה, כלומר השיחה בוואטסאפ נראתה לו כמתחילה
   * במילה „תזכיר”.
   */
  origin?: "user" | "assistant";
  /**
   * הרשומות שהתור נגע בהן — מה ש„אליו” חל עליו.
   *
   * קיים בעיקר לתורות של הסוכן: התראה מנוסחת סביב כותרת שיש בה
   * מספר טלפון, וההיסטוריה נשלחת למודל חיצוני. לכן מה שנשמר הוא
   * **תווית מקומית** לשיחה הזו (`הליד מהשיחה`) והמזהה הפנימי לצידה;
   * הפרומפט מדפיס את התווית בלבד, והקוד הוא שמתרגם אותה חזרה
   * לרשומה. המודל לעולם אינו רואה מזהה ולא מספר.
   */
  refs?: readonly AgentHistoryRef[];
  /**
   * ‎**מה שהסוכן הציע לעשות אחר כך** — המשפט המדויק, לא תיאור שלו.
   *
   * בלי זה „כן” הוא מילה תלושה: הסוכן סיים ב„רוצה שנעבור על
   * המשימות?”, המתווך ענה „כן”, והמודל קיבל „כן” אחרי תור שבו
   * נאמר „תציג לי לידים ממתינים” — כלומר בלי שום דבר להסכים לו.
   * התשובה שהתקבלה בפועל הייתה „במה אוכל לעזור?” (דיווח מהשטח).
   *
   * המשפט עצמו ולא מזהה פעולה: הוא נשלח למנוע כאילו הוקלד, בדיוק
   * כמו לחיצה על כפתור ההמשך — אין מסלול ביצוע שני.
   */
  offer?: string;
  /**
   * ‎**מה הסוכן ענה בתור שיחתי** (`action: "unknown"`) — הטקסט שהמתווך קרא.
   *
   * בלי זה תשובה חופשית לא השאירה עקבה: „תן עוד דוגמה” או „כן,
   * תנסח את זה קצר יותר” הגיעו למודל כאילו השיחה מתחילה בהם, וזה
   * בדיוק מה שנראה כמו בוט קשיח. אין כאן סוג נתון חדש: התשובה נוסחה
   * מהמשפט ומהשיחה, שתיהן כבר בפרומפט.
   */
  reply?: string;
  /**
   * ‎**המקום של התור הזה בשיחה הוא ניחוש.**
   *
   * ‏במסך, עדכון מההתראות האחרונות מצורף לסוף ההיסטוריה שהדפדפן שלח —
   * ‏בלי חותמת זמן אין דרך לדעת אם הוא קדם למה שהמתווך עשה בפאנל או
   * ‏אחריו. תור כזה נשאר בהקשר (ל„אליו”), אבל אינו בסיס לנושא מפורש:
   * ‏נושא שנבחר לפי סדר מנוחש מכוון כתיבה לרשומה הלא נכונה (ביקורת
   * ‏Codex, P1). לעולם אינו נשמר ואינו מגיע מהדפדפן.
   */
  unordered?: true;
  /**
   * ‎**התור הציג יותר משורה אחת** — גם כשרק לאחת מהן יש הפניה.
   *
   * ‏רשימת מיילים, הערות או תוצאות חיפוש מערבבת שורות שיש להן רשומה
   * ‏עם שורות שאין להן. ספירת ההפניות לבדה הייתה מציגה רשימה של
   * ‏שלושה כאילו היא כרטיס אחד, ו„תוסיף לו הערה” היה נכתב לזה שבמקרה
   * ‏היה לו מזהה (ביקורת Codex, P1). ראו `currentSubject`.
   */
  plural?: true;
}

/**
 * הפניה לרשומה מתוך תור בשיחה.
 *
 * `entityId` **אינו נכתב לפרומפט** — ראו `refs` למעלה, ובדיקת
 * `prompt.test.ts` שאוכפת זאת.
 */
export interface AgentHistoryRef {
  /** מה שהמודל רואה ומחזיר — קצר, בעברית, ובלי פרט מזהה */
  label: string;
  /**
   * `task` נוסף אחרון: „תסגור את השנייה” על שתי משימות באותו שם
   * חיפש כותרת ממוספרת שאינה קיימת בשום משימה (ביקורת Codex).
   * הפותר כבר ידע לחפש משימות — מה שחסר היה המזהה היציב.
   */
  entityType: "lead" | "buyer" | "property" | "task";
  entityId: string;
}

/** ‏איך הנושא מוצג למודל — סוג הרשומה בעברית, בלי שום פרט שלה. */
const SUBJECT_KIND_LABELS: Record<AgentHistoryRef["entityType"], string> = {
  lead: "ליד",
  buyer: "קונה",
  property: "נכס",
  task: "משימה",
};

/** ההקשר שהופך את התשובה לנכונה למשרד הזה ולרגע הזה. */
export interface AgentPromptContext {
  /** היום והשעה כפי שהמתווך חווה אותם — לפרשנות "מחר", לא לחישוב */
  nowText: string;
  /** הפעולות שלמשתמש הזה יש הרשאה אליהן. השאר אינן מוזכרות כלל. */
  allowedActions: readonly string[];
  /** ההצעה הקודמת, כשזה תיקון ולא בקשה חדשה */
  prior?: { action: string; params: Record<string, unknown> };
  /** התורות האחרונות בשיחה — למשפטי המשך ("ומה עם…", "תתקשר לראשון") */
  history?: readonly AgentHistoryTurn[];
  /**
   * מי מדבר. לא נימוס: „תראה לי את הקונים שלי” ו„מה יש לי מחר”
   * מקבלים משמעות אחרת כשידוע שהדובר רואה רק את הרשומות שלו, ותשובה
   * שיחתית („בוקר טוב”) שפונה בשם היא ההבדל בין עוזרת אישית לבין
   * טופס. `scope: "own"` = הנתונים שלו בלבד; `"all"` = כל המשרד.
   */
  speaker?: { name?: string; roleLabel?: string; scope: "all" | "own" };
  /**
   * איפה התשובה תיקרא. משפיע על `reply` בלבד — לא על בחירת הפעולה:
   * מסך מרשה פסקה, וואטסאפ מרשה שתי שורות.
   */
  channel?: "web" | "whatsapp";
  /**
   * הפעולה שהמתווך **בחר במפורש** מתוך ההצעות שהוצגו לו אחרי „לא
   * הבנתי”. כאן אין עוד שאלה איזו פעולה זו — נשארה רק מלאכת מילוי
   * השדות מהמשפט המקורי.
   */
  pin?: string;
}

/**
 * ## למה הפעולות שאין אליהן הרשאה נעלמות מהפרומפט
 *
 * לא כדי לחסוך אסימונים. מודל שמכיר פעולה יציע אותה, השרת יחסום
 * אותה בבדיקת ההרשאה, והמתווך יראה „אין לך הרשאה” על משהו שהוא
 * ביקש בניסוח סביר לגמרי. עדיף שהמודל יבחר את הפעולה המותרת הקרובה
 * ביותר — או יודה שאינו יודע.
 *
 * זו **אינה** שכבת האבטחה: הבדיקה בשרת נשארת ואינה תלויה בפרומפט.
 * זו שכבת החוויה.
 */
export function buildInterpretPrompt(
  transcript: string,
  context: AgentPromptContext,
): string {
  const actions = AGENT_ACTIONS.filter((action) =>
    context.allowedActions.includes(action.id),
  );

  const lines: string[] = [
    'אתה עוזר במערכת CRM למתווכי נדל"ן בישראל. המתווך אמר או הקליד משפט אחד בעברית מדוברת — ייתכנו שגיאות תמלול, קיצורים וסלנג.',
    "",
    "המשימה: לזהות איזו פעולה הוא רוצה, ולמלא את השדות שלה מתוך מה שנאמר.",
    "",
    "## הפעולות",
    "",
  ];

  for (const action of actions) {
    lines.push(`### ${action.id} — ${action.title}`);
    lines.push(action.when);
    lines.push(`דוגמאות: ${action.examples.map((e) => `"${e}"`).join(" · ")}`);
    lines.push("שדות:");
    for (const field of action.fields) {
      lines.push(`  - ${field.key}: ${fieldDescription(field)}`);
    }
    lines.push("");
  }

  lines.push(
    "### unknown",
    "הכוונה אינה ברורה, או שהיא פעולה שאינה ברשימה. אל תנחש ואל תדחוף למשבצת הקרובה.",
    /*
     * ‎**שאלה חופשית מקבלת תשובה, לא „לא הבנתי”.**
     *
     * עד כאן `reply` היה לברכות בלבד, וכל שאלה מקצועית או בקשת ניסוח
     * נפלה ל„אולי התכוונתם ל…” — מה שבעל המוצר תיאר כבוט קשיח
     * שמקובע לתבניות. הגבולות הם מה שמשאיר את זה בטוח: אין כאן גישה
     * לנתון שאינו כבר בשיחה, ושום דבר אינו מבוצע.
     */
    "אם זו שיחה ולא בקשה לפעולה — ברכה או תודה, שאלה מקצועית (תיווך, שיווק, משא ומתן, מיסוי ומשפט בקווים כלליים), בקשה לנסח טקסט (הודעה ללקוח, מודעה, תשובה להתנגדות), שאלה על מה שכבר עלה בשיחה, או \"מה אתה יודע לעשות?\" — ענה ב-`reply` כמו עוזר אישי מנוסה: לעניין, חם ומדויק, בעברית טבעית ובלי פתיחות רובוטיות. בקשה שיש לה פעולה ברשימה — תמיד הפעולה, גם אם משהו דומה כבר עלה בשיחה: הנתונים שלה עדכניים.",
    "גבולות `reply`: (א) הוא טקסט לתצוגה בלבד ולעולם אינו מבצע דבר — אל תכתוב שביצעת, שמרת, שלחת או קבעת משהו. (ב) עובדה על נתוני המשרד (שם, מספר, מחיר, סטטוס, כמות) — רק אם היא מופיעה בשיחה עד כה; אל תמציא ואל תשער. (ג) אם התשובה דורשת נתון מהמערכת שאינו בשיחה — אמור זאת ותן משפט שאפשר לבקש ממך כדי לקבל אותו. (ד) במס ובמשפט — מידע כללי בלבד, והמלצה לבדוק עם איש מקצוע לפני החלטה.",
    /*
     * ‎**„לא ידעתי” אינו חייב להיות קיר.**
     *
     * המודל בדיוק סרק את כל הקטלוג והכריע שאף פעולה אינה מספיק
     * קרובה כדי לפעול לפיה. זו הכרעה נכונה — אבל הידיעה *מה כן היה
     * קרוב* היא בדיוק מה שהמתווך צריך, והיא נזרקה. כאן היא נשמרת,
     * ומוצגת לו כבחירה. הבחירה שלו היא ההכרעה, לא של המודל.
     */
    "אם יש פעולות שכמעט התאימו — מלא ב-`suggest` עד שלוש מהן, לפי סדר הקרבה. המתווך יראה אותן ויבחר; הן אינן מבוצעות מעצמן. רק פעולות שסביר שהתכוון אליהן — אם אין כזו, השאר ריק. עדיף לא להציע מאשר להציע פעולה רחוקה.",
    "",
    /*
     * מעטפת התשובה מפורשת בפרומפט ולא רק ב-responseSchema: כשמודל
     * דוחה את הסכימה (קרה בפרודקשן) הקריאה רצה במצב JSON חופשי, ובלי
     * ההגדרה כאן הוא המציא מעטפת משלו — וכל פקודה צנחה לזיהוי הבסיסי.
     */
    "## מבנה התשובה",
    "",
    "החזר JSON יחיד, בלי טקסט מסביב, במבנה הזה בדיוק:",
    '{"action": "מזהה פעולה מהרשימה או unknown", "params": {"שדה": "ערך"}, "evidence": {"שדה": "המילים מהמשפט"}, "dateText": "מילות המועד", "unmapped": [], "clarify": "", "reply": "", "suggest": [], "steps": []}',
    "השמט מפתחות שאין להם תוכן — אל תכתוב null ואל תמציא מפתחות אחרים. כל צעד ב-steps הוא {\"action\": ..., \"params\": {...}, \"dateText\": \"מילות המועד\"}.",
    "",
    "## כללים",
    "",
    "1. מלא רק שדות שנאמרו. שדה שלא נאמר — השמט אותו. אל תשלים מהיגיון או מהסתברות.",
    /*
     * השעה הנוכחית **אינה** כאן אלא בזנב הפרומפט. Google מוזילה
     * אוטומטית קלט שחוזר על עצמו מתחילת הפרומפט (implicit caching),
     * ושעה שמשתנה כל דקה באמצע הכללים הייתה קוטעת את התחילית
     * המשותפת בדיוק לפני החלק הגדול — הקטלוג והכללים חייבים להישאר
     * זהים בין קריאות כדי להיכנס למטמון.
     */
    "2. אל תחזיר תאריכים, שעות או קואורדינטות בשום שדה. המערכת מחשבת אותם בעצמה.",
    /*
     * הכלל שמעביר את **הבנת** הזמן למודל, בלי להעביר אליו את
     * **החישוב.** לוח שנה ואזור זמן נשארים בקוד; מה שהמודל עושה
     * כאן הוא לסמן אילו מילים במשפט הן המועד — וזה בדיוק החלק
     * שתבניות טקסט כשלו בו שוב ושוב.
     */
    "2א. אם נאמר מועד לפעולה הראשית — העתק את **מילות המועד** ל-`dateText` כפי שנאמרו, בלי לחשב ובלי לנרמל: \"תזכיר לי עוד שעה\" ⇒ \"עוד שעה\", \"קבע פגישה מחר בעשר וחצי\" ⇒ \"מחר בעשר וחצי\". רק מילות המועד, בלי שאר המשפט. לא נאמר מועד — השמט את `dateText` לגמרי; אל תמציא „היום”.",
    "3. `evidence` חובה לכל שדה שמילאת — המילים המדויקות מהמשפט. זה מה שמאפשר למתווך לבדוק אותך.",
    "4. מה שנאמר ולא נכנס לשום שדה — לתוך `unmapped`. אל תשמיט מידע בשקט.",
    "5. סכומים תמיד בשקלים שלמים: \"2.3 מיליון\" ⇒ 2300000, \"900 אלף\" ⇒ 900000, \"מיליון וחצי\" ⇒ 1500000.",
    "6. שמות מקומות — כתוב בצורה המקובלת ובלי מילית חיבור: \"בגבעתיים\" ⇒ \"גבעתיים\", \"לראשל\\\"צ\" ⇒ \"ראשון לציון\". כלול כל שם מקום שנאמר, גם קטן או פחות מוכר.",
    "7. `clarify` — רק כשבאמת אי אפשר להציע כלום בלעדיה. הצעה חלקית עדיפה על שאלה.",
    "8. משפט שמבקש **כמה** פעולות (\"תוסיף קונה משה ותקבע לו סיור מחר\") — הפעולה הראשונה ב-`action`/`params`, והבאות ב-`steps` לפי הסדר. פעולת המשך שמכוונת למי שנוצר בצעד קודם מפנה אליו **בשם** בשדה הביטוי המתאים. אם לצעד המשך נאמר מועד — שים את **מילות המועד** שלו (לא תאריך מחושב) ב-`dateText` של אותו צעד. משפט של פעולה אחת — השאר את `steps` ריק.",
    /*
     * ‎**„ותקבע לראשון מהם” — רשומה שתיוולד מחיפוש באותו משפט.**
     *
     * ‏שם אין עדיין: הצעד הקודם עוד לא רץ. הסימון ממתין בשדה עד הביצוע
     * ‏ונקשר שם לשורה שחזרה (`resultRefIndex`).
     */
    "8א. צעד המשך שפועל על רשומה מתוך **התוצאה** של הצעד שלפניו (\"תמצא קונים להרצל ותקבע סיור לראשון מהם\", \"תראה את המשימות של היום ותסגור את השנייה\") — כתוב בשדה הביטוי המזהה של הצעד ⟪תוצאה 1⟫, ⟪תוצאה 2⟫ וכן הלאה לפי המקום ברשימה. רק בצעדי המשך, ורק כשהרשומה תיוולד מהצעד הקודם; רשומה שכבר עלתה בשיחה — בשמה או בסימון שלה.",
  );

  if (context.history !== undefined && context.history.length > 0) {
    lines.push(
      "",
      "## השיחה עד כה",
      "",
      "המשפט החדש עשוי להמשיך את השיחה: \"ומה עם רמת גן?\" אחרי שאלה על גבעתיים היא אותה שאלה בעיר אחרת, ו\"תוסיף אותו כקונה\" מדבר על מי שחזר בתוצאה האחרונה. פנייה לרשומה מהתוצאות (\"הראשון מהם\") — מלא את שדה הביטוי בשם שלה מהרשימה. אל תיגרר להקשר כשהמשפט פותח נושא חדש לגמרי.",
      /*
       * השורה שמלמדת את המודל להשתמש בתווית. בלעדיה הוא רואה
       * „הליד מהשיחה” כתיאור ומנסח מחדש — ואז אין מה לפתור.
       */
      'שורת "עניתי" היא התשובה החופשית שנתת בתור ההוא: "תן עוד דוגמה" או "תקצר" ממשיכים אותה, ו"כן" אחריה מסכים למה שהיא הציעה.',
      'שורות שמתחילות ב"הסוכן עדכן" הן הודעות שהמערכת שלחה מיוזמתה, ולא בקשות של המתווך. הן ההקשר של "אליו", "לו", "אותו". כשלצד שורה כזו מופיע ⟪סימון⟫ — העתק אותו **כמו שהוא, כולל הסוגריים** לשדה הביטוי המזהה של הפעולה, במקום שם. זו הדרך היחידה לקשור את הפעולה לרשומה הנכונה.',
      "",
    );
    context.history.forEach((turn, i) => {
      if (turn.origin === "assistant") {
        lines.push(
          `${i + 1}. הסוכן עדכן: "${turn.transcript.replaceAll('"', "'")}"`,
          ...(turn.refs ?? []).map((ref) => `   נוגע ב: ⟪${ref.label}⟫`),
        );
        return;
      }
      if (turn.reply !== undefined) {
        lines.push(
          `${i + 1}. המתווך: "${turn.transcript.replaceAll('"', "'")}"`,
          // שורה אחת בפרומפט — שורות התשובה אינן שורות של השיחה
          `   עניתי: "${turn.reply.replaceAll('"', "'").replaceAll("\n", " ")}"`,
        );
        return;
      }
      lines.push(
        `${i + 1}. המתווך: "${turn.transcript.replaceAll('"', "'")}"`,
        `   בוצע: ${turn.action} ${JSON.stringify(turn.params)}`,
        ...(turn.resultSummary ? [`   תוצאה: ${turn.resultSummary.replaceAll('"', "'")}`] : []),
        // מה שהוצע — כדי ש„כן”, „בטח” ו„קדימה” יהיו על משהו
        ...(turn.offer ? [`   הצעתי: "${turn.offer.replaceAll('"', "'")}"`] : []),
      );
    });

    /*
     * ‎**הנושא — במפורש, ולא כהסקה מהשורות שלמעלה.**
     *
     * ‏„תוסיף לו הערה” אחרי כרטיס שנפתח לפני שלושה תורות דרש מהמודל
     * ‏לסרוק את השיחה ולנחש מי „הוא”; ניחוש שגוי נפל לחיפוש לפי שם
     * ‏ולרשימת בחירה, או לרשומה אחרת. הסימון הוא אותו מנגנון של
     * ‏עדכוני הסוכן: התווית חוזרת כמו שהיא, והקוד מתרגם אותה לרשומה.
     */
    const subject = currentSubject(context.history);
    if (subject !== null) {
      lines.push(
        "",
        "## הרשומה שעליה מדברים עכשיו",
        "",
        `⟪${subject.label}⟫ — ${SUBJECT_KIND_LABELS[subject.entityType]}.`,
        "פנייה בלי שם — \"לו\", \"לה\", \"אליו\", \"אותה\", \"הנכס הזה\", \"הליד הזה\" — מתייחסת אליה: העתק את הסימון **כמו שהוא, כולל הסוגריים**, לשדה הביטוי המזהה. כשנאמר שם אחר — השם שנאמר גובר.",
      );
    }
  }

  /*
   * ‎**הפעולה כבר הוכרעה — על ידי המתווך.**
   *
   * המסלול היחיד לכאן הוא לחיצה על אחת ההצעות שהוצגו אחרי „לא
   * הבנתי”, כלומר המתווך ראה את שם הפעולה ובחר בה. שאלת הבחירה
   * סגורה, ומה שנשאר הוא מיפוי השדות מהמשפט **שהוא כבר אמר** —
   * במקום לבקש ממנו לנסח הכול מחדש.
   *
   * ‎`unknown` נשאר מותר: לחיצה על „קבע פגישה” על משפט שאין בו שום
   * שדה אינה סיבה להמציא. הפעולה נכפית בקוד בכל מקרה; מה שהמודל
   * מחזיר כאן הוא השדות בלבד.
   */
  if (context.pin !== undefined) {
    const pinned = AGENT_ACTIONS.find((action) => action.id === context.pin);
    if (pinned !== undefined) {
      lines.push(
        "",
        "## הפעולה כבר נבחרה",
        "",
        `המתווך בחר במפורש ב-**${pinned.id}** (${pinned.title}). אל תבחר פעולה אחרת.`,
        "המשימה כאן היא רק למלא את השדות שלה ממה שנאמר במשפט. שדה שלא נאמר — השמט; אל תמציא.",
      );
    }
  }

  if (context.prior) {
    lines.push(
      "",
      "## תיקון להצעה קודמת",
      "",
      "המתווך ראה את ההצעה הזאת ואמר משהו נוסף. סביר שהוא מתקן או משלים אותה, ולא מתחיל מחדש —",
      "החזר את **אותה** פעולה עם השדות המעודכנים, אלא אם הוא ביקש במפורש משהו אחר.",
      `הצעה קודמת: ${JSON.stringify(context.prior)}`,
    );
  }

  /*
   * מי מדבר ומאיפה — בזנב הפרומפט, יחד עם השעה ומהסיבה שלה בדיוק:
   * זהו החלק שמשתנה בין קריאה לקריאה, והתחילית הקבועה (הקטלוג
   * והכללים) חייבת להישאר זהה כדי להיכנס למטמון של Google.
   */
  const speaker = context.speaker;
  if (speaker !== undefined) {
    const who = [speaker.name, speaker.roleLabel].filter(Boolean).join(", ");
    lines.push(
      "",
      "## מי מדבר",
      "",
      who === "" ? "מתווך במשרד." : `${who}.`,
      speaker.scope === "own"
        ? 'רואה **רק את הרשומות שמשויכות אליו** ולא את כל המשרד. "הקונים שלי" ו"הקונים" הם אותו דבר עבורו.'
        : "רואה את כל נתוני המשרד.",
    );
  }
  if (context.channel === "whatsapp") {
    lines.push(
      "",
      "התשובה תיקרא בוואטסאפ בטלפון: אם מילאת `reply` — עד שש שורות קצרות, בלי כותרות ובלי Markdown מלבד *הדגשה*.",
    );
  }

  lines.push(
    "",
    "## המשפט",
    "",
    // השעה צמודה למשפט — החלק המשתנה של הפרומפט, אחרי התחילית הקבועה
    `(לידיעתך בלבד, לפרשנות מילות זמן: ${context.nowText}.)`,
    `"${transcript.replaceAll('"', "'")}"`,
  );

  return lines.join("\n");
}
