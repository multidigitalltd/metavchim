/**
 * ההצעה — מה שהמתווך רואה ומאשר.
 *
 * ## למה מבנה אחיד לכל הפעולות
 *
 * בסוכן הקודם לכל כוונה היה טיפול משלה במסך, ולכן כל פעולה חדשה
 * דרשה ענף `switch` נוסף ב-JSX. התוצאה הייתה שרוב הפעולות קיבלו
 * טיפול חלקי — „המשך →” שמעביר למסך אחר עם הטקסט בפרמטר URL, ושם
 * החילוץ רץ **מחדש** ומה שהובן נזרק בדרך.
 *
 * כאן ההצעה היא מבנה אחד: כותרת, שורות שדה, חוסרים ואזהרות. המסך
 * מרנדר אותו בלי לדעת איזו פעולה זו, והפעולה נשמרת עם בדיוק
 * הערכים שהוצגו.
 *
 * ## למה `source` על כל שדה
 *
 * מתווך שרואה „4 חדרים” אינו יודע אם המערכת שמעה זאת או ניחשה.
 * הסימון מבחין בין מה שהמודל הבין, מה שהקוד הדטרמיניסטי חילץ, ומה
 * שנפתר מול המאגר — ולכן אפשר לסמוך על השדות בלי לבדוק את כולם.
 */

export type AgentFieldSource =
  /** המודל הבין מהמשפט */
  | "llm"
  /** מנוע החוקים — כשאין Gemini או שהקריאה נכשלה */
  | "rules"
  /** הקוד הכריע: תאריך מלוח, מקום מול אוצר המילים, טלפון מנורמל */
  | "resolved"
  /** המתווך הקליד או תיקן */
  | "user";

export interface AgentField {
  key: string;
  label: string;
  /** הערך הגולמי — כפי שיישלח לביצוע */
  value: unknown;
  /** הערך כפי שמוצג (תוויות עברית ל-enum, פסיקים במחיר) */
  display: string;
  source: AgentFieldSource;
  /** המילים שממנה הובן השדה — מוצג כטקסט משני מתחת לערך */
  evidence?: string;
}

/**
 * מועמד לזיהוי ישות. מוחזר כשהביטוי שנאמר מתאים ליותר מרשומה אחת.
 *
 * הרשימה **אינה** נפתרת אוטומטית לראשונה גם כשהיא ברורה למדי:
 * „שלח לשרה” כששתי שרה קיימות במאגר הוא בדיוק המקרה שבו טעות
 * שקטה מגיעה ללקוח הלא נכון.
 */
export interface AgentCandidate {
  id: string;
  label: string;
  /** פרט מבחין — עיר, טלפון חלקי, מחיר */
  detail?: string;
}

export interface AgentProposal {
  actionId: string;
  title: string;
  risk: "read" | "create" | "update" | "outbound";
  /** משפט אחד שמתאר מה עומד לקרות */
  summary: string;
  fields: AgentField[];
  /** שדות שהפעולה שווה יותר איתם — מוצגים כהשלמות, לא כשגיאות */
  missing: { key: string; label: string }[];
  /**
   * מה שצריך לומר בקול רם לפני האישור: מקום שלא נמצא במאגר, שדה
   * שהמודל החזיר ונפסל, פרט שנאמר ולא נכנס לשום מקום.
   */
  warnings: string[];
  /**
   * זיהוי ישות שדורש בחירה — הפעולה חסומה עד שנבחר.
   * `idKey` אומר למסך תחת איזה מפתח לשלוח את הבחירה לביצוע
   * (buyerId / propertyId / taskId / cardId / leadId).
   */
  candidates?: { key: string; idKey: string; label: string; options: AgentCandidate[] };
  /** שאלה אחת, כשבאמת אי אפשר להציע בלעדיה */
  clarify?: string;
  /** האם המנוע הדטרמיניסטי הכריע — כלומר Gemini לא היה זמין */
  fallback: boolean;
  /**
   * צעדי המשך — כשמשפט אחד ביקש כמה פעולות ("תוסיף קונה משה ותקבע
   * לו סיור"). מאושרים יחד עם הצעד הראשון ומבוצעים לפי הסדר; ביטוי
   * שמפנה למי שנוצר בצעד קודם נפתר בזמן הביצוע, אחרי שהרשומה כבר
   * קיימת. לצעד המשך אין followUps משלו — השרשור שטוח.
   */
  followUps?: AgentProposal[];
}
