const PLACEHOLDER_PATTERN = /\{\{\s*([\p{L}_]+)\s*\}\}/gu;

export interface RenderedAgreement {
  text: string;
  /** שדות שהופיעו בנוסח ולא היה להם ערך — מוצגים למתווך לפני שליחה */
  unfilled: string[];
}

/**
 * מילוי הנוסח. שדה בלי ערך *לא* נמחק אלא מסומן — הסכם שנשלח עם
 * "מחיר: " ריק הוא פגם, ועדיף שהמתווך יראה את זה לפני הלקוח.
 */
export function renderAgreement(
  template: string,
  values: Partial<AgreementValues>,
): RenderedAgreement {
  const unfilled: string[] = [];
  const text = template.replace(PLACEHOLDER_PATTERN, (_match, rawName: string) => {
    const name = rawName as keyof AgreementValues;
    const value = values[name];
    if (value === undefined || value.trim() === "") {
      if (!unfilled.includes(name)) unfilled.push(name);
      return `[חסר: ${name.replace(/_/gu, " ")}]`;
    }
    return value;
  });
  return { text, unfilled };
}

/** פרטי חובה מהתקנות שהנוסח המותאם השמיט. ריק = תקין. */
export function missingRequiredPlaceholders(
  kind: AgreementKind,
  template: string,
): (keyof AgreementValues)[] {
  const present = new Set<string>();
  for (const match of template.matchAll(PLACEHOLDER_PATTERN)) {
    if (match[1]) present.add(match[1]);
  }
  return REQUIRED_PLACEHOLDERS[kind].filter((name) => !present.has(name));
}
