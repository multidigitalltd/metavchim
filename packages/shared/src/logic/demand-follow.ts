/**
 * ‎**„עקוב אחרי הביקוש” — מה שקורה כשאין לך נכס מתאים היום.**
 *
 * ## הבעיה שהקובץ הזה פותר
 *
 * ‏רשת השיתופים מציגה שני סוגי ביקושים: כאלה שיש לך נכס עבורם,
 * וכאלה שאין. הראשונים הם עבודה — כפתור „הצע נכס זה” ולחיצה אחת.
 * ‏**השניים לא היו כלום.** מתווך קרא אותם, ראה שאין לו מה להציע,
 * וזה נגמר שם — גם כשהנכס שהיה מתאים בדיוק נכנס למאגר שלו שבוע
 * אחר כך. איש לא חוזר לגלול ביקושים ישנים כדי לבדוק.
 *
 * ‏המעקב הופך את הביקוש הזה מ„אין לי מה לעשות” ל„אני אדע”: הסורק
 * בודק כל יום את הנכסים החדשים של העוקב מול הביקושים שהוא עוקב
 * אחריהם, ושולח התראה כשנכנס נכס שמתאים.
 *
 * ## שלוש ההכרעות
 *
 * ‎**1. המעקב הוא של האדם, לא של המשרד.** סוכן שלחץ הוא זה שיקבל
 * את ההתראה. מעקב משרדי היה שולח לכל הצוות התראה על נכס שרק אחד
 * מהם עוסק בו, ואחרי שבוע כולם היו מכבים התראות.
 *
 * ‎**2. התראה אחת לכל צמד (מעקב, נכס).** נכס שנכנס ומתאים מייצר
 * הודעה אחת. עדכון של אותו נכס למחרת אינו מייצר שנייה — האילוץ
 * במסד הוא שמכריע, ולכן הסורק אינו צריך לקרוא לפני שהוא כותב.
 *
 * ‎**3. אותו סף כמו הכרטיס.** ‏`NETWORK_MATCH_MIN_SCORE` הוא מה
 * שמכריע גם מה נספר כ„הנכסים שלך שמתאימים” בכרטיס וגם מה מפעיל
 * את ההתראה. שני ספים היו יוצרים את הסתירה הגרועה ביותר: כרטיס
 * שאומר „מתאים” לצד התראה שלא הגיעה.
 */

import type { NotificationCopy } from "./notifications.js";

/** ‏סוג ההתראה שנשלחת לעוקב כשנכנס נכס מתאים. */
export const DEMAND_MATCH_NOTIFICATION_TYPE = "coop_demand_match";

/**
 * ‏כמה ביקושים אדם אחד יכול לעקוב אחריהם.
 *
 * ‏הגבול אינו טכני אלא של תשומת לב: מי שעוקב אחרי מאתיים ביקושים
 * מקבל התראות שאינן אומרות לו דבר, ואז הוא מכבה את כולן. מספר
 * שמחייב לבחור הוא מה ששומר על ההתראה משמעותית.
 */
export const MAX_FOLLOWS_PER_USER = 40;

/**
 * ‎**מפתח הייחודיות של ההתראה.**
 *
 * ‏המעקב והנכס — ולא הביקוש והנכס: שני סוכנים באותו משרד יכולים
 * לעקוב אחרי אותו ביקוש, וכל אחד מהם אמור לקבל את ההודעה שלו.
 */
export function demandMatchDedupeKey(followId: string, propertyId: string): string {
  return `coop_follow:${followId}:${propertyId}`;
}

export interface DemandMatchCopyInput {
  /** ‏הביקוש כפי שהמסך מתאר אותו — „קונה מחפש 4 חדרים בחולון”. */
  demandLabel: string;
  /** ‏הנכס שנכנס והתאים. */
  propertyTitle: string;
  /** ‏ציון ההתאמה, 0–100. */
  score: number;
}

/**
 * ‎**ההודעה לעוקב — עם שני הצדדים, ולא רק עם הבשורה.**
 *
 * ‏„נמצאה התאמה לביקוש שאתה עוקב אחריו” מחייב לפתוח את המסך כדי
 * לדעת על מה מדובר. „דירת 4 חדרים ברחוב כצנלסון מתאימה לקונה
 * שחיפש בחולון” היא משהו שאפשר להחליט עליו מהטלפון.
 */
export function demandMatchCopy(input: DemandMatchCopyInput): NotificationCopy {
  return {
    title: `נכס שלך מתאים לביקוש שאתה עוקב אחריו`,
    body: `${input.propertyTitle} — ${input.score}% התאמה ל${input.demandLabel}. אפשר להציע אותו עכשיו.`,
  };
}

/**
 * ‏תווית הכפתור.
 *
 * ‎**„עוקבים” ולא „הפסק לעקוב”.** כפתור שאומר את פעולת הביטול
 * מאלץ לקרוא אותו כדי לדעת מה המצב הנוכחי; כפתור שאומר את המצב
 * נקרא בעין אחת, והלחיצה עליו ממילא מבטלת.
 */
export function followLabel(following: boolean): string {
  return following ? "עוקבים אחרי הביקוש" : "עקוב אחרי הביקוש";
}

/**
 * ‏השורה שמסבירה למה הכפתור הזה קיים בכרטיס הזה.
 *
 * ‏היא נאמרת רק כשאין התאמה: בכרטיס שיש בו נכס מתאים המעקב מיותר,
 * והפעולה הנכונה שם היא להציע.
 */
export const FOLLOW_EMPTY_TITLE = "אין לכם עדיין נכס שתואם לביקוש הזה";
export const FOLLOW_EMPTY_NOTE =
  "אפשר לעקוב, ותקבלו התראה ברגע שייכנס נכס מתאים למאגר.";

/** ‏מה שנאמר אחרי הלחיצה — אישור קצר, ולא הסבר חוזר. */
export const FOLLOW_ACTIVE_NOTE = "נעדכן אתכם ברגע שייכנס נכס שמתאים.";

/**
 * ‎**הביקוש במילים — כפי שההתראה מזכירה אותו.**
 *
 * ‏„הביקוש שאתה עוקב אחריו” מחייב לפתוח את המסך כדי לדעת על מה
 * מדובר. „קונה שמחפש 4 חדרים בחולון” הוא משהו שאפשר לזהות מיד.
 *
 * ‏שלושה פרטים ולא יותר: חדרים, עיר, וסוג עסקה כשהוא שכירות.
 * תיאור ארוך יותר לא נכנס בהתראה בטלפון, ומה שנחתך שם נחתך באמצע.
 */
export function demandLabel(demand: {
  cities: readonly string[];
  roomsMin?: number | null;
  roomsMax?: number | null;
  dealType?: string | null;
}): string {
  const min = demand.roomsMin ?? null;
  const max = demand.roomsMax ?? null;
  const rooms =
    min === null && max === null
      ? ""
      : min !== null && max !== null && min !== max
        ? `${min}–${max} חדרים`
        : `${min ?? max} חדרים`;
  const city = demand.cities[0] ?? "";
  /* ‏„קונה” בברירת מחדל; שכירות היא הכיוון השני ואסור לקרוא לו קנייה */
  const who = demand.dealType === "rent" ? "שוכר" : "קונה";
  const parts = [
    `${who} שמחפש`,
    rooms,
    city === "" ? "" : `ב${city}`,
  ].filter((part) => part !== "");
  /* ‏בלי חדרים ובלי עיר — „קונה שמחפש” לבדו אינו משפט */
  return parts.length === 1 ? who : parts.join(" ");
}
