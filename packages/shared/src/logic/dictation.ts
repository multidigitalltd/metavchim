/**
 * הלוגיקה הטהורה של ההכתבה — איסוף הטקסט מהמנוע וחיבורו לשדה.
 *
 * ## למה כאן ולא ב-`apps/web`
 *
 * הקוד הזה ישב ב-`apps/web/src/lib/dictation.ts`, שאין בו הרצת
 * בדיקות. כלומר שני התיקונים הקודמים לכפילות ההכתבה נמסרו בלי
 * שאיש הריץ עליהם ולו מקרה אחד — והבאג חזר. כאן הוא נבדק.
 *
 * שני מנועי ההכתבה במערכת (שדות הטפסים ומסך הסוכן) קוראים לאותן
 * הפונקציות: תיקון שחי רק באחד מהם משאיר את הכפילות בשני.
 */

/**
 * קטע אחד מרשימת התוצאות של מנוע הזיהוי.
 *
 * מוגדר רחב בכוונה — זו רשימה חיה של הדפדפן (`SpeechRecognitionResultList`),
 * לא מבנה שאנחנו בונים, ודפדפנים שונים ממלאים אותה אחרת.
 */
export interface DictationResultSegment {
  readonly isFinal?: boolean;
  readonly 0?: { transcript: string } | undefined;
}

/**
 * איסוף הטקסט מרשימת תוצאות הזיהוי — עם סינון השכפול של אנדרואיד.
 *
 * כרום באנדרואיד, במצב `continuous`, משכפל קטעים: אותה תוצאה מופיעה
 * פעמיים ברצף ברשימה, והטקסט נכתב פעמיים.
 *
 * ## איך מבדילים שכפול מחזרה מכוונת
 *
 * מי שחוזר על מילה אחרי הפסקה („לא… לא”) מייצר באמת שני קטעים
 * זהים עוקבים — ומחיקת כל קטע שזהה לקודמו הייתה בולעת גם אותם.
 * ההבדל הוא בדרך שבה הקטע נולד: קטע אמיתי גדל מול העיניים — הוא
 * מופיע קודם כתוצאה זמנית (`isFinal === false`) ורק אז מתקבע; קטע
 * הרפאים של אנדרואיד מופיע יש-מאין, סופי מיד, לצד התאום שלו.
 *
 * לכן `interimSeen` — סט האינדקסים שנראו אי פעם כזמניים בסבב הזה,
 * שהקורא מחזיק בין אירועים — קובע: קטע זהה לקודמו נמחק רק אם
 * מעולם לא היה זמני.
 *
 * ## הרשימה מצטברת, והטקסט המוחזר הוא הסבב כולו
 *
 * `event.results` מכיל את **כל** הסבב מאינדקס 0, ולא רק את החדש.
 * לכן המחזיר כאן אינו „מה נוסף” אלא „מה נאמר עד כה”, והקורא כותב
 * אותו על טקסט בסיס קבוע. כל דרך אחרת מצטברת כפול.
 */
export function collectDictation(
  results: ArrayLike<DictationResultSegment | undefined>,
  /** אינדקסים שנראו כתוצאה זמנית בסבב הזה — סט אחד לכל סשן הקלטה */
  interimSeen: Set<number>,
): { final: string; interim: string } {
  let final = "";
  let interim = "";
  let previous = "";
  for (let i = 0; i < results.length; i += 1) {
    const segment = results[i];
    const text = segment?.[0]?.transcript ?? "";
    if (text.trim() === "") continue;
    const isInterim = segment?.isFinal === false;
    if (isInterim) interimSeen.add(i);
    // קטע רפאים: זהה לקודמו, סופי, ומעולם לא חי כתוצאה זמנית
    if (!isInterim && text.trim() === previous.trim() && !interimSeen.has(i)) continue;
    previous = text;
    if (isInterim) interim += text;
    else final += text;
  }
  return { final, interim };
}

/**
 * חיבור הטקסט המוכתב לטקסט שכבר היה בשדה.
 *
 * ארבעה מקומות במערכת כתבו את אותן שלוש השורות בעצמם, ואחד מהם
 * הוא בדיוק המקום שבו רווח כפול או בסיס ריק נראים כמו באג. פונקציה
 * אחת, כלל אחד: הבסיס נשמר כפי שהוא, נחתך בקצה, ומופרד ברווח יחיד.
 */
export function appendDictated(base: string, spoken: string): string {
  const text = spoken.trim();
  if (text === "") return base;
  return base.trim() === "" ? text : `${base.trimEnd()} ${text}`;
}

/**
 * מי הסבב הפעיל — הלב של תיקון „ההכתבה מתמללת פעמיים”.
 *
 * ## הבאג שזה מתקן
 *
 * מנוע הזיהוי אינו נעצר ברגע ש-`stop()` נקרא: הוא מחזיר תוצאה
 * אחרונה ואז יורה `onend`, מאות מילישניות אחר כך. עד כה הזהות של
 * הסבב הייתה ה-ref היחיד שהחזיק את המנוע, ולכן משתמש שלחץ „מהיר”
 * שוב לפני שהסבב הקודם נסגר קיבל שרשרת שלמה של תקלות:
 *
 * 1. `onend` של הסבב **הישן** התעורר, איפס את ה-ref — ובכך ניתק
 *    את המערכת מהמנוע **החדש** שכבר רץ — וכיבה את מצב „מקליט”.
 * 2. המנוע החדש נשאר חי בלי שאיש יעצור אותו, וממשיך לכתוב לשדה.
 * 3. „הסבב הסתיים” נורה באמצע הסבב, טקסט הבסיס אופס, והתוצאה
 *    הבאה נכתבה על טקסט שכבר מכיל אותה — כלומר הכול פעמיים.
 * 4. לחיצה נוספת הוסיפה מנוע שלישי: שניים מקליטים במקביל, וכל
 *    מילה נכתבת פעמיים באמת.
 *
 * ## הכלל
 *
 * לכל סבב מספר משלו. כל callback שמגיע — תוצאה, סיום, שגיאה או
 * שעון הביטחון — מציג את המספר שלו, ומי שאינו הסבב הנוכחי אינו
 * נוגע בכלום. סבב חדש מבטל את הקודם במפורש, ולא מקווה שייסגר.
 */
export interface DictationSessions {
  /** פותח סבב חדש ומבטל את הקודם. מחזיר את מזהה הסבב החדש. */
  begin: () => number;
  /** האם המזהה הזה הוא הסבב הפעיל כרגע. */
  isCurrent: (token: number) => boolean;
  /**
   * סוגר את הסבב הזה. מחזיר `false` אם הוא כבר לא היה הפעיל —
   * ואז לקורא אין רשות לגעת במצב.
   */
  end: (token: number) => boolean;
}

export function createDictationSessions(): DictationSessions {
  /* 0 אינו מזהה חוקי: הוא „אין סבב”, כך שאף callback לא יתפוס אותו במקרה */
  let current = 0;
  let next = 0;
  return {
    begin(): number {
      next += 1;
      current = next;
      return current;
    },
    isCurrent(token: number): boolean {
      return token !== 0 && token === current;
    },
    end(token: number): boolean {
      if (token === 0 || token !== current) return false;
      current = 0;
      return true;
    },
  };
}
