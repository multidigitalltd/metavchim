/**
 * ‎**מסירה עמומה — ומה עושים בניסיון השני.**
 *
 * ‏שליחת מייל היא פעולה חיצונית בלתי הפיכה, ולכישלון שלה יש שתי
 * ‏משמעויות שונות לחלוטין: ‎4xx פירושו שהספק **בדק ופסל**, כלומר
 * ‏ההודעה בוודאות לא יצאה; פסק זמן, נפילת רשת או ‎5xx פירושם
 * ‏ש**איננו יודעים** — ייתכן ש-Postmark קיבל את ההודעה ושלח אותה,
 * ‏ורק התשובה אבדה בדרך חזרה.
 *
 * ‏עד כה שני המקרים נראו לקורא כמעט זהים, ולכן כל ניסיון חוזר היה
 * ‏הימור: לשלוח שוב ולסכן מייל כפול ללקוח, או לא לשלוח ולסכן מייל
 * ‏שלא הגיע. אין ניסוח של „נסה שוב” שפותר את זה בלי **זיכרון**.
 *
 * ‎**המפתח הוא זהות עסקית ולא טביעת אצבע של התוכן.** „אותו הסכם
 * ‏לאותו לקוח” הוא אותה שליחה גם אם הנוסח עודכן; „תזכורת החידוש
 * ‏של החודש הבא” היא שליחה חדשה גם אם הנוסח זהה בתו. גזירה
 * ‏מהתוכן הייתה בולעת את השנייה ומפספסת את הראשונה.
 */

/** מצב הניסיון כפי שהוא שמור. */
export type EmailAttemptStatus = "sending" | "sent" | "unknown" | "rejected";

/**
 * מה לעשות עכשיו, בהינתן ניסיון קודם עם אותו מפתח.
 *
 * ‎`send` — אין ניסיון קודם, או שידוע שהוא לא יצא. שולחים.
 * ‎`resolved` — כבר יצא. לא שולחים, ומדווחים הצלחה.
 * ‎`probe` — עמום. שואלים את הספק אם ההודעה קיימת אצלו, ורק אז
 * ‏מכריעים; זו הסיבה שהמפתח נשלח גם כ-Metadata בהודעה עצמה.
 * ‎`inFlight` — שליחה זהה ממש עכשיו בתהליך אחר. לא שולחים שוב.
 */
export type EmailAttemptDecision = "send" | "resolved" | "probe" | "inFlight";

/**
 * ‎**כמה זמן `sending` עדיין אומר „בתהליך”.**
 *
 * ‏פסק הזמן של הקריאה לספק הוא עשר שניות. תהליך שנפל בין הכתיבה
 * ‏לשליחה משאיר שורה תקועה ב-`sending` לנצח, ובלי תקרה כזו כל
 * ‏שליחה עתידית עם אותו מפתח הייתה נחסמת לתמיד — כלומר הזיכרון
 * ‏שנועד למנוע כפילות היה הופך לחסם מסירה.
 *
 * ‏המרווח נדיב במכוון: הוא נמדד מול תהליך שקרס, לא מול קריאה
 * ‏איטית, ומחיר ההמתנה הוא דקה בניסיון החוזר.
 */
export const EMAIL_ATTEMPT_STALE_MS = 60_000;

/**
 * ההכרעה עצמה — פונקציה טהורה, ולכן היא זו שנבדקת.
 *
 * ‎`previous === null` הוא „אין ניסיון קודם”, וזו גם התשובה למי
 * ‏שאינו מבקש הגנה בכלל.
 */
export function emailAttemptDecision(
  previous: { status: EmailAttemptStatus; updatedAt: Date } | null,
  now: Date,
  staleMs: number = EMAIL_ATTEMPT_STALE_MS,
): EmailAttemptDecision {
  if (previous === null) return "send";
  switch (previous.status) {
    case "sent":
      return "resolved";
    /*
     * ‏נדחה = הספק בדק ופסל, ולכן בוודאות לא יצאה הודעה. ניסיון
     * ‏חוזר כאן אינו כפילות אלא בדיוק מה שהקורא מתכוון אליו.
     */
    case "rejected":
      return "send";
    case "unknown":
      return "probe";
    /*
     * ‎`sending` טרי הוא תהליך אחר שעובד עכשיו; `sending` ישן הוא
     * ‏תהליך שקרס, ואז מצבו זהה ל„עמום” — ייתכן שההודעה יצאה לפני
     * ‏הקריסה. בשני המקרים לא שולחים בעיוורון.
     */
    case "sending":
      return now.getTime() - previous.updatedAt.getTime() >= staleMs ? "probe" : "inFlight";
  }
}

/**
 * ‎**המפתח שהספק יראה** — ‎`Metadata` על ההודעה היוצאת.
 *
 * ‏זה מה שהופך את „עמום” לניתן להכרעה בדיעבד: חיפוש ההודעות
 * ‏היוצאות של Postmark מסנן לפי `metadata_<key>`, ולכן אפשר לשאול
 * ‏אותו „האם ההודעה הזו קיימת אצלך” במקום לנחש.
 *
 * ‏שם המפתח קצר ואחיד בכוונה: הוא נכנס למחרוזת שאילתה, והספק מתיר
 * ‏שדה מטא-דאטה **אחד** בחיפוש.
 */
export const EMAIL_IDEMPOTENCY_METADATA_KEY = "idem";

/**
 * ‎**גבול אורך המפתח — של הספק, ולכן שלנו.**
 *
 * ‏Postmark מגביל ערך מטא-דאטה ל-80 תווים. מפתח ארוך מזה היה נשלח
 * ‏קטוע, והחיפוש בדיעבד היה מחפש מחרוזת שאינה קיימת — כלומר ההגנה
 * ‏הייתה נשברת בדיוק ברגע שנזקקים לה. לכן זו שגיאת קורא ולא קיצור
 * ‏שקט.
 */
export const EMAIL_IDEMPOTENCY_KEY_MAX = 80;

/** ‏מפתח תקין: אורך סביר, ובלי תווים ששוברים מחרוזת שאילתה. */
export function isValidEmailIdempotencyKey(key: string): boolean {
  return key.length > 0 && key.length <= EMAIL_IDEMPOTENCY_KEY_MAX && /^[A-Za-z0-9:._-]+$/u.test(key);
}

/**
 * ‎**מפתח לאירוע שיכול לקרות שוב — זהות ועוד היום שבו קרה.**
 *
 * ‏„המקום הזה עבר לחוב” אינו אירוע יחיד לאורך זמן: מקום שנכנס
 * ‏לחוב, הוסדר, ושב לחוב כעבור שבוע הוא **שני** אירועים ושתי
 * ‏הודעות. מפתח שהוא המזהה בלבד היה בולע את השנייה — כלומר
 * ‏המנגנון שנועד למנוע כפילות היה מונע הודעה אמיתית.
 *
 * ‏היום הוא הגרעיניות הנכונה כאן מפני שהסורקים האלה רצים יומית:
 * ‏חזרה **באותו יום** היא ניסיון חוזר על אותה סריקה; יום אחר הוא
 * ‏מצב חדש שראוי לדווח עליו.
 *
 * ‏אירוע שקורה פעם אחת בחיי הישות (מייל הצטרפות, פנייה חד-פעמית)
 * ‏אינו משתמש בזה — שם המזהה לבדו הוא הזהות, ובול.
 */
export function dailyEmailIdempotencyKey(purpose: string, id: string, now: Date): string {
  return `${purpose}:${id}:${now.toISOString().slice(0, 10)}`;
}
