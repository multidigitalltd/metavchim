/**
 * ‏אימוג'י אחד או יותר, ושום דבר אחר.
 *
 * ‎`Extended_Pictographic` הוא המאפיין שמכסה את הסמלים
 * ‏הגרפיים; לצידו מותרים מה שמרכיב אימוג'י מורכב — בורר וריאציה,
 * ‏מחבר אפס-רוחב, גוני עור — ורווחים.
 *
 * ‎**דגל אינו „סמל גרפי”.** ‏הוא בנוי משתי אותיות
 * ‏אזוריות, ו-`Extended_Pictographic` אינו כולל אותן. בלעדיו
 * ‏דגל היה נופל למנוע ההבנה ומקבל „לא הבנתי”.
 *
 * ‎**וספרה אינה אימוג'י כאן.** ‏`3\u{FE0F}\u{20E3}` בנוי מספרה ועוד
 * ‏סימני צירוף, אבל מספר סידורי הוא בדיוק איך שבוחרים
 * ‏רשומה מרשימה — ולכן הוא נפסל כאן במפורש.
 *
 * ‏כל התווים הבלתי-נראים נכתבים כרצף בריחה ולא כתו עצמו:
 * ‏מחבר אפס-רוחב בתוך מחלקת תווים נראה כמו כלום, ועריכה
 * ‏אחת שמוחקת אותו בטעות אינה משנה דבר במסך העורך.
 */
const PICTOGRAPH = /[\p{Extended_Pictographic}\p{Regional_Indicator}]/u;
/*
 * ‏חלופה ולא מחלקת תווים: מחבר אפס-רוחב, בורר וריאציה
 * ‏וגוני עור הם **מצרפים**, ומחלקת תווים שמכילה מצרף
 * ‏קוראת כאילו הוא תו עצמאי (`no-misleading-character-class`).
 */
const EMOJI_ONLY =
  /^(?:[\p{Extended_Pictographic}\p{Regional_Indicator}]|\u200D|\uFE0F|\uFE0E|[\u{1F3FB}-\u{1F3FF}]|\s)+$/u;
/** ‏סימן התיבה שהופך ספרה ל„ספרה בתיבה”. */
const KEYCAP = /\u20E3/u;
/** ‏בוררי הווריאציה — `\u2764\uFE0F` ו-`\u2764` הם אותו לב. */
const VARIATION = /[\uFE0F\uFE0E]/gu;

/** האם כל מה שנכתב הוא אימוג'י — ויש בו לפחות אחד. */
export function isEmojiOnlyMessage(text: string): boolean {
  const trimmed = text.trim();
  if (trimmed === "") return false;
  if (KEYCAP.test(trimmed)) return false;
  return EMOJI_ONLY.test(trimmed) && PICTOGRAPH.test(trimmed);
}

export type EmojiSentiment = "positive" | "negative" | "neutral";

/**
 * ‏מה האימוג'י אומר — בשלוש קטגוריות, לא ברשימה פתוחה.
 *
 * ‏הרשימות קצרות בכוונה: מה שאינו ברור מסווג „ניטרלי”, והתשובה
 * ‏הניטרלית מתאימה גם לחיובי וגם לשלילי. ניחוש שגוי על אימוג'י
 * ‏נדיר גרוע מתשובה כללית שנכונה תמיד.
 */
const POSITIVE = new Set([
  "👍", "👌", "🙏", "❤", "🧡", "💛", "💚", "💙", "💜", "🤍",
  "😊", "😀", "😃", "😄", "🙂", "😁", "🥳", "🎉", "🎊", "👏", "💪",
  "🔥", "✅", "✔", "💯", "⭐", "🌟", "😍", "🤩", "☺",
]);
const NEGATIVE = new Set([
  "👎", "😞", "😔", "😢", "😭", "😠", "😡", "🤬", "😤", "🙄", "😕",
  "☹", "🙁", "💔", "❌", "✖", "🤦", "😑",
]);

/** הסיווג נעשה על האימוג'י הראשון — הוא מה שנאמר, והשאר הדגשה. */
export function emojiSentiment(text: string): EmojiSentiment {
  for (const char of Array.from(text.trim())) {
    const bare = char.replace(VARIATION, "");
    if (POSITIVE.has(char) || POSITIVE.has(bare)) return "positive";
    if (NEGATIVE.has(char) || NEGATIVE.has(bare)) return "negative";
  }
  return "neutral";
}

/**
 * ‏מה הסוכן עונה על הודעה שכולה אימוג'י.
 *
 * ‏קצר, אנושי, ובלי רשימת יכולות: מי ששלח 👍 יודע מה המערכת
 * ‏עושה. המשפט השני הוא הזמנה להמשיך, לא הסבר.
 */
export function emojiOnlyReply(sentiment: EmojiSentiment): string {
  if (sentiment === "positive") return "😊 קיבלתי. כשתצטרך משהו — אני כאן.";
  if (sentiment === "negative")
    return "מבין. כתוב לי במילים מה לא עבד, ואני אטפל בזה.";
  return "קיבלתי 🙂 כתוב לי מה לעשות ואני על זה.";
}
