/**
 * מחיקת ליד — הדרך הרביעית, וההפוכה משלוש האחרות.
 *
 * ליד יכול להפוך לקונה, להפוך לנכס, או להימכר ברשת. אבל ליד ספאם,
 * טעות במספר או פנייה שאינה קשורה לנדל"ן אינו אף אחד מאלה: הוא זבל,
 * ו"סגור" רק מסתיר אותו ברשימה. מחיקה מוציאה אותו מהמסד.
 *
 * **למה זו לא מחיקה רכה.** לנכס ולקונה יש `deletedAt` כי מאחוריהם
 * יש היסטוריה עסקית — הצעות, התאמות, עסקאות — שאסור להעלים. לליד
 * זבל אין היסטוריה, ומה שכן יש בו הוא בדיוק מה שהמשרד רוצה שייעלם:
 * שם וטלפון של מישהו שלא ביקש להיות אצלו במאגר (docs/04 §5).
 */

/**
 * מה חוסם מחיקה — הודעה בעברית, או `null` כשמותר.
 *
 * הכלל היחיד: **ליד שהומר אינו נמחק.** ההמרה כבר יצרה כרטיס קונה או
 * נכס שמצביע על אותו איש קשר, ומחיקת הליד הייתה משאירה את הכרטיס
 * הזה בלי המקור שלו. מי שרוצה להיפטר משניהם מוחק את הכרטיס עצמו.
 *
 * ליד שמוצע כרגע למכירה בשוק השת"פ **אינו** חסום: הוא פשוט יורד
 * מהשוק לפני המחיקה. חסימה כאן הייתה מכריחה את המשרד לזכור מסך אחר
 * לפני שהוא מוחק זבל.
 */
export function leadDeletionRejectionReason(status: string): string | null {
  if (status === "converted") {
    return "ליד שהומר כבר יצר כרטיס — מחקו את כרטיס הקונה או הנכס שנוצר ממנו";
  }
  return null;
}

/**
 * מה בדיוק מוחקים — שתי כוונות שונות שנראו עד היום כפעולה אחת.
 *
 * - `lead` — **הפנייה בלבד.** הליד היה טעות, כפילות או פנייה שנסגרה,
 *   אבל האדם עצמו לקוח של המשרד ואמור להישאר במאגר עם הטלפון,
 *   ההערות ובני הזוג שלו. זו ברירת המחדל במסך.
 * - `lead_and_contact` — **גם הכרטיס.** ספאם או טעות במספר: מי
 *   שנמחק כאן לא ביקש להיות במאגר. הכרטיס יורד רק אם לא נשאר לו
 *   שום קשר אחר במשרד; אם הוא גם קונה או בעל נכס הוא נשאר בכל מקרה.
 *
 * עד לפני השינוי הזה התנהגות `lead_and_contact` הייתה היחידה, ומי
 * שרצה למחוק ליד כפול של לקוח קיים איבד איתו את כרטיס הלקוח — הפעולה
 * היחידה במערכת שמחקה יותר ממה שביקשו.
 */
export type LeadDeletionScope = "lead" | "lead_and_contact";

/** האם הבקשה משאירה את איש הקשר גם כשלא נשאר לו קשר אחר. */
export function leadDeletionKeepsContact(scope: LeadDeletionScope): boolean {
  return scope === "lead";
}

/**
 * מה לומר אחרי המחיקה — התשובה לשאלה "וגם הלקוח ירד?".
 *
 * `contactDeleted` מגיע מהשרת ולא מהבחירה: מי שביקש למחוק גם את
 * הכרטיס ונשאר לו קונה או נכס יראה שהכרטיס נשאר, וזו בדיוק ההפתעה
 * שעדיף לגלות במסך ולא שבועיים אחר כך.
 */
export function leadDeletionOutcome(contactName: string, contactDeleted: boolean): string {
  return contactDeleted
    ? `הליד של ${contactName} נמחק, וגם כרטיס הלקוח — לא נשאר לו קשר אחר במשרד.`
    : `הליד של ${contactName} נמחק. כרטיס הלקוח נשאר במאגר.`;
}
