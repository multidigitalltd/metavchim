import { coopOfferCost, type LeadSourcePrice } from "./collaboration-cost.js";

/**
 * שוק הלידים בשת"פ: משרד מציע ליד שהוא לא יטפל בו, ומשרד אחר קונה
 * אותו בקרדיטים. הקרדיטים עוברים מהקונה למוכר — זה מה שהופך שיתוף
 * ליד למשתלם, ולא רק ל"ויתור".
 */

/** אורך ההערה שהמוכר מצרף לליד — מוצגת בפיד, לכן קצרה ואנונימית. */
export const MAX_SHARED_LEAD_NOTE = 300;

/** אורך שם העיר שהמוכר מציין (ללידים אין עמודת עיר — זה קלט חופשי). */
export const MAX_SHARED_LEAD_CITY = 120;

/**
 * מחיר ליד בשוק — לפי מקור הליד, מאותה טבלת תמחור של הביקושים.
 *
 * **רצפה של קרדיט אחד.** `coopOfferCost` מחזיר 0 למקורות שהפלטפורמה
 * תמחרה כחינם (כמו `network` בביקושים), אבל ליד שנמכר בשוק הוא איש
 * קשר אמיתי שהמוכר מוותר עליו — מכירה בחינם משאירה את המוכר בלי
 * כלום ואת השוק בלי סיבה לשתף. המחיר נקבע **ברגע השיתוף** ונשמר על
 * השורה; שינוי תמחור מאוחר לא משנה ליד שכבר פורסם.
 */
export function sharedLeadPrice(
  source: string,
  prices: readonly LeadSourcePrice[],
): number {
  return Math.max(1, coopOfferCost(source, prices));
}
