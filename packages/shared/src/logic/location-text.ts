/**
 * שמות מקומות בעברית — **השוואה שסולחת על מה שאין לו משמעות.**
 *
 * עד כה קריטריון המיקום בהתאמות היה `a.trim() === b.trim()` על שם
 * העיר, והוא קריטריון **פוסל**. כלומר "רמת גן" מול "רמת-גן" לא
 * החזירו אפס נקודות — הם הוציאו את ההתאמה מהרשימה לגמרי. אותו דבר
 * עם "תל אביב" מול "תל אביב-יפו", ועם "קרית" מול "קריית".
 *
 * זה לא מקרה קצה: סוכן מקליד שם עיר בכרטיס הקונה, סוכן אחר מקליד
 * אותה עיר בכרטיס הנכס, ואף אחד לא רואה את מה שהשני הקליד. הכתיב
 * הישראלי של שמות יישובים אינו אחיד גם במקורות רשמיים.
 *
 * ## שלוש שכבות, מהבטוחה למסוכנת
 *
 * 1. **ניקוי תווים** — גרשיים, מקפים, רווחים כפולים. חסר משמעות
 *    לחלוטין, ולכן תמיד.
 * 2. **כתיב חלופי** — `קריית`→`קרית`, `תקוה`→`תקווה`. אלה כללי
 *    כתיב מלא/חסר, לא שמות שונים.
 * 3. **שם חלופי מלא** — `תל אביב` ו-`ת"א` הן אותה עיר. הרשימה כאן
 *    **קצרה בכוונה**: כל ערך בה הוא החלטה שאי אפשר לגזור מכלל, ורשימה
 *    שמנסה לכסות את כל הארץ תייצר התאמה שגויה ביום שיש שני יישובים
 *    בעלי שם דומה.
 *
 * מה שנשאר בחוץ במתכוון: קרבה פונטית (Soundex ודומיו). היא מייצרת
 * "כמעט" — ובקריטריון פוסל, "כמעט" הוא התאמה שגויה שאיש לא יבין
 * מאיפה הגיעה.
 */

/**
 * כתיב חלופי — מלא מול חסר. אלה כללים, לא שמות.
 *
 * הסדר חשוב: `קריית` לפני `קרית` היה מייתר, אבל `תקוה`→`תקווה`
 * חייב לרוץ אחרי ניקוי הגרשיים, אחרת `תקוַה` לא נתפס.
 */
const SPELLING: readonly [RegExp, string][] = [
  [/קריית/gu, "קרית"],
  [/תקוה/gu, "תקווה"],
  [/עלית\b/gu, "עילית"],
  [/הרצלייה/gu, "הרצליה"],
  [/נהרייה/gu, "נהריה"],
  [/נתנייה/gu, "נתניה"],
  [/רעננה/gu, "רעננה"],
];

/**
 * שמות חלופיים מלאים. המפתח הוא הצורה **אחרי** נרמול, והערך הוא
 * הצורה הקנונית.
 *
 * קצרה בכוונה — ראו ההסבר למעלה. קיצורים נכללים רק כשהם חד-משמעיים
 * כמילה שלמה: `תא` אינו שם יישוב אחר, ולכן בטוח.
 */
const ALIASES: Readonly<Record<string, string>> = {
  "תל אביב": "תל אביב יפו",
  "תא": "תל אביב יפו",
  "תל אביב  יפו": "תל אביב יפו",
  "ראשלצ": "ראשון לציון",
  "פת": "פתח תקווה",
  "בש": "באר שבע",
  "רג": "רמת גן",
  "בב": "בני ברק",
  "כס": "כפר סבא",
  "קש": "קרית שמונה",
  "מא": "מודיעין מכבים רעות",
  "מודיעין": "מודיעין מכבים רעות",
};

/**
 * שם מקום בצורתו הקנונית.
 *
 * מחזיר מחרוזת ריקה על קלט ריק — קריאה שמחזירה `undefined` הייתה
 * מחייבת כל קורא להתמודד עם שני מצבים באותה נקודה.
 */
export function normalizeLocationName(raw: string): string {
  let text = raw.normalize("NFC").trim().toLowerCase();
  // גרשיים עבריים ולועזיים — קישוט, לא תוכן
  text = text.replace(/[׳״'"`]/gu, "");
  // מקף עברי, מקף רגיל וקו מפריד — כולם רווח
  text = text.replace(/[־\-–—]/gu, " ");
  // נקודה בקיצור ("ק. גת") הופכת לרווח ולא נעלמת, אחרת נוצר "קגת"
  text = text.replace(/[.,]/gu, " ");
  text = text.replace(/\s+/gu, " ").trim();
  for (const [pattern, replacement] of SPELLING) text = text.replace(pattern, replacement);
  text = text.replace(/\s+/gu, " ").trim();
  return ALIASES[text] ?? text;
}

/** האורך המזערי להשוואת הכלה — מתחתיו כל מילה קצרה "מוכלת" בהכל. */
const MIN_CONTAINMENT_LENGTH = 3;

/**
 * כמה שני שמות מקום מתאימים: 1 זהה · 0.85 הכלה · 0 שונה.
 *
 * ההכלה שווה 0.85 ולא 1: "גן" בתוך "גן יבנה" הוא כנראה אותו מקום,
 * אבל לא בוודאות, וההפרש בציון הוא מה שמאפשר להתאמה מדויקת יותר
 * לעלות מעליה ברשימה.
 */
export function locationNameScore(a: string, b: string): number {
  const left = normalizeLocationName(a);
  const right = normalizeLocationName(b);
  if (left === "" || right === "") return 0;
  if (left === right) return 1;
  const [short, long] = left.length <= right.length ? [left, right] : [right, left];
  if (short.length < MIN_CONTAINMENT_LENGTH) return 0;
  return long.includes(short) ? 0.85 : 0;
}

/**
 * הציון הטוב ביותר של שם אחד מול רשימה, ומי התאים.
 *
 * מחזיר את השם **כפי שהמשתמש הקליד אותו** ולא את הצורה הקנונית:
 * הסבר ההתאמה נקרא בידי אדם, ו"באזור המבוקש (תל אביב יפו)" למי
 * שכתב "ת״א" נראה כמו נתון שהמערכת המציאה.
 */
export function bestLocationMatch(
  needle: string,
  candidates: readonly string[],
): { score: number; matched?: string } {
  let best = 0;
  let matched: string | undefined;
  for (const candidate of candidates) {
    const score = locationNameScore(needle, candidate);
    if (score > best) {
      best = score;
      matched = candidate;
      if (score === 1) break;
    }
  }
  return matched === undefined ? { score: 0 } : { score: best, matched };
}

/**
 * כל הצורות שאותו מקום עשוי להיות **שמור** בהן במסד.
 *
 * הנרמול הוא חד-כיווני — הרבה כתיבים מתכנסים לצורה אחת — ולכן
 * שאילתת SQL שמחפשת את הצורה הקנונית בלבד תחמיץ שורות ישנות
 * שנשמרו לפני הנרמול, או שורות שנכתבו בכתיב אחר.
 *
 * הרשימה משמשת **סינון גס בלבד**: היא מרחיבה את קבוצת המועמדים,
 * והניקוד המדויק רץ אחריה. מוטב שתחזיר יותר מדי מאשר תחמיץ נכס.
 */
export function locationNameVariants(name: string): string[] {
  const canonical = normalizeLocationName(name);
  if (canonical === "") return [];
  const out = new Set<string>([canonical, name.trim()]);
  // כל הכתיבים שמתכנסים לצורה הזו — היפוך טבלת השמות החלופיים
  for (const [alias, target] of Object.entries(ALIASES)) {
    if (target === canonical) out.add(alias);
  }
  // רווח ומקף מתחלפים זה בזה בכתיב ישראלי, ושניהם נשמרים כמות שהם
  if (canonical.includes(" ")) out.add(canonical.replace(/ /gu, "-"));
  return [...out];
}
