/** סגנון פתוח, בלי מפתח ובלי חשבון — כדי שמפה תעבוד מהרגע הראשון. */
export const DEFAULT_MAP_STYLE_URL = "https://tiles.openfreemap.org/styles/liberty";

/**
 * המקורות שיש להתיר ב-CSP עבור כתובת סגנון נתונה.
 *
 * מוחזר גם המארח של הסגנון וגם, כשהוא ידוע, מארחי האריחים שהוא
 * מפנה אליהם: קובץ סגנון של MapLibre הוא רק המפתח, והאריחים עצמם
 * מגיעים לעיתים ממארח אחר. כתובת פגומה מחזירה רשימה ריקה במקום
 * להפיל את בניית המדיניות.
 */
export function mapCspOrigins(styleUrl: string | undefined): string[] {
  const raw = styleUrl === undefined || styleUrl.trim() === "" ? DEFAULT_MAP_STYLE_URL : styleUrl;
  /*
   * חילוץ בביטוי רגולרי ולא ב-`URL`: החבילה המשותפת נבנית בלי
   * ספריות סביבה, והיא נצרכת גם ב-Edge Runtime של Next. תבנית
   * מפורשת עובדת בשלושת המקומות ואינה תלויה בפוליפיל.
   */
  const match = /^(https?:\/\/[^/?#\s]+)/u.exec(raw.trim());
  return match?.[1] === undefined ? [] : [match[1]];
}
