/**
 * ‎**מציון להחלטה — הפירוט כצ'יפים (SPEC-4a §1).**
 *
 * הציון לבדו אינו מספיק כדי להחליט אם לשלוח הצעה. „‎87%” אינו אומר
 * אם החדרים תואמים ורק השטח חסר, או שהתקציב בקושי עובר. המתווך
 * שמסתכל על השורה צריך לראות **על מה** נשען המספר, ובעיקר מה חסר —
 * כי זה מה שהוא יכול לתקן.
 *
 * ## שלושה מצבים, לא שניים
 *
 * ההבחנה שהפונקציה הזו קיימת בשבילה:
 *
 * - ‎**תואם** — הקריטריון נבדק ועבר.
 * - ‎**חלקי או נכשל** — נבדק, והתוצאה אינה מלאה. יש לו סיבה, והיא
 *   נכתבת בהערה שהמנוע כבר מנסח („תקציב נמוך ב-5%”).
 * - ‎**חסר בנכס** — הקריטריון **אינו ברשימה כלל**, והסיבה היא
 *   שדה ריק בנכס. אין לו ציון, ולא בגלל שהוא נכשל.
 *
 * השלישי הוא מה שהיה בלתי נראה: קריטריון שנכשל וקריטריון שלא נבדק
 * נראו שניהם כ„לא ירוק”. ההבדל ביניהם הוא ההבדל בין „הקונה הזה לא
 * מתאים” לבין „לא מילאנו שדה” — שתי מסקנות הפוכות מאותו מסך.
 *
 * ## ומצב רביעי, שאינו צ'יפ בכלל
 *
 * קריטריון יכול להיעדר גם משום ש**הקונה לא ביקש אותו**: לא הגדיר
 * תקציב, לא סימן ולו מאפיין אחד כ„נחמד שיהיה”. אין כאן פער, אין
 * מה להשלים, וההתאמה מלאה כפי שהיא.
 *
 * הגרסה הראשונה צבעה גם אותו באפור „לא נבדק”, ולכן התאמה תקינה
 * לחלוטין נראתה כמלאה בשדות פתוחים — והמתווך נשלח לחפש מה למלא
 * (ביקורת Codex). זו אותה טעות שהקובץ הזה נבנה כדי לתקן, מדרגה
 * אחת פנימה: שני מצבים שונים באותו צבע.
 *
 * הוא **אינו מוצג כלל**. „לא רלוונטי לקונה” בתור צ'יפ הוא רעש
 * שתופס מקום ואינו אומר דבר; היעדרו אומר בדיוק את מה שקרה.
 *
 * ## למה כאן ולא ב-JSX
 *
 * ב-`apps/web` אין הרצת בדיקות, וזו החלטה עם שלושה ענפים וסדר.
 * אותו נימוק בדיוק שהעביר לכאן את `collectDictation` ואת
 * ‎`dictationErrorMessage`.
 */

import { MATCH_CRITERIA, type MatchCriterion, type ScoreComponent } from "../schemas/match.js";
import { DEFAULT_MATCH_WEIGHTS, MATCH_CRITERION_LABELS } from "./matching.js";

export type MatchChipTone = "matched" | "partial" | "missing";

export interface MatchChip {
  tone: MatchChipTone;
  /** מה שמוצג — תווית הקריטריון, או ההערה שהמנוע ניסח כשיש כזו. */
  label: string;
  criterion: MatchCriterion;
  /**
   * המשקל שההתאמה **הזו** חושבה לפיו.
   *
   * משרד יכול לכייל משקלים בהגדרות, והרכיב שחזר נושא את המשקל
   * שבפועל שימש. מיון לפי ברירת המחדל היה מציג את סדר החשיבות של
   * המערכת ולא של המשרד — כלומר דוחף קריטריון שהמשרד הכריז עליו
   * כחשוב אל סוף השורה (ביקורת Codex).
   *
   * לקריטריון שלא נבחן אין משקל אפקטיבי — הוא לא השתתף בחישוב —
   * ולכן הוא ממוין לפי ברירת המחדל. זה נכון: הסדר שם עונה על „מה
   * הכי כדאי להשלים”, וזו שאלה על המערכת ולא על ההתאמה שלא קרתה.
   */
  weight: number;
}

/**
 * ‎**סף ה„תואם”.**
 *
 * הניקוד הוא מספר ממשי, והשוואה ל-1 מדויק הייתה מסמנת `0.9999`
 * כחלקי. הסף אינו „כמעט” אלא הכרה בכך שהחישוב מגיע ל-1 דרך כפל
 * שברים.
 */
const FULL = 0.995;

/**
 * הפירוט ⟵ צ'יפים, בסדר שבו הם מוצגים.
 *
 * ‎**הסדר: תואם, אחר כך חלקי, אחר כך לא-נבדק** — ובתוך כל קבוצה לפי
 * המשקל, מהכבד לקל. זה הסדר שבו המתווך קורא: קודם למה כן, אחר כך
 * מה מפריע, ולבסוף מה אפשר להשלים.
 *
 * ‎**כל קריטריון מופיע לכל היותר פעם אחת.** הרשימה נבנית מ-`MATCH_CRITERIA`
 * ולא ממה שהגיע בפירוט, ולכן אין תלות בסדר שבו המנוע דחף רכיבים —
 * וגם אין קריטריון שנשמט בשקט משום שהוא לא היה שם.
 *
 * ‎`propertyEvaluable` הוא מה שמפריד „חסר בנכס” מ„הקונה לא ביקש”:
 * מה שהנכס **כן** מסוגל לספק והקריטריון בכל זאת נעדר — הקונה לא
 * ביקש, ואין מה להציג. ראו `propertyEvaluableCriteria`, שמחשב
 * זאת מהמנוע עצמו ולא מרשימת תנאים מקבילה.
 *
 * הפרמטר **חובה** בכוונה: בלעדיו כל קורא היה מכריע את ההבחנה הזו
 * בשתיקה, וזה בדיוק מה שקרה בגרסה הקודמת.
 */
export function matchChips(
  breakdown: readonly ScoreComponent[],
  propertyEvaluable: ReadonlySet<MatchCriterion>,
): MatchChip[] {
  const byCriterion = new Map<MatchCriterion, ScoreComponent>();
  for (const part of breakdown) byCriterion.set(part.criterion, part);

  const chips: MatchChip[] = [];
  for (const criterion of MATCH_CRITERIA) {
    const part = byCriterion.get(criterion);
    const label = MATCH_CRITERION_LABELS[criterion];
    if (part === undefined) {
      /*
       * הנכס מסוגל לקריטריון הזה, והוא בכל זאת לא נבחן — כלומר
       * הקונה לא ביקש אותו. אין פער, ואין צ'יפ.
       */
      if (propertyEvaluable.has(criterion)) continue;
      chips.push({
        tone: "missing",
        /*
         * נוקב **איפה** חסר, כי זו כל הפעולה: „לא נבדק: שטח”
         * שולח לחפש, ו„חסר בנכס: שטח” שולח לשדה.
         */
        label: `חסר בנכס: ${label}`,
        criterion,
        weight: DEFAULT_MATCH_WEIGHTS[criterion],
      });
      continue;
    }
    if (part.score >= FULL) {
      chips.push({ tone: "matched", label, criterion, weight: part.weight });
      continue;
    }
    /*
     * ההערה מנוסחת במנוע („רחוק מכל אזורי החיפוש”), ולכן היא מדויקת
     * יותר מכל ניסוח שנמציא כאן. כשאין — התווית לבדה, בלי להמציא
     * סיבה שאיננו יודעים.
     */
    chips.push({
      tone: "partial",
      label: part.note ?? label,
      criterion,
      weight: part.weight,
    });
  }

  const order: Record<MatchChipTone, number> = { matched: 0, partial: 1, missing: 2 };
  return chips.sort((a, b) => order[a.tone] - order[b.tone] || b.weight - a.weight);
}
