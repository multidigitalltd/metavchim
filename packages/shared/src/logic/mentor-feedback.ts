/**
 * ‎**כשסוכן עומד ביעד השבועי — והמנהל שלו יודע לומר על כך משהו.**
 *
 * ## הבעיה שהקובץ הזה פותר, והיא אינה טכנית
 *
 * ‏מנהל משרד יודע להגיד „כל הכבוד”. מה שאין לו הוא **הרגע** ו**המידע**:
 * הוא לא יודע ביום שלישי שסוכן סגר את השבוע שלו, וכשהוא כן שומע —
 * זה כבר בישיבת צוות שבועיים אחר כך, ואז זה מרגיש כמו סעיף בפרוטוקול.
 *
 * ‎**מחקר על משוב במקום עבודה חוזר על אותה נקודה: מה שמשנה הוא
 * הספציפיות והקרבה בזמן.** „עבודה יפה” אחרי חודש אינו עושה דבר;
 * „ראיתי שסגרת את השבוע עם 42 שיחות” באותו יום — כן.
 *
 * ## שלוש ההכרעות
 *
 * ‎**1. ההודעה נושאת את המספרים.** היא אינה אומרת „דנה הגיעה ליעד”
 * אלא מה בדיוק היא עשתה. מנהל שקורא מספר יכול להגיב עליו; מנהל
 * שקורא כותרת יכול רק לאשר אותה.
 *
 * ‎**2. יש משפטים מוכנים, והם אינם קיצור דרך אלא התגברות על החסם
 * האמיתי.** מנהל שצריך *לחבר* טקסט לא יכתוב — הוא ידחה את זה
 * ל„אחר כך” שלא יגיע. שלושה משפטים בלחיצה, ושדה חופשי למי שרוצה.
 * המשפטים מנוסחים סביב **הפעולה** ולא סביב האדם: „מה שעשית השבוע”
 * ולא „אתה סוכן טוב” — שבח על תכונה מייצר פחד לאבד אותה, ושבח על
 * מאמץ מייצר עוד מאמץ.
 *
 * ‎**3. שתיקה אינה נשלחת.** אם המנהל לא כתב כלום, הסוכן אינו מקבל
 * „המנהל שלך ראה שהגעת ליעד ולא אמר דבר”. אין הודעה — אין נזק.
 */

import type { NotificationCopy } from "./notifications.js";

/** ‏האורך המרבי של פידבק. אותו גבול כמו „מה עצר אותך” ביעד. */
export const FEEDBACK_MAX_LENGTH = 400;

/** סוג ההתראה שנשלחת למנהל. */
export const GOAL_REACHED_NOTIFICATION_TYPE = "mentor_goal_reached";
/** סוג ההתראה שנשלחת לסוכן כשהמנהל הגיב. */
export const FEEDBACK_NOTIFICATION_TYPE = "mentor_feedback";

/**
 * ‎**מפתח הייחודיות של ההתראה למנהל.**
 *
 * ‏שילוב של הסוכן, השבוע והמנהל — כדי ששני מנהלים יקבלו כל אחד
 * הודעה אחת, ואותו מנהל לא יקבל שתיים על אותו שבוע. האילוץ במסד
 * הוא שמכריע, ולכן הסורק אינו צריך לקרוא לפני שהוא כותב.
 */
export function goalReachedDedupeKey(
  agentUserId: string,
  weekKey: string,
  managerUserId: string,
): string {
  return `mentor_goal:${agentUserId}:${weekKey}:${managerUserId}`;
}

export interface GoalReachedInput {
  /** ‏שם הסוכן כפי שהמנהל מכיר אותו. */
  agentName: string;
  /** ‏אחוז הביצוע — 100 ומעלה. */
  percent: number;
  /** ‏מה שהוא התחייב לו ומה שעשה, לפי פעולה. */
  lines: { label: string; committed: number; actual: number }[];
}

/**
 * ‎**ההודעה למנהל — עם המספרים, לא רק עם הבשורה.**
 *
 * ‏„דנה עמדה ביעד השבועי” היא כותרת שאפשר רק לאשר. „דנה סגרה את
 * השבוע: 42 שיחות מתוך 40, 6 פגישות מתוך 5” היא משהו שאפשר להגיב
 * עליו — וזה ההבדל בין התראה לבין פתח לשיחה.
 */
export function goalReachedCopy(input: GoalReachedInput): NotificationCopy {
  const detail = input.lines
    .map((l) => `${l.label} ${l.actual}/${l.committed}`)
    .join(" · ");
  return {
    title: `${input.agentName} סגר/ה את היעד השבועי`,
    body:
      detail === ""
        ? `${input.percent}% ביצוע השבוע.`
        : `${detail}. זה הרגע להגיד על זה משהו — לוקח שנייה, ונשאר לשבוע שלם.`,
  };
}

/** ‏ההודעה שהסוכן מקבל כשהמנהל כתב לו. */
export function feedbackCopy(managerName: string, text: string): NotificationCopy {
  return {
    title: `${managerName} כתב/ה לך על השבוע`,
    body: text,
  };
}

/**
 * ‎**משפטים מוכנים — סביב הפעולה, לא סביב האדם.**
 *
 * ‏„אתה סוכן מעולה” הוא שבח על תכונה, והוא מייצר פחד לאבד אותה:
 * מי שהוא „מעולה” מפסיד משהו בכל שבוע פחות טוב. „מה שעשית השבוע”
 * הוא שבח על מאמץ, והוא מייצר עוד מאמץ — כי המאמץ הוא מה שנראה.
 *
 * ‏שלושה ולא עשרה: רשימה ארוכה הופכת לבחירה, ובחירה היא בדיוק
 * החיכוך שגורם למנהל לדחות את זה.
 */
export const FEEDBACK_SUGGESTIONS: readonly string[] = [
  "ראיתי את המספרים של השבוע — עבודה עקבית, בדיוק ככה זה נבנה.",
  "סגרת שבוע מלא. זה לא מובן מאליו, ושמתי לב.",
  "המספרים השבוע מדברים בעד עצמם. תמשיך בקצב הזה.",
];

/**
 * ‏ניקוי וּולידציה של פידבק שהמנהל כתב.
 *
 * ‎`null` פירושו „אין מה לשלוח” — טקסט ריק אינו הודעה, ואסור
 * שייצור אצל הסוכן התראה שאין בה דבר.
 */
export function cleanFeedback(raw: string): string | null {
  const text = raw.trim().replace(/\s+/gu, " ");
  if (text === "") return null;
  return text.slice(0, FEEDBACK_MAX_LENGTH);
}
