/**
 * ‎**משפטי מוטבציה — של מי שכותב אותם, לא של המערכת.**
 *
 * ## מה השתנה כאן, ולמה
 *
 * ‏בגרסה הראשונה ישבה כאן רשימה סגורה של חמישה-עשר משפטים שהמערכת
 * בחרה. היא נמחקה. הסיבה אינה טכנית: משפט מוטבציה עובד כשהוא בקול
 * שהמתווך מזהה — של מנהל המשרד שלו, של מי שהכניס אותו למקצוע — ולא
 * בקול של תוכנה. רשימה שהגיעה עם הקוד היא רשימה שאיש לא בחר, וכזו
 * הופכת אחרי שבוע לרעש שגוללים מעליו.
 *
 * ‏לכן המשפטים נכתבים עכשיו בשני מקומות: הפלטפורמה כותבת את מה
 * שמשותף לכל המשרדים, וכל משרד מוסיף את שלו. שניהם מוצגים באותו
 * סליידר, ומשרד שלא כתב דבר רואה את של הפלטפורמה.
 *
 * ## מה נשאר כאן
 *
 * ‏רק **הכללים**. גבולות האורך הם אותם גבולות שבעמודות המסד ולא
 * מספרים שנבחרו פעמיים, הניקוי זהה בשרת ובדפדפן, וסדר התצוגה מוכרע
 * במקום אחד — כדי שהסליידר, ה-API והבדיקות לא יחלקו על מה בא אחרי
 * מה.
 */

import { jerusalemWallParts } from "./israel-time.js";

/** ‏אורך המשפט. מעבר לזה זה כבר פסקה, ופסקה אינה נקראת בסליידר. */
export const QUOTE_MAX_LENGTH = 240;

/** ‏„מי אמר”. שם ומקור, לא ביוגרפיה. */
export const QUOTE_AUTHOR_MAX_LENGTH = 80;

/**
 * ‏כמה משפטים מותר בכל היקף.
 *
 * ‏הגבול אינו טכני: סליידר עם מאתיים משפטים אינו סליידר אלא ארכיון,
 * ומשרד שהגיע לגבול צריך למחוק את מה שכבר לא מדבר אליו — וזו בדיוק
 * ההחלטה שמשאירה את הרשימה חיה.
 */
export const QUOTE_LIMIT_PER_SCOPE = 60;

/**
 * ‏מי כתב את המשפט.
 *
 * ‎`platform` — הפלטפורמה, ומוצג בכל המשרדים.
 * ‎`office` — המשרד הזה, ומוצג רק בו.
 */
export type QuoteScope = "platform" | "office";

export interface MentorQuote {
  id: string;
  text: string;
  /**
   * ‏מי אמר. **מחרוזת ריקה היא תשובה לגיטימית** — משרד שכתב משפט
   * משלו אינו חייב לייחס אותו לאיש, ו„— לא ידוע” מתחת למשפט שמנהל
   * המשרד חיבר בעצמו הוא שקר קטן שאין בו צורך.
   */
  author: string;
  scope: QuoteScope;
}

/**
 * ‏ניקוי המשפט עצמו.
 *
 * ‎`null` פירושו „אין מה לשמור”: שורה ריקה אינה משפט, ומשפט ריק
 * בסליידר הוא שקופית לבנה שהמשתמש חושב שהיא באג.
 *
 * ‏שורות חדשות מתקפלות לרווח ולא נשמרות: הסליידר מציג שורה אחת
 * מרכזית, וירידת שורה שנשמרה הייתה שוברת אותה במקום אקראי.
 */
export function cleanQuoteText(raw: string): string | null {
  const text = raw.trim().replace(/\s+/gu, " ");
  if (text === "") return null;
  return text.slice(0, QUOTE_MAX_LENGTH);
}

/** ‏ניקוי „מי אמר”. ריק נשאר ריק — ראו את ההערה על `author`. */
export function cleanQuoteAuthor(raw: string): string {
  return raw.trim().replace(/\s+/gu, " ").slice(0, QUOTE_AUTHOR_MAX_LENGTH);
}

/**
 * ‎**סדר התצוגה: המשרד לפני הפלטפורמה.**
 *
 * ‏מי שכתב את המשפט קרוב יותר למי שקורא אותו. משפט שמנהל המשרד
 * ניסח לצוות שלו אמור להופיע לפני משפט כללי, ולא להיבלע בתוכו.
 *
 * ‏בתוך כל היקף נשמר הסדר שבו הגיעו — הכרעת הסדר היא של מי שכתב.
 */
export function orderQuotes(quotes: readonly MentorQuote[]): MentorQuote[] {
  return [
    ...quotes.filter((q) => q.scope === "office"),
    ...quotes.filter((q) => q.scope === "platform"),
  ];
}

/**
 * ‎**באיזה משפט נפתח היום.**
 *
 * ‏סליידר שנפתח תמיד על הראשון הופך את המשפט הראשון לרקע: אחרי
 * שבוע העין מדלגת עליו, ושאר הרשימה קיימת רק למי שילחץ. נקודת
 * הפתיחה נגזרת מהתאריך בירושלים, ולכן היא **יציבה בתוך היום** — מי
 * שרענן את המסך רואה את אותו משפט, ולא הגרלה חדשה בכל טעינה — אבל
 * מחר תהיה אחרת.
 *
 * ‏זה גם מה שמאפשר לחשב אותה בשרת ובדפדפן בלי שהן יחלקו: אין כאן
 * ‎`Math.random`, ולכן אין הבדל בין מה שהשרת צייר למה שהדפדפן צייר.
 */
export function dailyQuoteIndex(count: number, at: Date): number {
  if (count <= 0) return 0;
  const digits = jerusalemWallParts(at).date.replace(/-/gu, "");
  return Number(digits) % count;
}
