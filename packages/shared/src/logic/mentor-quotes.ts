/**
 * ‎**משפטי מוטבציה — עם מי שאמר אותם.**
 *
 * ## הכלל היחיד שקובע מה נכנס לכאן
 *
 * ‎**ציטוט בלי מקור אמיתי הוא המצאה.** משפטי מוטבציה הם התחום שבו
 * ייחוס שגוי הוא הנורמה: אותו משפט עצמו מיוחס ברשת לאיינשטיין,
 * לגנדי ולמנדלה, ואף אחד מהם לא אמר אותו. מתווך שיצטט כאן משהו
 * בפני לקוח וייתפס בטעות — המערכת עשתה לו נזק, לא טובה.
 *
 * ‏לכן כל שורה כאן היא אחת משתיים:
 *
 * ‎**1. מקור שאפשר לפתוח ולבדוק** — פרק ופסוק בתנ״ך, מסכת ודף
 * בתלמוד, משנה בפרקי אבות. אלה רוב הציטוטים כאן, וזו אינה בחירה
 * דתית אלא בחירה של **בדיקוּת**: לאף ציטוט אחר אין כתובת מדויקת
 * כל כך.
 *
 * ‎**2. ייחוס מסורתי שמסומן ככזה** — „מיוחס ל…” או „פתגם עברי”.
 * המילה „מיוחס” היא הודאה, ולא קישוט: היא אומרת שהמשפט נקשר לאדם
 * הזה במסורת רחבה אך בלי מקור ראשוני שאפשר להצביע עליו.
 *
 * ‏שער בודק שכל ציטוט נושא מקור, ושהיחס בין השניים לא מיטשטש.
 *
 * ## למה חמש המשפחות האלה
 *
 * ‏הן נבחרו לפי מה שמפיל מתווך בפועל, ולא לפי חלוקה ספרותית:
 * ‏**חזון** כשהיעד רחוק, **רצון** כשאין חשק להתחיל, **אמונה**
 * כשהשוק שקט, **ביטחון** אחרי „לא” ברצף, ו**השתדלות** כשהתוצאה
 * מאחרת אף שהעבודה נעשתה. השורה שמתחת לכל משפחה היא שלי — היא
 * מחברת את המשפחה לעבודה, וכתובה בלשון המנטור ולא בלשון הציטוט.
 */

