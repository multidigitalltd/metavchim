/**
 * ‎**שיחות המנטור — איפה אחת נגמרת והבאה מתחילה.**
 *
 * ‏עד כה השיחה הייתה רשימה שטוחה אחת לכל מתווך: כל מה שנאמר אי פעם,
 * ‏בזה אחר זה. זה עבד כל עוד המסך הציג את ארבעים האחרונים, ונשבר
 * ‏ברגע שביקשו „לחזור לשיחה מלפני שבוע” — כי לא היה מה לחזור אליו.
 * ‏„שיחה” לא הייתה ישות.
 *
 * ‏הקובץ הזה הוא ההגדרה של הישות הזו, והוא יושב ב-shared ולא בשרת
 * ‏כדי שיהיה **נבדק**: שאלת „האם זו אותה שיחה” נשאלת בשלושה מקומות
 * ‏(כתיבת הודעה חדשה, ההגירה שמחלקת את מה שכבר נכתב, והמסך שמקבץ),
 * ‏ושלושה עותקים של אותו כלל מסכימים רק כל עוד איש לא נגע.
 */

/**
 * ‎**כמה שקט הופך שיחה לשיחה קודמת.**
 *
 * ‏שש שעות ולא עשרים וארבע, ולא חצי שעה. הפסקת צהריים באמצע שיחה
 * ‏אינה מתחילה נושא חדש; לחזור בערב אל מה ששאלת בבוקר — כן. הגבול
 * ‏הוא היום העסקי, לא היממה.
 *
 * ‏מספר אחד ולא שניים: אותו כלל בדיוק מחלק את מה שכבר נכתב במסד
 * ‏(ההגירה) ואת מה שייכתב מחר (השירות). שני מספרים היו נפרדים ביום
 * ‏שאחד מהם זז, וההיסטוריה הייתה מתחלקת אחרת ממה שנכתב.
 */
export const MENTOR_THREAD_GAP_MS = 6 * 60 * 60 * 1000;

/**
 * ‏האם ההודעה הבאה פותחת שיחה חדשה.
 *
 * ‎`previousAt === null` הוא המתווך שמדבר עם המנטור בפעם הראשונה —
 * ‏אין למה להצטרף, ולכן זו שיחה חדשה. זה נאמר במפורש ולא נופל
 * ‏במקרה מהחישוב, כי „אין קודמת” ו„הקודמת רחוקה” הם אותו מצב רק
 * ‏אחרי שמחליטים שהם.
 */
export function mentorStartsNewThread(
  previousAt: Date | null,
  at: Date,
  gapMs: number = MENTOR_THREAD_GAP_MS,
): boolean {
  if (previousAt === null) return true;
  return at.getTime() - previousAt.getTime() > gapMs;
}

/** ‏אורך הכותרת ברשימת ההיסטוריה — שורה אחת ברוחב הרייל. */
export const MENTOR_THREAD_TITLE_MAX = 60;

/**
 * ‎**הכותרת נגזרת ולא נשמרת.**
 *
 * ‏שם השיחה הוא מה ששאלו בה ראשון, מקוצר. הוא אינו עמודה במסד
 * ‏ובכוונה: כותרת שמורה יכולה לחלוק על השיחה שהיא מתארת — נערכה,
 * ‏נמחקה הודעה, השתנה הכלל — וכותרת נגזרת אינה יכולה.
 *
 * ‏שורות חדשות מתקפלות לרווח: הכותרת היא שורה אחת ברשימה, וטקסט
 * ‏רב-שורות היה שובר את הפריסה או נחתך באמצע מילה בלי שהוא נראה
 * ‏חתוך.
 */
export function mentorThreadTitle(
  firstUserText: string | null,
  max: number = MENTOR_THREAD_TITLE_MAX,
): string {
  const flat = (firstUserText ?? "").replace(/\s+/gu, " ").trim();
  if (flat === "") return "שיחה ללא שאלה";
  if (flat.length <= max) return flat;
  /* ‏חיתוך בגבול מילה כשיש אחד קרוב — „מה המצ…” קורא רע */
  const cut = flat.slice(0, max);
  const space = cut.lastIndexOf(" ");
  return `${(space > max * 0.6 ? cut.slice(0, space) : cut).trimEnd()}…`;
}
