/**
 * ‎**„עקוב” — מה שקורה כשאין לך מה להציע היום, בשני הכיוונים.**
 *
 * ## הבעיה שהקובץ הזה פותר
 *
 * ‏רשת השיתופים מציגה שני סוגי ביקושים: כאלה שיש לך נכס עבורם,
 * וכאלה שאין. הראשונים הם עבודה — כפתור „הצע נכס זה” ולחיצה אחת.
 * ‏**השניים לא היו כלום.** מתווך קרא אותם, ראה שאין לו מה להציע,
 * וזה נגמר שם — גם כשהנכס שהיה מתאים בדיוק נכנס למאגר שלו שבוע
 * אחר כך. איש לא חוזר לגלול ביקושים ישנים כדי לבדוק.
 *
 * ‏המעקב הופך את הביקוש הזה מ„אין לי מה לעשות” ל„אני אדע”: הסורק
 * בודק כל יום את הנכסים החדשים של העוקב מול הביקושים שהוא עוקב
 * אחריהם, ושולח התראה כשנכנס נכס שמתאים.
 *
 * ## שלוש ההכרעות
 *
 * ‎**1. המעקב הוא של האדם, לא של המשרד.** סוכן שלחץ הוא זה שיקבל
 * את ההתראה. מעקב משרדי היה שולח לכל הצוות התראה על נכס שרק אחד
 * מהם עוסק בו, ואחרי שבוע כולם היו מכבים התראות.
 *
 * ‎**2. התראה אחת לכל צמד (מעקב, נכס).** נכס שנכנס ומתאים מייצר
 * הודעה אחת. עדכון של אותו נכס למחרת אינו מייצר שנייה — האילוץ
 * במסד הוא שמכריע, ולכן הסורק אינו צריך לקרוא לפני שהוא כותב.
 *
 * ‎**3. אותו סף כמו הכרטיס.** ‏`NETWORK_MATCH_MIN_SCORE` הוא מה
 * שמכריע גם מה נספר כ„הנכסים שלך שמתאימים” בכרטיס וגם מה מפעיל
 * את ההתראה. שני ספים היו יוצרים את הסתירה הגרועה ביותר: כרטיס
 * שאומר „מתאים” לצד התראה שלא הגיעה.
 */

