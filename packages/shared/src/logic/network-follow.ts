/** ‏סוג ההתראה שנשלחת לעוקב כשנכנס קונה מתאים. */
export const LISTING_MATCH_NOTIFICATION_TYPE = "coop_listing_match";

/**
 * ‎**מפתח הייחודיות של ההתראה.**
 *
 * ‏המעקב והקונה — ולא הנכס והקונה: שני סוכנים באותו משרד יכולים
 * ‏לעקוב אחרי אותו נכס, וכל אחד מהם אמור לקבל את ההודעה שלו.
 * ‏אותה סמנטיקה בדיוק כמו בכיוון הביקושים.
 */
export function listingMatchDedupeKey(followId: string, buyerId: string): string {
  return `coop_listing_follow:${followId}:${buyerId}`;
}

export interface ListingMatchCopyInput {
  /** ‏הנכס כפי שהמסך מתאר אותו — „דירת 4 חדרים בחולון”. */
  listingLabel: string;
  /** ‏הקונה שנכנס והתאים. השם הוא **של הלקוח שלי**. */
  buyerName: string;
  /** ‏ציון ההתאמה, 0–100. */
  score: number;
}

/**
 * ‎**ההודעה לעוקב — עם שני הצדדים, ולא רק עם הבשורה.**
 *
 * ‏„נמצאה התאמה לנכס שאתה עוקב אחריו” מחייב לפתוח את המסך כדי
 * ‏לדעת על מה מדובר. „רונית לוי מתאימה ב-88% לדירת 4 חדרים
 * ‏בחולון” היא משהו שאפשר להחליט עליו מהטלפון.
 *
 * ‎**השם שבהודעה הוא של הלקוח שלי**, לא של איש מהמשרד השני: זו
 * ‏התראה על הקונה שנכנס אליי, והנכס מתואר בדיוק באותם פרטים
 * ‏שהפיד כבר מציג לי. אין כאן פרט שלא היה גלוי לי קודם.
 */
export function listingMatchCopy(input: ListingMatchCopyInput): NotificationCopy {
  return {
    title: `קונה שלך מתאים לנכס שאתה עוקב אחריו`,
    body: `${input.buyerName} — ${input.score}% התאמה ל${input.listingLabel}. אפשר להציע אותו עכשיו.`,
  };
}

/**
 * ‎**הנכס במילים — כפי שההתראה מזכירה אותו.**
 *
 * ‏אותו עיקרון כמו ב-`demandLabel`: שלושה פרטים ולא יותר, כי מה
 * ‏שנחתך בהתראה בטלפון נחתך באמצע. כאן הפרטים הם סוג, חדרים ועיר —
 * ‏**בלי רחוב ובלי מספר בית**, שממילא אינם נחשפים ברשת.
 */
export function listingLabel(listing: {
  city?: string | null;
  rooms?: number | null;
  propertyType?: string | null;
  dealType?: string | null;
}): string {
  const rooms = listing.rooms ?? null;
  /*
   * ‎**השם מגיע מ-`PROPERTY_TYPE_LABELS_HE`**, שממנו גם נגזרות
   * ‏העמודות בייצוא ובייבוא. מפה שנייה כאן הייתה מסכימה איתה ביום
   * ‏שנכתבה, ומראה „apartment” בהתראה בטלפון ביום שמישהו יוסיף סוג.
   * ‏מפתח שאינו מוכר חוזר כ„נכס”, ולא כמחרוזת באנגלית.
   */
  const labels: Readonly<Record<string, string>> = PROPERTY_TYPE_LABELS_HE;
  const type = listing.propertyType ?? "";
  const kind =
    type !== "" && Object.hasOwn(labels, type) ? (labels[type] ?? "נכס") : "נכס";
  const parts = [
    rooms === null ? kind : `${kind} ${rooms} חדרים`,
    listing.city === null || listing.city === undefined || listing.city === ""
      ? ""
      : `ב${listing.city}`,
  ].filter((part) => part !== "");
  const text = parts.join(" ");
  /* ‏שכירות היא הכיוון השני, ואסור לקרוא לה מכירה */
  return listing.dealType === "rent" ? `${text} להשכרה` : text;
}
