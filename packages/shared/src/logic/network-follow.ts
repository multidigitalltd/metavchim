/**
 * ‎**הביקוש במילים — כפי שההתראה מזכירה אותו.**
 *
 * ‏„הביקוש שאתה עוקב אחריו” מחייב לפתוח את המסך כדי לדעת על מה
 * מדובר. „קונה שמחפש 4 חדרים בחולון” הוא משהו שאפשר לזהות מיד.
 *
 * ‏שלושה פרטים ולא יותר: חדרים, עיר, וסוג עסקה כשהוא שכירות.
 * תיאור ארוך יותר לא נכנס בהתראה בטלפון, ומה שנחתך שם נחתך באמצע.
 */
export function demandLabel(demand: {
  cities: readonly string[];
  roomsMin?: number | null;
  roomsMax?: number | null;
  dealType?: string | null;
}): string {
  const min = demand.roomsMin ?? null;
  const max = demand.roomsMax ?? null;
  const rooms =
    min === null && max === null
      ? ""
      : min !== null && max !== null && min !== max
        ? `${min}–${max} חדרים`
        : `${min ?? max} חדרים`;
  const city = demand.cities[0] ?? "";
  /* ‏„קונה” בברירת מחדל; שכירות היא הכיוון השני ואסור לקרוא לו קנייה */
  const who = demand.dealType === "rent" ? "שוכר" : "קונה";
  const parts = [
    `${who} שמחפש`,
    rooms,
    city === "" ? "" : `ב${city}`,
  ].filter((part) => part !== "");
  /* ‏בלי חדרים ובלי עיר — „קונה שמחפש” לבדו אינו משפט */
  return parts.length === 1 ? who : parts.join(" ");
}

