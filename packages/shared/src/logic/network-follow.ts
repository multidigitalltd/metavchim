/**
 * ‏כמה אדם אחד יכול לעקוב אחריהם — **לכל כיוון בנפרד**.
 *
 * ‏הגבול אינו טכני אלא של תשומת לב: מי שעוקב אחרי מאתיים ביקושים
 * מקבל התראות שאינן אומרות לו דבר, ואז הוא מכבה את כולן. מספר
 * שמחייב לבחור הוא מה ששומר על ההתראה משמעותית.
 *
 * ‏אותו מספר לשני הכיוונים, ולא סכום משותף: ביקושים ונכסים הם שני
 * ‏פידים ושתי עבודות, ומי שעוקב אחרי ארבעים ביקושים אינו אמור
 * ‏לגלות שנגמרו לו המעקבים כשהוא מגיע לפיד הנכסים.
 */
export const MAX_FOLLOWS_PER_USER = 40;

/**
 * ‎**שני הכיוונים של אותה רשת.**
 *
 * ‎`demand` — עוקבים אחרי ביקוש של משרד אחר, ומקבלים התראה כשנכנס
 * ‏**נכס שלי** שמתאים לו.
 *
 * ‎`listing` — עוקבים אחרי נכס שמשרד אחר פרסם, ומקבלים התראה
 * ‏כשנכנס **קונה שלי** שמתאים לו. עד שהוא נוסף, מחצית מהרשת
 * ‏הייתה מבוי סתום: מתווך ראה נכס טוב, לא היה לו קונה באותו רגע,
 * ‏וזה נגמר שם — גם כשהקונה נכנס אליו שבוע אחר כך.
 */
export const FOLLOW_KINDS = ["demand", "listing"] as const;
export type FollowKind = (typeof FOLLOW_KINDS)[number];

/**
 * ‎**מפתח הייחודיות של ההתראה.**
 *
 * ‏המעקב והנכס — ולא הביקוש והנכס: שני סוכנים באותו משרד יכולים
 * לעקוב אחרי אותו ביקוש, וכל אחד מהם אמור לקבל את ההודעה שלו.
 */
export function demandMatchDedupeKey(followId: string, propertyId: string): string {
  return `coop_follow:${followId}:${propertyId}`;
}

