/**
 * ניקוי קוד שהודבק — **ניסוח אחד לכל קוד שעובר דרך העתקה.**
 *
 * ## למה זה קיים בנפרד
 *
 * קוד שהמשתמש מעתיק ממסך או מדואר מגיע אלינו עם לכלוך: רווחים
 * שנדבקו בהעתקה, מקף שהוא הוסיף מעצמו, וסימני כיווניות בלתי-נראים
 * שדפדפנים ותוכנות דואר משתילים בטקסט מעורב עברית-ספרות. משתמש
 * שהעתיק „123 456” והוקפץ ב„קוד שגוי” אינו מבין מה קרה — הוא רואה
 * על המסך בדיוק את מה שקיבל.
 *
 * הניקוי היה כתוב בתוך קוד ההרשמה, וקוד הקישור לוואטסאפ הוא הקוד
 * השני שעובר את אותה דרך בדיוק. עותק שני היה נפרד מהראשון ביום
 * שמישהו יגלה תו בלתי-נראה נוסף.
 */

/**
 * סימני כיווניות בלתי-נראים.
 *
 * `LRM`/`RLM`/`ALM`, ההטמעות (`LRE`…`RLO`), `PDF`, הבידוד
 * (`LRI`…`PDI`) ו-`BOM`. כולם מגיעים מהעתקה מתוך טקסט בעברית, כולם
 * ברוחב אפס, ואף אחד מהם אינו נראה למי שמדביק אותם.
 *
 * כתובים כתווי בריחה ולא כתווים עצמם — **בכוונה**. תו בלתי-נראה
 * בתוך קוד מקור אינו ניתן לביקורת: הוא נראה בדיוק כמו כלום, ועורך
 * או כלי מיזוג יכולים לבלוע אותו בלי שאיש ישים לב.
 */
const INVISIBLE = /[\u200e\u200f\u061c\u202a-\u202e\u2066-\u2069\ufeff]/gu;

/** מפרידים שהמשתמש עשוי להוסיף בעצמו: רווחים, מקפים ונקודות. */
const SEPARATORS = /[\s\-–—.·]/gu;

/** הקוד בלי הלכלוך שנדבק בדרך — בלי מפרידים ובלי תווים בלתי-נראים. */
export function stripPastedNoise(raw: string): string {
  return raw.replace(INVISIBLE, "").replace(SEPARATORS, "");
}
