import { locationNameScore, normalizeLocationName } from "./location-text.js";

/**
 * מיקום שנאמר בקול ⟵ המיקומים שקיימים בפועל במאגר המשרד.
 *
 * ## למה לא רשימת ערים
 *
 * עד כה זיהוי העיר עבד מול רשימה קשיחה של תשע-עשרה ערים בקוד. מה
 * שלא היה ברשימה פשוט לא זוהה — וזו לא הייתה שגיאה שקטה אלא **תשובה
 * שגויה שנראית נכונה**: השאלה "מי מחפש 4 חדרים בגבעתיים" החזירה
 * חמישים קונים מכל הארץ, כולל בני ברק, כי תנאי העיר מעולם לא נוסף
 * לשאילתה. המתווך רואה רשימה ארוכה ומניח שזו התשובה.
 *
 * רשימה קשיחה היא גם הבטחה שאי אפשר לקיים: בישראל מאות יישובים,
 * ולכל אחד כמה כתיבים. כל שם שנוסיף רק יזיז את הקו שמעבר לו המערכת
 * שותקת.
 *
 * ## מה במקומה
 *
 * **אוצר המילים של המשרד עצמו.** הערים שקיימות בכרטיסי הקונים הן
 * בדיוק קבוצת התשובות האפשריות — עיר שאיש לא הזין אליה קונה לעולם
 * לא תהיה תשובה נכונה לשאלה "מי מחפש שם". ההתאמה סלחנית
 * (`locationNameScore`), ולכן "גבעתיים" מוצא גם "גבעתיים " ו-"גבעתים",
 * ואין מה לתחזק: המאגר מתעדכן, אוצר המילים איתו.
 *
 * החילוץ עצמו — איזו מילה במשפט היא בכלל שם מקום — עובר ל-Gemini,
 * שמבין שפה. הקוד כאן מכריע מה מזה קיים באמת.
 *
 * ## מה שקורה כשאין התאמה
 *
 * `unmatched` אינו קישוט. מיקום שנאמר ולא נמצא הוא ההבדל בין
 * "אין קונים בגבעתיים" לבין "לא הבנתי איפה" — ובלעדיו התשובה
 * היחידה האפשרית היא להתעלם מהמיקום ולהחזיר את הכול, כלומר בדיוק
 * הבאג שהמודול הזה בא לסגור.
 */

/**
 * הסף שמעליו שם נחשב מותאם.
 *
 * ‎0.85 הוא ציון ההכלה של `locationNameScore` — "גן" בתוך "גן יבנה".
 * הוא נכלל בכוונה: מתווך שאומר "רמת השרון" צריך למצוא גם קונה
 * שנשמר תחת "רמת השרון מערב". מתחת לזה `locationNameScore` מחזיר
 * אפס בלבד, ולכן אין כאן טווח אפור.
 */
const MATCH_THRESHOLD = 0.85;

export interface ResolvedPlaces {
  /**
   * הערכים **כפי שהם שמורים במאגר** — לא הצורה הקנונית ולא מה
   * שנאמר. אלה שהולכים לשאילתה, ולכן חייבים להיות זהים למה שיושב
   * בעמודה.
   */
  matched: string[];
  /** מה שנאמר ואין לו דבר במאגר — הבסיס לתשובה כנה. */
  unmatched: string[];
}

/**
 * מיפוי שמות שנאמרו לערכים שקיימים במאגר.
 *
 * שם אחד יכול להתאים לכמה ערכים שמורים ("תל אביב" מול "תל אביב"
 * ו-"תל אביב יפו" שנשמרו בשתי צורות), וכולם נכנסים: סינון על אחד
 * מהם היה מחמיץ מחצית מהכרטיסים.
 */
export function resolvePlaces(
  spoken: readonly string[],
  vocabulary: readonly string[],
): ResolvedPlaces {
  const matched = new Set<string>();
  const unmatched: string[] = [];

  for (const name of spoken) {
    if (normalizeLocationName(name) === "") continue;
    let hit = false;
    for (const known of vocabulary) {
      if (locationNameScore(name, known) >= MATCH_THRESHOLD) {
        matched.add(known);
        hit = true;
      }
    }
    if (!hit) unmatched.push(name.trim());
  }

  return { matched: [...matched], unmatched };
}

/**
 * ניקוי אוצר המילים שמגיע מהמאגר.
 *
 * `SELECT DISTINCT unnest(cities)` מחזיר גם מחרוזות ריקות ורווחים —
 * שדה שנשמר ריק בטופס — ואלה היו מתאימים לכל שם ומזהמים את
 * `matched`. הסינון כאן ולא בשאילתה כדי שכל קורא יקבל את אותה
 * התנהגות בלי לזכור.
 */
export function cleanVocabulary(raw: readonly string[]): string[] {
  const out = new Set<string>();
  for (const value of raw) {
    const trimmed = value.trim();
    if (trimmed !== "" && normalizeLocationName(trimmed) !== "") out.add(trimmed);
  }
  return [...out];
}
