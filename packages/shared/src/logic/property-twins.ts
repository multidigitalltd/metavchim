/**
 * נכסים תואמים — **מה שהמתווך מחזיק בראש, ובשיחה נשכח.**
 *
 * ## מה זה פותר
 *
 * לקוח מתקשר על דירת 4 חדרים בשכונה מסוימת. המתווך יודע שיש לו עוד
 * שתיים כאלה במאגר — אותו סגנון, אותו טווח, לקוחות מאותו סוג — אבל
 * בזמן השיחה הוא צריך להיזכר בהן, ולעיתים קרובות הוא לא. הקישור
 * מוגדר **מראש**, ברגע שהוא רגוע, ומופיע בכרטיס כשהוא על הקו.
 *
 * ## למה הקשר סימטרי
 *
 * מי שהגדיר „ב׳ תאום לא׳” התכוון לשני הכיוונים: אלה שתי דירות
 * שמתאימות לאותו לקוח. קשר חד-כיווני היה מחייב את הסוכן להיכנס גם
 * לכרטיס ב׳ ולהגדיר שוב — ומי ששוכח (וישכח) מקבל כרטיס שמסתיר ממנו
 * מידע שהוא עצמו הזין. לכן שורה אחת לזוג, בסדר קנוני, ושני
 * הכרטיסים קוראים אותה.
 *
 * ## למה **לא** קבוצה, ולמה הקשר אינו טרנזיטיבי
 *
 * „א׳ תואם לב׳” ו„א׳ תואם לג׳” אינם אומרים „ב׳ תואם לג׳”. א׳ יכולה
 * להתאים לב׳ במחיר ולג׳ בשכונה, בעוד ב׳ וג׳ אינן דומות כלל. קבוצה
 * הייתה מסיקה קשר שאיש לא הצהיר עליו — כלומר המסך מציג ידיעה שאין
 * לו. כאן מוצג בדיוק מה שנאמר, בשני הכיוונים, ולא יותר.
 *
 * ## למה השם בקוד הוא `twins` והשם במסך הוא „נכסים תואמים”
 *
 * השם בעברית הוא זה שבאפיון, והוא נבחר על פני „תאומים” כי „תאום”
 * מבטיח זהות ואילו הקשר הזה מבטיח **התאמה ללקוח**. שינוי מקביל
 * בקוד היה נוגע ב-212 מזהים, בנתיב API ציבורי ובשמות עמודות במסד —
 * כלומר מיגרציה, לא שינוי טקסט.
 *
 * לכן הפער כאן **מכוון ומתועד**, ולא סחיפה: כל טקסט שמופנה למתווך
 * אומר „תואמים”, וכל מזהה פנימי נשאר `twin`. מי שיבצע אי-פעם את
 * המיגרציה — יסיר את הפסקה הזו.
 */

/**
 * תקרת הנכסים התואמים לנכס.
 *
 * לא מגבלה טכנית אלא מגבלת שימוש: מי שמסמן שלושים נכסים כתואמים
 * הפך את הלשונית לרשימת הנכסים, וברגע השיחה — שבשבילו זה נבנה —
 * היא כבר לא עוזרת. שתים-עשרה זה יותר ממה שאפשר להציע בטלפון.
 */
export const MAX_TWINS_PER_PROPERTY = 12;

/** אורך ההערה שמסבירה **למה** הם תואמים ("אותו בניין, קומה גבוהה"). */
export const TWIN_NOTE_MAX = 200;

/** זוג בסדר קנוני — `first` תמיד המזהה הקטן לקסיקוגרפית. */
export interface TwinPair {
  first: string;
  second: string;
}

/**
 * הסדר הקנוני של הזוג.
 *
 * הוא מה שהופך את האינדקס הייחודי למחסום אמיתי: בלעדיו „א׳,ב׳”
 * ו„ב׳,א׳” הן שתי שורות חוקיות לאותו קשר, והכרטיס היה מציג את אותו
 * נכס פעמיים — או, גרוע יותר, מסיר אחת מהן ונראה כמי שלא הסיר.
 *
 * `null` = אותו נכס בשני הצדדים. נכס אינו תאום של עצמו, וזו טעות
 * קלט ולא מקרה קצה שצריך לשתוק עליו.
 */
export function canonicalTwinPair(a: string, b: string): TwinPair | null {
  if (a === b) return null;
  return a < b ? { first: a, second: b } : { first: b, second: a };
}

/** מפתח יציב לזוג — לדה-דופליקציה ולהשוואה בצד הלקוח. */
export function twinPairKey(a: string, b: string): string | null {
  const pair = canonicalTwinPair(a, b);
  return pair === null ? null : `${pair.first}:${pair.second}`;
}

/** תקינות ההערה — הודעה בעברית או `null`. ריק הוא ערך חוקי: ההערה רשות. */
export function twinNoteRejectionReason(note: string): string | null {
  if (note.trim().length > TWIN_NOTE_MAX) {
    return `ההערה ארוכה מדי — עד ${TWIN_NOTE_MAX} תווים`;
  }
  return null;
}

/**
 * האם אפשר להוסיף עוד תאום — הודעה בעברית או `null`.
 *
 * `current` הוא מספר הנכסים התואמים **הפעילים** של הנכס. נכס שהועבר
 * לארכיון אינו נספר: אחרת סוכן ותיק היה נחסם בגלל קשרים שאינם
 * מוצגים לו ואינו יכול להסיר.
 */
export function twinLimitRejectionReason(current: number): string | null {
  if (current >= MAX_TWINS_PER_PROPERTY) {
    return `אפשר לסמן עד ${MAX_TWINS_PER_PROPERTY} נכסים תואמים לנכס. הסירו אחד כדי להוסיף אחר.`;
  }
  return null;
}

/** השדות שמהם נבנית שורת הכותרת של נכס. כולם רשות — נכס בקליטה חלקי. */
export interface PropertyHeadlineFields {
  street?: string | undefined;
  houseNumber?: string | undefined;
  neighborhood?: string | undefined;
  city?: string | undefined;
  rooms?: number | undefined;
}

/**
 * שורת הזיהוי של נכס ברשימה — "4 חדרים · הרצל 12, מרכז, רמת גן".
 *
 * החדרים ראשונים בכוונה: ברשימת נכסים של אותו משרד הכתובות דומות
 * זו לזו, ומספר החדרים הוא מה שמבדיל ביניהן בסריקה מהירה.
 *
 * נכס בלי אף שדה כתובת אינו מוצג כשורה ריקה — שורה ריקה ברשימת
 * בחירה אינה ניתנת ללחיצה מודעת.
 */
export function propertyHeadline(p: PropertyHeadlineFields): string {
  /*
   * מספר בית בלי רחוב נשמט. „12, רמת גן” אינו כתובת חלקית אלא שורה
   * שנראית כמו תקלה, ומי שקורא אותה ברשימת בחירה אינו יודע במה בחר.
   */
  const streetLine =
    p.street !== undefined && p.street !== ""
      ? [p.street, p.houseNumber].filter(Boolean).join(" ")
      : "";
  const where = [streetLine, p.neighborhood, p.city]
    .filter((part) => part !== undefined && part !== "")
    .join(", ");
  const rooms = p.rooms !== undefined ? `${p.rooms} חדרים` : "";
  return [rooms, where].filter(Boolean).join(" · ") || "נכס ללא כתובת";
}
