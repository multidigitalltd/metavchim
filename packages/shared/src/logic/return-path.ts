/**
 * חזרה למקום שממנו יצאת — בלי לפתוח דלת החוצה.
 *
 * ## מה זה פותר
 *
 * "קביעת סיור" מתחילה בכרטיס הלקוח ונגמרת בטופס הפגישה, אבל באמצע
 * מתברר שהנכס עוד לא קיים במערכת. השליחה לטופס קליטת הנכס היא
 * הפתרון הנכון — הטופס הזה כבר יודע לאמת, לפענח כתובת ולקלוט
 * בעלים, ושכפול מוקטן שלו בתוך מסך הפגישה היה נסחף ממנו תוך חודש.
 * מה שחסר הוא רק **הדרך חזרה**: אחרי השמירה, לחזור לטופס הפגישה
 * עם הנכס החדש כבר מקושר ועם הטיוטה שנכתבה עד כה.
 *
 * ## למה רשימת היתר ולא "כל נתיב פנימי"
 *
 * כתובת חזרה שמגיעה מה-URL היא קלט של מי ששלח את הקישור, לא של מי
 * שלחץ עליו. `?returnTo=https://evil.example/login` הופך את המסך
 * שלנו למגרשת: הקורבן נשמר אצלנו ומוצא את עצמו בעמוד התחברות זהה
 * של מישהו אחר — עם הכתובת שלנו בהיסטוריה כמי שהפנתה אותו.
 *
 * בדיקה של "מתחיל בלוכסן" עוצרת את זה, אבל היא עדיין מתירה להנחית
 * מישהו על **כל** מסך פנימי אחרי שמירה — למשל על מסך מחיקה עם
 * פרמטרים שנראים כאילו הוא בחר אותם. `login-return.ts` כבר הכריע
 * את השאלה הזאת בשביל `next` של ההתחברות, ומונה נתיבים; כאן אותו
 * כלל, ולכן אותו מבנה.
 *
 * היום יש יעד חזרה אחד: טופס הפגישה. מי שמוסיף יעד מוסיף שורה
 * לרשימה, וזה בדיוק הרגע שבו הוא נשאל אם הוא מתכוון לכך.
 */

/**
 * ‎**היעדים שמותר לחזור אליהם, ובאילו פרמטרים.**
 *
 * גם השאילתה בתבנית, ובכוונה צרה: היא נושאת **מזהים בלבד** —
 * `?buyerId=01HZ…&propertyId=01J0…`. הטקסט החופשי של הטופס אינו
 * עובר כאן אלא ב-`sessionStorage` (ראו `calendar/new/draft.ts`),
 * ולכן אין צורך להתיר `%`-קידוד, ואין סכנה שהערה בעברית תנפח את
 * הכתובת עד שהיא נדחית בשקט.
 */
const ALLOWED_RETURN_PATHS: readonly RegExp[] = [
  /^\/calendar\/new(\?[A-Za-z0-9_=&-]{0,200})?$/u,
];

/** התקרה קיימת כדי שנתיב חזרה לא יישא בתוכו טיוטה שלמה. */
const MAX_LENGTH = 512;

/**
 * נתיב החזרה כשהוא ברשימה, אחרת `null`.
 *
 * הקלט מוכרז `unknown` בכוונה — כמו ב-`safeLoginReturnPath`: מקורו
 * במחרוזת השאילתה, ושם הוא יכול להגיע גם כמערך
 * (`?returnTo=a&returnTo=b`). מי שיקבל כאן `string` ייאלץ להמיר
 * בכוח בכל אתר קריאה, וההמרה הזו היא בדיוק הנקודה שבה בדיקה נשמטת.
 */
export function safeReturnPath(raw: unknown): string | null {
  if (typeof raw !== "string") return null;
  if (raw === "" || raw.length > MAX_LENGTH) return null;
  return ALLOWED_RETURN_PATHS.some((pattern) => pattern.test(raw)) ? raw : null;
}

/**
 * מוסיף פרמטר לנתיב, גם כשכבר יש בו שאילתה.
 *
 * הפרדת ה-hash אינה קישוט: `withQuery("/a#b", "id", "1")` בלי הפרדה
 * היה מייצר `/a#b?id=1`, כלומר פרמטר בתוך העוגן — שאיש אינו קורא.
 */
export function withQuery(path: string, key: string, value: string): string {
  const hashAt = path.indexOf("#");
  const hash = hashAt === -1 ? "" : path.slice(hashAt);
  const body = hashAt === -1 ? path : path.slice(0, hashAt);
  const separator = body.includes("?") ? "&" : "?";
  return `${body}${separator}${encodeURIComponent(key)}=${encodeURIComponent(value)}${hash}`;
}
