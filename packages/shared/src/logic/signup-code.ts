import { stripPastedNoise } from "./pasted-code.js";

/**
 * קוד האימות שנשלח לכתובת האימייל בפתיחת משרד.
 *
 * ## למה נרמול, ולמה כאן
 *
 * הקוד עובר דרך תיבת דואר וחזרה. בדרך הוא נדבק לרווחים, למקף
 * שהמשתמש הוסיף מעצמו, ולסימני כיווניות בלתי-נראים שדפדפנים
 * ותוכנות דואר משתילים בטקסט מעורב עברית-ספרות. משתמש שהעתיק
 * „123 456” והוקפץ ב„קוד שגוי” אינו מבין מה קרה — הוא רואה על
 * המסך בדיוק את מה שקיבל במייל.
 *
 * הנרמול נעשה **גם בשרת וגם במסך**: המסך משתמש בו כדי לדעת מתי
 * הכפתור נדלק, והשרת כדי לדעת מה להשוות. שתי הכרעות שונות על אותה
 * מחרוזת היו מייצרות בדיוק את הפער שבו הכפתור פעיל והשרת דוחה.
 */

/** אורך הקוד. שינוי כאן משנה גם את ההנפקה בשרת. */
export const SIGNUP_CODE_LENGTH = 6;

/**
 * הקוד בצורתו התקנית, או `null` אם אינו קוד.
 *
 * מחזיר `null` ולא מחרוזת ריקה: „לא קוד” ו„קוד ריק” הם אותו דבר
 * למי שמקליד, אבל קוד ריק שנשלח לשרת נראה כמו ניסיון אמיתי ושורף
 * אחד מחמשת הניסיונות.
 */
export function normalizeSignupCode(raw: string): string | null {
  const stripped = stripPastedNoise(raw);
  if (stripped.length !== SIGNUP_CODE_LENGTH) return null;
  return /^\d+$/u.test(stripped) ? stripped : null;
}
