import { describe, expect, it } from "vitest";
import { parseSpokenAmountShekels } from "./spoken-amount.js";

/**
 * הצורות שנאמרות בפועל — כולל המשפט המקורי מהתקלה: "מה יש לי
 * ברמת גן עד שני מיליון" חזר בלי תקרת מחיר כי "שני מיליון" במילים
 * לא זוהה (ביקורת Codex על #172).
 */
describe("parseSpokenAmountShekels", () => {
  it.each([
    ["מה יש לי ברמת גן עד שני מיליון", 2_000_000, "שני מיליון"],
    ["עד מיליון", 1_000_000, "מיליון"],
    ["שלושה מיליון", 3_000_000, "שלושה מיליון"],
    ["מיליון וחצי", 1_500_000, "מיליון וחצי"],
    ["שני מיליון וחצי", 2_500_000, "שני מיליון וחצי"],
    ["מיליון ורבע", 1_250_000, "מיליון ורבע"],
    ["חצי מיליון", 500_000, "חצי מיליון"],
    ["רבע מיליון", 250_000, "רבע מיליון"],
    ["מיליון שש מאות", 1_600_000, "מיליון שש מאות"],
    ["שני מיליון שש מאות אלף", 2_600_000, "שני מיליון שש מאות אלף"],
    ["מיליון ומאתיים", 1_200_000, "מיליון ומאתיים"],
    ["מיליון ושמונים אלף", 1_080_000, "מיליון ושמונים אלף"],
    ["שבע מאות אלף", 700_000, "שבע מאות אלף"],
    ["מאתיים חמישים אלף", 250_000, "מאתיים חמישים אלף"],
    ["תשע מאות וחמישים אלף", 950_000, "תשע מאות וחמישים אלף"],
    ["מאה אלף", 100_000, "מאה אלף"],
    ["עשרים אלף לחודש", 20_000, "עשרים אלף"],
    ["שלושים וחמישה אלף", 35_000, "שלושים וחמישה אלף"],
  ])("%s → %d", (text, shekels, evidence) => {
    expect(parseSpokenAmountShekels(text)).toEqual({ shekels, evidence });
  });

  it.each([
    // "אלף" לבדו אינו סכום — "אלף פעמים אמרתי לו"
    "אלף פעמים אמרתי לו",
    // מספרים קטנים במילים אינם מחיר — חדרים וקומות
    "ארבעה חדרים בקומה שלישית",
    "דירת שלושה חדרים",
    "",
  ])("אין זיהוי שווא: %s", (text) => {
    expect(parseSpokenAmountShekels(text)).toBeUndefined();
  });

  it("חצי מיליון לפני מיליון גם כשהטקסט ממשיך", () => {
    expect(parseSpokenAmountShekels("תקציב של חצי מיליון בערך")).toEqual({
      shekels: 500_000,
      evidence: "חצי מיליון",
    });
  });
});
