/**
 * ‎**רמז אוצר המילים למודל התמלול — ולמה יש שניים.**
 *
 * ## מה הרמז עושה
 *
 * המונחים שמתווך אומר בכל משפט שני — „ממ״ד”, „בלעדיות”, „טאבו”,
 * „מ״ר” — הם מילים נדירות בעברית הכללית שהמודל אומן עליה, ולכן הוא
 * מחליף אותן במילה שכיחה שנשמעת דומה („ממ״ד” ⇐ „ממד”, „בלעדיות”
 * ⇐ „בעלות”). הרמז אינו מאלץ דבר: הוא מטה את ההסתברות לטובת הניסוח
 * שנכון לתחום הזה, וזה בדיוק הכלי שהמודל מציע לכך (`initial_prompt`).
 *
 * ניסוח כטקסט זורם ולא כרשימת מילים — כך זה עובד: המודל מתייחס
 * לרמז כאל **ההקשר שקדם להקלטה**, ולא כאל הוראה. לכן גם המשפט
 * הפותח שונה בין השניים, ולא רק אוצר המילים.
 *
 * ## למה זה עבר לחבילה המשותפת
 *
 * הרמז ישב בתוך `TranscriptionService` שב-API, כלומר רק ההכתבה
 * בדפדפן קיבלה אותו. **תמלול שיחות הטלפון — הצרכן שהכי זקוק לו —
 * שלח את ההקלטה בלי שום רמז.** אודיו טלפוני צר-פס ורועש הוא בדיוק
 * המקרה שבו המודל נשען על ההקשר, ושם הוא לא קיבל אותו.
 *
 * שני צרכנים לאותו שירות `/transcribe` הם הסיבה שזה כאן ולא באחד
 * מהם: מי שיוסיף צרכן שלישי ימצא את הרמז במקום שמחפשים בו.
 */

