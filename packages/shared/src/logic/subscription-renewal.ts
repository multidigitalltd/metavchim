/**
 * ‎**חידוש מנוי — מהמקום שבו המתווך כבר נמצא.**
 *
 * ## הכשל שזה מתקן
 *
 * משרד שתקופתו נגמרה קיבל בוואטסאפ משפט אחד: „חדשו אותה במסך
 * ניהול המשרד”. זו הפניה ולא פתרון — היא מניחה שהקורא יודע איזה
 * מסך, שהוא ליד מחשב, ושהוא יזכור. בפועל זה הרגע שבו לקוח מפסיק
 * לנסות, ובדיוק אצל הלקוחות שביקשו לעבוד **רק** מוואטסאפ.
 *
 * הדשבורד מזמן יודע לעשות את זה נכון: משרד שתקופתו נגמרה מתחבר,
 * ‎`billingOnly` פותח לו את נתיבי החיוב בלבד, והוא משלם וממשיך.
 * ‏לוואטסאפ לא היה מקביל — הוא פשוט נעצר.
 *
 * ## למה כפתור ולא קישור בהודעה
 *
 * פתיחת דף תשלום **מבטלת כל תשלום ממתין של המשרד** (ראו
 * ‎`BillingService.startCheckout`). לכן קישור חי שנוצר על כל הודעה
 * נכנסת היה הורג דף תשלום שבעל המשרד פתח בדפדפן באותו רגע, ומייצר
 * שורת תשלום מבוטלת לכל „היי” שנשלח.
 *
 * לחיצה על כפתור היא **בקשה מפורשת אחת** — ולכן דף תשלום אחד. זה
 * ההבדל שמאפשר לתת קישור אמיתי ולא הפניה למסך.
 */

import { describeCycle, type BillingCycle } from "./billing.js";

/**
 * כותרת כפתור החידוש.
 *
 * ‎`WA_BUTTON_TITLE_MAX` הוא 20 תווים אצל Meta, וכותרת ארוכה ממנו
 * מפילה את ההודעה **כולה** — כלומר המשרד שתקופתו נגמרה לא מקבל
 * דבר. בדיקה אוכפת את האורך.
 */
export const RENEW_BUTTON_TITLE = "חידוש המנוי";

/**
 * ‎**מה שנאמר למשרד שתקופתו נגמרה — לפי מי שקורא.**
 *
 * מי שרשאי לשלם מקבל דרך פעולה; מי שאינו רשאי מקבל את מי שכן,
 * ולא כפתור שייכשל. הנוסח אינו מתנצל ואינו מאיים: זו עובדה
 * מסחרית ומה עושים איתה.
 */
export function subscriptionEndedText(input: { mayPay: boolean }): string {
  if (!input.mayPay) {
    return (
      "תקופת המנוי של המשרד הסתיימה, ולכן אני לא יכול לעבוד כרגע.\n" +
      "החידוש נעשה על ידי מי שמנהל את החיוב במשרד — ברגע שזה קורה אני חוזר לעבוד מיד, בלי שתצטרכו לעשות שום דבר."
    );
  }
  return (
    "תקופת המנוי של המשרד הסתיימה, ולכן אני לא יכול לעבוד כרגע.\n" +
    `אפשר לחדש מכאן — לחיצה על „${RENEW_BUTTON_TITLE}” ואשלח קישור לתשלום מאובטח. מיד אחרי התשלום אני חוזר לעבוד.`
  );
}

/**
 * ‎**ההודעה שנושאת את הקישור עצמו.**
 *
 * אומרת מה נרכש ובכמה **לפני** הקישור: „לחץ כאן לתשלום” בלי סכום
 * הוא בדיוק מה שאדם זהיר אינו לוחץ עליו, ובצדק.
 */
export function renewalLinkText(input: {
  url: string;
  planName: string;
  /** מה שכתוב על המחיר — מ-`describeCyclePrice`, כולל ציון המע"מ. */
  price: string | null;
  cycle: BillingCycle;
}): string {
  const head = `חידוש ${input.planName} · חיוב ${describeCycle(input.cycle)}`;
  const priceLine = input.price === null ? "" : `\n${input.price}`;
  return (
    `${head}${priceLine}\n\n` +
    `לתשלום מאובטח:\n${input.url}\n\n` +
    "מיד אחרי התשלום אני חוזר לעבוד — אין צורך לעשות שום דבר נוסף."
  );
}

/**
 * ‎**למה אין קישור — במקום קישור שבור.**
 *
 * ‏`checkoutRejectionReason` כבר מנסח את הסיבה (מסלול שאינו נמכר
 * ‏עצמאית, מסלול בלי מחיר, סליקה שטרם הופעלה), והיא נכונה בכל
 * ‏ערוץ. מה שנוסף כאן הוא **לאן ללכת עם זה** — בלי זה המתווך יודע
 * ‏שמשהו לא עובד ואינו יודע את מי לשאול, וזה בדיוק הרגע שבו הוא
 * ‏מפסיק לנסות.
 */
export function renewalBlockedText(reason: string): string {
  return `${reason}\n\nכתבו לי „תמיכה” ואפתח פנייה, ונסגור את זה מולכם.`;
}

/**
 * שורת מצב המנוי כפי שהיא נאמרת בשיחה.
 *
 * ‏`describeSubscription` הוא המשפט שכבר מוצג בראש מסך החיוב, והוא
 * ‏מגיע מכאן **כפי שהוא**: שני ניסוחים לאותו מצב היו אומרים
 * ‏לדשבורד דבר אחד ולוואטסאפ דבר אחר, והשיחה בין השניים מתחילה
 * ‏מתרגום.
 */
export function subscriptionStatusText(input: {
  /** המשפט מ-`describeSubscription` — לא נוסח כאן מחדש. */
  statusLine: string;
  planName: string;
  cycle: BillingCycle;
  /**
   * ‏המחיר כטקסט מוכן, או `null` כשאין.
   *
   * ‎**מנוסח אצל הקורא ולא כאן**, כי רק הוא יודע על המחיר המוסכם
   * ‏למשרד (`tenantPriceOverride`). חישוב מהמחירון בלבד היה מציג
   * ‏למשרד עם מחיר מיוחד סכום שאינו שלו.
   */
  price: string | null;
  /** האם הקורא רשאי לחדש — קובע אם מוצעת פעולה או רק מידע. */
  mayPay: boolean;
}): string {
  const price = input.price;
  const lines = [
    `המסלול: ${input.planName} · חיוב ${describeCycle(input.cycle)}`,
    ...(price === null ? [] : [price]),
    input.statusLine,
  ];
  if (input.mayPay) {
    lines.push("", "אפשר לחדש מכאן בכל רגע — כתבו לי „תחדש את המנוי”.");
  }
  return lines.join("\n");
}
