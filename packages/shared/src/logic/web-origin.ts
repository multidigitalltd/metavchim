/**
 * ‎**כתובת הבסיס של המערכת — כלל אחד, לכל תהליך.**
 *
 * ‏עשרות מקומות בונים כתובת כ-`${WEB_ORIGIN}${path}`. לוכסן אחד
 * ‏בסוף הערך הופך את כולם ל-`https://host//path` — **נתיב שאינו
 * ‏קיים**, כלומר „העמוד לא נמצא” על כל קישור שהמערכת שולחת:
 * ‏בוואטסאפ, במייל ובהתראה. זה אינו באג בקישור אחד אלא בכולם בבת
 * ‏אחת, והוא נראה בדיוק כמו „הבוט מביא קישורים שבורים”.
 *
 * ## ‏למה זה חי כאן ולא ב-`env.ts` של ה-API
 *
 * ‏הנרמול **היה** שם, ב-`apps/api/src/config/env.ts` בלבד. אבל
 * ‏ההודעות שהבוט שולח נבנות ב-**Workers**, שאינם עוברים דרך
 * ‎`loadEnv()` — הם קראו `process.env["WEB_ORIGIN"]` ישירות. כלומר
 * ‏התיקון כיסה תהליך אחד משניים, והתהליך שנשאר בחוץ הוא בדיוק זה
 * ‏ששולח את הקישורים (דיווח המשתמש, פעם שנייה).
 *
 * ‏שני תהליכים שקוראים את אותו משתנה חייבים לקרוא אותו דרך אותה
 * ‏פונקציה. חבילה משותפת היא המקום היחיד ששניהם רואים.
 */

/** ‏מסיר לוכסנים עוקבים מסוף כתובת הבסיס. */
export function normalizeWebOrigin(value: string): string {
  return value.replace(/\/+$/u, "");
}

/**
 * ‎**קריאה בטוחה מהסביבה — מנורמלת, ובלי „ריק” שקט.**
 *
 * ‏הקורא ב-Workers היה `process.env["WEB_ORIGIN"] ?? ""`, ושתי
 * ‏התקלות שם שקטות באותה מידה:
 *
 * ‏לוכסן בסוף → כל קישור נוחת על 404.
 * ‏משתנה חסר → `""`, והקישור יוצא כנתיב יחסי (`/properties/123`)
 * ‏שבוואטסאפ אינו קישור בכלל.
 *
 * ‏שתיהן נראות זהה מבחוץ: הודעה יצאה, אף אחד לא הגיע. לכן חסר
 * ‏אינו מוחזר כמחרוזת ריקה אלא כ-`null`, והקורא מחליט מה לומר
 * ‏על כך — בקול.
 */
export function webOriginFromEnv(raw: string | undefined): string | null {
  const value = normalizeWebOrigin((raw ?? "").trim());
  return value === "" ? null : value;
}
