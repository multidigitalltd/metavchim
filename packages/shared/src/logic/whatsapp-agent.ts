/**
 * ‎**מי רשאי לסוכן בוואטסאפ — הכרעה אחת, לשתי נקודות הכניסה.**
 *
 * ## התקלה שזה נולד ממנה
 *
 * הזכאות נבדקה על **הודעה נכנסת** בלבד. הפקת קוד הצימוד במסך
 * ההגדרות הייתה `@AnyAuthenticated` בלי שום בדיקה, ולכן כל משתמש
 * בכל מסלול יכול היה לייצר קוד, לצמד מכשיר, ולגלות רק בהודעה
 * הראשונה שהסוכן אינו כלול אצלו. כלומר: אונבורדינג מלא לתכונה
 * שאינה נמכרת לו, קישור חי במסד שאיש לא ישתמש בו, והודעת דחייה
 * במקום שבו כבר מאוחר להסביר.
 *
 * ## למה פונקציה טהורה ולא בדיקה בכל צד
 *
 * שתי נקודות הכניסה — הצימוד והודעה נכנסת — חייבות לענות **אותה
 * תשובה**. שתי בדיקות מקבילות היו נפרדות ביום שבו אחת מהן משתנה,
 * וההפרש ביניהן הוא בדיוק החור: זכאות שנבדקת בכניסה ולא בשימוש
 * (או להפך) היא זכאות שאפשר לעקוף.
 *
 * ההכרעה כאן טהורה — היא מקבלת עובדות ומחזירה סיבה. שליפת המסלול
 * והמשתמש נשארת אצל הקורא, כי לכל צד יש כבר את הנתונים בידיים.
 *
 * ## ולמה ב-`shared` ולא במודול ההודעות
 *
 * גם **המסך** צריך את הנוסח. הוא קיבל 403 עם הודעה מדויקת והציג
 * במקומה „הפקת הקוד נכשלה — נסו שוב”: הוראה לנסות שוב על בקשה
 * שלעולם לא תצליח, במקום ההסבר שכבר היה כתוב (ביקורת Codex).
 * נוסח שיושב בצד אחד בלבד הוא נוסח שהצד השני ימציא מחדש.
 */

import { VAT_EXCLUDED_SUFFIX, formatPlanPrice } from "./plans.js";

/** למה נדחה — כל סיבה היא מצב אחר, והפעולה של המתווך שונה. */
export type WhatsappAgentDenial =
  /** המסלול של המשרד אינו כולל את הסוכן כלל */
  | "plan"
  /** המסלול כולל, אבל למשתמש הזה לא הופעל מנוי */
  | "seat";

export interface WhatsappAgentEligibility {
  /** האם המסלול של המשרד כולל את הסוכן */
  planHasAgent: boolean;
  /**
   * האם המקום מוקצה למשתמש הזה.
   *
   * ‎**כולל בעל המשרד.** קודם הוא היה מורשה אוטומטית לפי `role`,
   * ולכן לא הייתה שום דרך להעביר את המקום לסוכן אחר — הדגל שלו לא
   * נשמר בשום מקום, ולא היה מה לכבות. עכשיו זו הקצאה מפורשת:
   * ברירת המחדל היא בעל המשרד, והוא רשאי להעביר אותה.
   */
  whatsappAccess: boolean;
}

/**
 * ‎`null` = רשאי. אחרת הסיבה, לפי סדר: מסלול קודם למנוי אישי.
 *
 * הסדר אינו שרירותי — הוא מה שקובע מה המתווך יקרא. „הסוכן אינו
 * כלול במסלול” הוא מצב של המשרד, ו„לא הופעל עבורך” הוא מצב אישי
 * שיש לו פתרון בלחיצה אחת. הצגת השני כשהראשון הוא הסיבה שולחת את
 * המתווך לבקש מבעל המשרד משהו שאין לו מה לעשות איתו.
 */
export function whatsappAgentDenial(
  eligibility: WhatsappAgentEligibility,
): WhatsappAgentDenial | null {
  if (!eligibility.planHasAgent) return "plan";
  return eligibility.whatsappAccess ? null : "seat";
}

/**
 * הנוסח שהמתווך קורא — **אותו נוסח בשני הערוצים.**
 *
 * הודעת דחייה שנוסחה פעמיים נפרדת פעם אחת, והמתווך שקורא במסך
 * הסבר אחד ובוואטסאפ אחר אינו יודע איזה מהם נכון.
 */
export const WHATSAPP_AGENT_DENIAL_TEXT: Record<WhatsappAgentDenial, string> = {
  plan: "הסוכן החכם אינו כלול במסלול של המשרד.",
  seat:
    "הסוכן בוואטסאפ מוקצה כרגע לסוכן אחר במשרד. " +
    "בעל המשרד יכול להעביר אותו אליכם במסך ניהול משרד ← סוכני המשרד.",
};

/**
 * כמה סוכנים במשרד רשאים להחזיק בסוכן הוואטסאפ.
 *
 * ‎**המקום הראשון מגיע מהמסלול, לא מהמשרד.** כל מסלול שכולל את
 * הסוכן מזכה בסוכן אחד; מסלול שאינו כולל אותו מזכה באפס, ולא
 * ב„אחד שחסום” — שני המצבים נראים דומה מבחוץ והם שונים לגמרי
 * כשמשרד משדרג מסלול.
 *
 * ## שני מקורות למקומות הנוספים, ובכוונה
 *
 * ‎`granted` הוא מה שבעל הפלטפורמה העניק ידנית — עסקה, פיילוט,
 * פיצוי. `paid` הוא מספר המנויים החודשיים הפעילים. הם **נספרים
 * יחד ואינם מחליפים זה את זה**: הענקה שהייתה נמחקת ברגע שהמשרד
 * קונה מקום, או להפך, היא בדיוק הבאג שגורם למשרד לשלם על מה שכבר
 * קיבל.
 *
 * ‎**ארגומנט אחד בשם ולא שניים לפי סדר.** החתימה הקודמת קיבלה
 * „מספר מקומות נוספים” יחיד; קורא ששכח את המקומות בתשלום היה
 * מחשב מכסה נמוכה מדי וחוסם לקוח **משלם**, בלי ששום דבר ייראה
 * שבור. שם מפורש לכל מקור הוא מה שהופך את ההשמטה לגלויה.
 */
export function whatsappAgentSeats(input: {
  planHasAgent: boolean;
  /** מקומות שבעל הפלטפורמה העניק ידנית */
  granted: number;
  /** מנויים חודשיים פעילים למקום נוסף */
  paid: number;
}): number {
  if (!input.planHasAgent) return 0;
  return 1 + Math.max(0, Math.trunc(input.granted)) + Math.max(0, Math.trunc(input.paid));
}

/**
 * מצבי מקום ש**תופסים מכסה ללא תלות בתאריך.**
 *
 * ‎`past_due` נשאר בפנים במכוון, ומאותה סיבה שהשכרת מספר שנכשלה
 * אינה משחררת את המספר: ניתוק מיידי על כשל חיוב רגעי (כרטיס שפג,
 * סירוב חד-פעמי) מוציא סוכן מהעבודה באמצע יום, והכסף ממילא נגבה
 * בניסיון הבא.
 *
 * ‎**`cancelled` אינו כאן — אבל הוא כן נספר עד תום התקופה.** ראו
 * ‎`WHATSAPP_SEAT_QUOTA_STATUSES`: הוא תלוי תאריך, ולכן אינו יכול
 * לחיות ברשימה שטוחה.
 */
export const WHATSAPP_SEAT_LIVE_STATUSES = ["active", "past_due"] as const;

/**
 * ‎**מקום שבוטל ממשיך להיספר עד תום התקופה ששולמה.**
 *
 * הביטול אומר במפורש „המקום יישאר עד סוף התקופה, בלי החזר”, וכל
 * ספירות המכסה בדקו `active | past_due` בלבד — כלומר המכסה ירדה
 * ברגע הלחיצה. המשרד ראה פחות מקומות ממה ששילם עליהם, וגרוע מזה:
 * בעל משרד שכיבה מחזיק אחד כדי להעביר את המקום **ששולם** לסוכן
 * אחר נחסם בהקצאה החוזרת (ביקורת Codex).
 *
 * ולכן אי אפשר לבטא את זה ברשימת סטטוסים: המצב תלוי בזמן. הפונקציה
 * הזו מחזירה את התנאי המלא, והיא המקום היחיד שמכיר אותו.
 */
export function whatsappSeatCountsForQuota(
  seat: { status: string; currentPeriodEnd: Date | null },
  now: Date,
): boolean {
  if ((WHATSAPP_SEAT_LIVE_STATUSES as readonly string[]).includes(seat.status)) return true;
  /*
   * ‎`null` בתקופה = מעולם לא שולם (ביטול לפני תשלום), ואז אין מה
   * לספור — להבדיל מתקופה שעברה, שגם היא אינה נספרת.
   */
  return (
    seat.status === "cancelled" &&
    seat.currentPeriodEnd !== null &&
    seat.currentPeriodEnd.getTime() > now.getTime()
  );
}

/**
 * מה להציע למי שאין לו מקום — **מחיר, או „פנו אלינו”.**
 *
 * ‎`null` בשדה המחיר של המסלול אינו „טרם הוגדר”: הוא אומר שהמסלול
 * הזה אינו מוכר מקומות נוספים. הצגת כפתור קנייה שם הייתה מבטיחה
 * רכישה שאין לה מחיר, ולכן ההבחנה נשמרת עד המסך.
 */
export type WhatsappSeatOffer =
  /** אפשר לרכוש כאן ועכשיו, במחיר הזה */
  | { kind: "purchase"; monthlyAgorot: number }
  /** המסלול אינו מוכר מקומות נוספים — פנייה אנושית */
  | { kind: "contact" };

export function whatsappSeatOffer(
  planSeatMonthlyAgorot: number | null,
): WhatsappSeatOffer {
  return planSeatMonthlyAgorot !== null && planSeatMonthlyAgorot > 0
    ? { kind: "purchase", monthlyAgorot: planSeatMonthlyAgorot }
    : { kind: "contact" };
}

/**
 * הנוסח שההצעה נקראת בו — **ליד ההצעה עצמה, לא באתר הקריאה.**
 *
 * המסך עיגל את המחיר לשקלים שלמים (`Math.round(agorot / 100)`),
 * ולכן מחיר של 199.50 ₪ הוצג „200 ₪” — כלומר פרסום מחיר שאינו מה
 * שיחויב, על סכום שהעורך והסכימה מאפשרים במפורש (ביקורת Codex).
 * ‎`formatPlanPrice` כבר יודע לשמור אגורות כשיש, ולהשמיט כשאין.
 *
 * הנוסח יושב כאן ולא במסך גם מסיבה שנייה: **הסוכן בוואטסאפ אומר
 * את אותו הדבר.** מחיר שנוסח פעמיים נפרד פעם אחת, והמתווך שרואה
 * במסך סכום אחד ובוואטסאפ אחר אינו יודע מה נכון.
 *
 * ואפס אינו מקרה כאן: `whatsappSeatOffer` הוא היחיד שמייצר
 * ‎`purchase`, והוא מייצר אותו רק מעל אפס — ולכן „חינם + מע"מ”,
 * שהוא השטות ש-`formatPriceExVat` נועד למנוע, אינו נגזר מכאן.
 */
export function whatsappSeatOfferText(offer: WhatsappSeatOffer): string {
  if (offer.kind === "contact") {
    return "המסלול הנוכחי אינו כולל מקומות נוספים — פנו אלינו ונתאים.";
  }
  return (
    `מקום נוסף לסוכן במשרד: ${formatPlanPrice(offer.monthlyAgorot)} לחודש ` +
    `${VAT_EXCLUDED_SUFFIX}. פנו לבעל המשרד להוספה.`
  );
}
