import { stripPastedNoise } from "./pasted-code.js";

/**
 * קוד הקישור בין מספר וואטסאפ לחשבון — **הזהות המפורשת.**
 *
 * ## מה הבעיה שזה פותר
 *
 * הזהות בערוץ הוואטסאפ נגזרה עד כה ממספר הטלפון של השולח בלבד:
 * השוואת ספרות מול שדה `phone` של משתמש פעיל. זה עובד, וזה גם
 * הבעיה — אף אחד מעולם לא **אמר** שהמספר הזה שלו:
 *
 * - מספר שהוחזר לשוק וניתן למישהו אחר (נפוץ בישראל) פותח לבעליו
 *   החדש את כל מאגר המשרד, כל עוד השדה במערכת לא עודכן.
 * - אותו מספר אצל שני משתמשים הוכרע בשקט לפי „מי התחבר לאחרונה” —
 *   ניחוש שנרשם באזהרה ואיש אינו קורא.
 * - למתווך לא הייתה שום דרך לראות איזה מכשיר מחובר, ולא דרך לנתק.
 *
 * הקוד הופך את ההנחה להצהרה: המתווך מייצר קוד במסך, שולח אותו
 * מהמכשיר שלו, והקישור נרשם. מכאן הזהות היא **הקישור**, לא ההשוואה.
 *
 * ## למה קוד עם קידומת ולא שש ספרות
 *
 * ההודעה מגיעה לאותו צינור שמפרש פקודות בעברית. „123456” הוא גם
 * קוד תקין וגם משהו שמתווך עלול לכתוב, ואילו הקידומת הופכת את
 * הזיהוי לחד-משמעי — בלי לנחש ובלי לשרוף ניסיון על טקסט שאינו קוד.
 *
 * האלפבית מדלג על תווים שנקראים אותו דבר (`0/O`, `1/I/L`): הקוד
 * מועתק במכשיר נייד, ולעיתים מוקלד ידנית.
 */

/** בלי `0`,`O`,`1`,`I`,`L` — הם נראים אותו דבר במסך קטן. */
export const WHATSAPP_LINK_CODE_ALPHABET = "ABCDEFGHJKMNPQRSTUVWXYZ23456789";

/** אורך החלק האקראי. 31^6 ≈ 8.9·10⁸ צירופים. */
export const WHATSAPP_LINK_CODE_LENGTH = 6;

/**
 * הקידומת שהופכת את ההודעה לקוד ולא לפקודה.
 *
 * לטינית ולא עברית: היא נכתבת פעם אחת במסך והמתווך מעתיק אותה, אבל
 * מקלדת עברית שנשארה פתוחה הופכת הקלדה ידנית של אותיות לטיניות
 * לג'יבריש. הנרמול למטה סלחני לרישיות ולמפרידים בדיוק מהסיבה הזו.
 */
export const WHATSAPP_LINK_CODE_PREFIX = "MV";

/**
 * כמה זמן הקוד תקף.
 *
 * קצר יותר מקוד הכניסה (עשר דקות): שם המשתמש כבר עומד מול המסך
 * וממתין, וכאן הוא צריך לעבור למכשיר אחר, לפתוח שיחה ולהדביק.
 */
export const WHATSAPP_LINK_CODE_TTL_SECONDS = 15 * 60;

/** כמה ניסיונות שגויים לפני שהקוד נשרף. */
export const WHATSAPP_LINK_CODE_MAX_ATTEMPTS = 5;

/**
 * אחרי כמה ימים הקישור נדרש לאימות מחדש.
 *
 * לא „ליתר ביטחון”: קישור הוא מפתח קבוע למאגר שלם, ומכשיר אבוד או
 * מספר שהוחלף אינם מודיעים לנו. חצי שנה היא טווח שבו החלפת מספר
 * או מכשיר כבר קרתה בפועל אצל חלק מהמשתמשים.
 */
export const WHATSAPP_LINK_MAX_AGE_DAYS = 180;

const BODY = new RegExp(`^[${WHATSAPP_LINK_CODE_ALPHABET}]{${WHATSAPP_LINK_CODE_LENGTH}}$`, "u");

/** „MV-4F7K2Q” — הצורה שהמסך מציג ושהמתווך מעתיק. */
export function formatWhatsappLinkCode(body: string): string {
  return `${WHATSAPP_LINK_CODE_PREFIX}-${body}`;
}

/**
 * הקוד בצורתו התקנית, או `null` כשההודעה אינה קוד כלל.
 *
 * `null` ולא מחרוזת ריקה: „זו אינה הודעת קוד” היא תשובה שונה
 * לחלוטין מ„זה קוד שגוי”. הראשונה ממשיכה לפירוש הרגיל, השנייה
 * שורפת ניסיון ואומרת למתווך שהקוד לא נקלט.
 */
export function normalizeWhatsappLinkCode(raw: string): string | null {
  const stripped = stripPastedNoise(raw).toUpperCase();
  if (!stripped.startsWith(WHATSAPP_LINK_CODE_PREFIX)) return null;
  const body = stripped.slice(WHATSAPP_LINK_CODE_PREFIX.length);
  return BODY.test(body) ? body : null;
}

/**
 * אורך מרבי להודעה שנחשבת **ניסיון** קישור — קידומת, מפריד וגוף,
 * ועוד קצת סבלנות להקלדה. משפט בעברית שמתחיל ב-„MV” אינו נכנס.
 */
const ATTEMPT_MAX_LENGTH = WHATSAPP_LINK_CODE_PREFIX.length + WHATSAPP_LINK_CODE_LENGTH + 4;

/**
 * האם ההודעה **מתיימרת** להיות קוד — גם כשהיא שגויה.
 *
 * ההבחנה הזו נחוצה כי טעות הקלדה אחת (`MV-4F7K2O` במקום `…2Q`) הפכה
 * את ההודעה למשהו אחר לגמרי: שולח לא מוכר קיבל את עמוד המכירות
 * ונרשם כמתעניין, ושולח מוכר שלח את „הקוד” שלו למודל כפקודה. שניהם
 * במקום המשפט היחיד שעוזר — „הקוד אינו תקף, הפיקו חדש” (ביקורת
 * Codex).
 *
 * הקידומת היא מה שמכריע, והאורך הוא מה ששומר על „פקודה נשארת
 * פקודה”: מי שכותב משפט אמיתי לסוכן לא מגיע לכאן.
 */
export function looksLikeWhatsappLinkCode(text: string): boolean {
  const stripped = stripPastedNoise(text).toUpperCase();
  return (
    stripped.startsWith(WHATSAPP_LINK_CODE_PREFIX) && stripped.length <= ATTEMPT_MAX_LENGTH
  );
}

/**
 * הקוד פג — לפי גיל הקישור, לא לפי „מתי נכנס לאחרונה”.
 *
 * שימוש שוטף אינו ראיה: מכשיר גנוב משתמש בדיוק כמו הבעלים. מה
 * שנמדד הוא הזמן מאז שמישהו **הוכיח** שהמספר שלו.
 */
export function linkNeedsReverification(verifiedAt: Date, now: Date): boolean {
  const days = (now.getTime() - verifiedAt.getTime()) / 86_400_000;
  return days >= WHATSAPP_LINK_MAX_AGE_DAYS;
}
