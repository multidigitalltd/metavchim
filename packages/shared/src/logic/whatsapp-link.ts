/**
 * קישור `wa.me` עם טקסט מוכן.
 *
 * זה ערוץ השליחה העיקרי במערכת: לאיש קשר יש **תמיד** טלפון (שדה חובה),
 * ואימייל רק לפעמים. המתווך לוחץ, וואטסאפ נפתח עם ההודעה כתובה.
 *
 * המספר חייב להיות בפורמט בינלאומי מלא. `wa.me/0501234567` **אינו
 * עובד** — וואטסאפ מפרש את הספרות כקידומת מדינה, ו-0 אינה קידומת של
 * אף מדינה. הפונקציה הזו קיימת בעיקר בשביל התרגום הזה, שהיה חסר בכל
 * שלושת המקומות שבנו את הקישור בעצמם.
 */

/** קידומת ישראל. המערכת עברית ומיועדת לשוק הישראלי. */
const IL = "972";

/**
 * ספרות בפורמט בינלאומי, בלי `+`.
 *
 * - `+972-50-123-4567` → `972501234567`
 * - `050-1234567` → `972501234567` (0 מקומי מוחלף בקידומת)
 * - `00972501234567` → `972501234567` (חיוג בינלאומי ישן)
 *
 * מספר שכבר בא עם קידומת מדינה אחרת נשאר כפי שהוא — משרד שעובד עם
 * קונה תושב חוץ לא אמור לקבל מספר ישראלי מומצא.
 */
export function normalizePhoneForWhatsapp(phone: string): string {
  const digits = phone.replace(/\D/gu, "");
  if (digits === "") return "";
  if (digits.startsWith("00")) return digits.slice(2);
  if (digits.startsWith(IL)) return digits;
  // מספר מקומי: 0 בהתחלה הוא קידומת חיוג פנימית ואינה חלק במספר
  if (digits.startsWith("0")) return `${IL}${digits.slice(1)}`;
  /*
   * בלי 0 ובלי קידומת. בישראל זה מספר תקין שנשמר בלי האפס
   * (`50-1234567`), ואורכו 9. אורך אחר הוא כנראה מספר זר — לא נוגעים.
   */
  return digits.length === 9 ? `${IL}${digits}` : digits;
}

/** הקישור עצמו. ההודעה עוברת קידוד — היא עברית ורב-שורתית. */
export function whatsappLink(phone: string, message: string): string {
  return `https://wa.me/${normalizePhoneForWhatsapp(phone)}?text=${encodeURIComponent(message)}`;
}

/**
 * ‎**האם אפשר בכלל לשלוח וואטסאפ למספר הזה.**
 *
 * ‎`ISRAELI_PHONE` מקבל גם קווי — `+9722…` עד `+9724…`, `+9728…`,
 * ‎`+9729…` — כי שיחה נכנסת מקו נייח היא שיחה לכל דבר. אבל **הודעת
 * וואטסאפ לקו נייח אינה נכשלת ברעש**: Meta מקבלת את הבקשה, ההודעה
 * אינה מגיעה לאיש, ומבחינת המערכת „נשלח”.
 *
 * ולכן זו הבדיקה שקובעת אם יש בכלל טעם לפתוח כרטיס ולשלוח: מה
 * שאינו נייד ישראלי אינו נמען.
 */
export function canReceiveWhatsapp(phone: string): boolean {
  return /^9725\d{8}$/u.test(normalizePhoneForWhatsapp(phone));
}
