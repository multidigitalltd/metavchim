import { z } from "zod";
import { normalizePhone } from "../logic/contact-people.js";
import { PhoneSchema } from "./common.js";

/**
 * ‎**הרשמה עצמית — סכימה אחת למסך ולשרת.**
 *
 * ## הבאג שנסגר
 *
 * הטופס הוא `noValidate` — בכוונה, כדי שהודעות השגיאה יהיו בעברית
 * ולא במה שהדפדפן ממציא. המחיר היה ש-`required`, `minLength`
 * ו-`type="email"` שעל השדות **אינם עוצרים דבר**: כל מה שהוקלד נשלח
 * כמות שהוא, השרת פסל אותו בסכימה פרטית שישבה בבקר, והמסך הציג את
 * המחרוזת הכללית „קלט לא תקין” — בלי לומר איזה שדה, ובלי לומר מה
 * לתקן. לקוח שהקליד סיסמה בת שמונה תווים, או טלפון עם סוגריים, ראה
 * מסך שנכשל בלי סיבה וסגר אותו.
 *
 * זו בדיוק הצורה שכבר תועדה כאן פעמיים — `PAGE_LIMIT_MAX` מול המסך,
 * ו-`PITCH_MAX_PROPERTIES` מול הבורר: **שני צדדים של אותה שאלה
 * שהוגדרו בנפרד.** שלב האימות באותו טופס כבר עשה את הדבר הנכון
 * (`normalizeSignupCode` משותף למסך ולשרת, ולכן הכפתור נדלק בדיוק
 * כשהשרת יקבל); שלב הפרטים לא.
 *
 * הסכימה כאן היא המקור היחיד. המסך בודק בה לפני השליחה ומצביע על
 * השדה, והשרת בודק בה שוב — ולכן אין מצב שבו המסך שולח משהו שהשרת
 * יפסול בשקט.
 *
 * ‎**כל הודעה בעברית ובגוף השדה.** ההודעות האלה מוצגות למשתמש כפי
 * שהן, ולכן הן אומרות מה לתקן ולא „Invalid input”.
 */

/** מינימום הסיסמה בפתיחת חשבון — זהה לזה של החלפת סיסמה, לא של כניסה. */
export const SIGNUP_PASSWORD_MIN = 10;

/**
 * קוד מסלול — ‎`plans.code` הוא `VarChar(20)`, ולכן זו התקרה.
 *
 * הכלל היה פרטי למסך הפלטפורמה, והרשמה עצמית החזיקה חצי ממנו
 * (אורך בלי תבנית). מסלול נוצר במקום אחד בלבד, ולכן די בכלל אחד.
 */
export const PlanCodeSchema = z
  .string()
  .min(2, "קוד מסלול קצר מדי")
  .max(20, "קוד מסלול ארוך מדי")
  .regex(/^[a-z0-9_]+$/u, "קוד מסלול באותיות לטיניות קטנות, ספרות וקו תחתון");

/**
 * ‎**טלפון לא חובה, כפי שאדם מקליד אותו.**
 *
 * הרשמה החזיקה כאן תבנית פרטית — `/^[\d\-+ ]{9,20}$/` — שפסלה
 * ‎`(054) 1234567`, `054.123.4567`, רווח קשיח מהדבקה וסימן כיווניות
 * שנדבק בהדבקה מדף בעברית. כל אלה מספרים תקינים לחלוטין, וכולם
 * חזרו כ„קלט לא תקין”.
 *
 * ‎`normalizePhone` כבר יודע לקרוא את כולם, והוא זה שמייצר את
 * הפורמט שכל שאר המערכת שומרת (`UserSchema.phone` הוא `PhoneSchema`,
 * כלומר E.164). בלי הנרמול כאן נפתח משרד שהטלפון של בעליו אינו
 * בפורמט שמסך העריכה שלו עצמו דורש.
 *
 * ריק = לא הוזן, וזה תקין: השדה מסומן „לא חובה”.
 */
export const OptionalPhoneInputSchema = z
  .string()
  .trim()
  /*
   * ‎**„ריק” נקבע על מה שהוקלד, ולא על מה שיצא מהנרמול.**
   *
   * ‏`normalizePhone` מסיר כל תו שאינו ספרה, ולכן `abc`, `()` ו-`---`
   * ‏יוצאים ממנו כמחרוזת ריקה בדיוק כמו שדה שלא מולא. בדיקה על
   * ‏התוצאה הייתה מקבלת את שלושתם כ„לא הוזן טלפון”, שומרת `null`,
   * ‏ולא אומרת דבר — כלומר בדיוק הכישלון השקט שהסכימה הזו נכתבה כדי
   * ‏לסגור, רק בכיוון ההפוך (ביקורת Codex).
   *
   * ‏לכן הבדיקה על הגלם, והנרמול רק אחריה.
   */
  .max(25, "מספר הטלפון ארוך מדי")
  .refine((raw) => raw === "" || PhoneSchema.safeParse(normalizePhone(raw)).success, {
    message: "מספר טלפון ישראלי לא תקין — למשל 050-1234567",
  })
  .transform((raw) => (raw === "" ? "" : normalizePhone(raw)))
  .optional();

export const SignupInputSchema = z
  .object({
    agencyName: z.string().trim().min(2, "שם המשרד — לפחות שני תווים").max(120, "שם המשרד ארוך מדי"),
    ownerName: z.string().trim().min(2, "השם — לפחות שני תווים").max(120, "השם ארוך מדי"),
    email: z
      .string()
      .trim()
      .email("כתובת אימייל לא תקינה")
      .max(254, "כתובת האימייל ארוכה מדי"),
    phone: OptionalPhoneInputSchema,
    /*
     * אותו מינימום של החלפת סיסמה (10) ולא זה של ההתחברות (8).
     * הסיסמה הראשונה של בעל משרד היא המפתח לכל נתוני הלקוחות שלו,
     * ואין סיבה שדרישת הסף בפתיחת חשבון תהיה נמוכה מזו של החלפה.
     */
    password: z
      .string()
      .min(SIGNUP_PASSWORD_MIN, `הסיסמה חייבת להיות באורך ${SIGNUP_PASSWORD_MIN} תווים לפחות`)
      .max(200, "הסיסמה ארוכה מדי"),
    plan: PlanCodeSchema,
    /** קוד קופון — לא חובה. הנרמול והבדיקה בשרת. */
    coupon: z.string().max(40, "קוד הקופון ארוך מדי").optional(),
    /** אישור מפורש לתנאים — נדרש לפני יצירת החשבון. */
    acceptTerms: z.literal(true, {
      errorMap: () => ({ message: "יש לאשר את תנאי השימוש ומדיניות הפרטיות" }),
    }),
  })
  .strict();

export type SignupInput = z.infer<typeof SignupInputSchema>;
